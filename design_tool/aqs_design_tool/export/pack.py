CT = ZoneInfo("America/Chicago")

# Hub root (sibling of design_tool/) — optional matplotlib bridged PNGs live here
HUB_ROOT = TOOL_ROOT.parent

# Graph-driven layer views (AQS-FLOW-GRAPH-001 / render_layer_views.py)
_PFD_LAYER_FILES = (
    "pfd.svg",
    "pfd.json",
    "mfd.svg",
    "mfd.json",
)
_SLD_LAYER_MAP = (
    # pack name ← views/ name
    ("sld.svg", "efd-elec.svg"),
    ("sld.json", "efd-elec.json"),
)
_SLD_RELATED = (
    ("efd-thermal.svg", "efd-thermal.svg"),
    ("efd-thermal.json", "efd-thermal.json"),
    ("efd-ess.svg", "efd-ess.svg"),
    ("efd-ess.json", "efd-ess.json"),
)

# Optional matplotlib bridged sheets (not authority; copy-if-present only)
_MATPLOTLIB_OPTIONAL = (
    "electrical_sld.png",
    "mass_flow_pfd.png",
)


def _enabled_sector_ids(rec: SandboxRecord) -> set[str]:
    return {s.sector_id for s in rec.model.sectors if s.enabled}


def _load_graph_snapshot(pack_dir: Path) -> dict[str, Any] | None:
    snap = pack_dir / "flow_graph_snapshot.json"
    if not snap.is_file():
        if FLOW_GRAPH_JSON.is_file():
            return json.loads(FLOW_GRAPH_JSON.read_text(encoding="utf-8"))
        return None
    return json.loads(snap.read_text(encoding="utf-8"))


def _emit_pfd(
    pack_dir: Path, files: list[str], notes: list[str]
) -> None:
    """Copy graph layer PFD/MFD SVG+JSON into pack ``pfd/``."""
    out = pack_dir / "pfd"
    out.mkdir(parents=True, exist_ok=True)
    copied: list[str] = []
    missing: list[str] = []
    for name in _PFD_LAYER_FILES:
        src = FLOW_GRAPH_VIEWS / name
        if src.is_file():
            shutil.copy2(src, out / name)
            rel = f"pfd/{name}"
            files.append(rel)
            copied.append(name)
        else:
            missing.append(name)
    bridge = out / "BRIDGE.md"
    bridge.write_text(
        "\n".join(
            [
                "# PFD module — graph-driven layer views",
                "",
                "Licence: CERN-OHL-S-2.0",
                "",
                "Source: `flow_graph/views/` regenerated by "
                "`flow_graph/render_layer_views.py` from "
                "`plant_flow_graph.json` (sole topology authority).",
                "",
                "Copied:",
                *([f"- `{n}`" for n in copied] or ["- (none — views missing)"]),
                "",
                "Missing:" if missing else "Missing: (none)",
                *[f"- `{n}`" for n in missing],
                "",
                "Matplotlib `pfd_scripts` are **not** run by this module "
                "(optional `matplotlib` exporter only). No invented rates.",
                "",
            ]
        ),
        encoding="utf-8",
    )
    files.append("pfd/BRIDGE.md")
    if copied:
        notes.append(
            f"Module 'pfd': copied {len(copied)} graph layer artefact(s) "
            f"from flow_graph/views/ → pfd/."
        )
    else:
        notes.append(
            "Module 'pfd': no layer views found under flow_graph/views/; "
            "run render_layer_views.py."
        )


def _emit_sld(
    pack_dir: Path, files: list[str], notes: list[str]
) -> None:
    """Emit electrical SLD from graph EFD-elec layer (+ related EFD)."""
    out = pack_dir / "sld"
    out.mkdir(parents=True, exist_ok=True)
    copied: list[str] = []
    for dest_name, src_name in _SLD_LAYER_MAP:
        src = FLOW_GRAPH_VIEWS / src_name
        if src.is_file():
            # Pack-root aliases per AQS-UI-001 §8
            shutil.copy2(src, pack_dir / dest_name)
            files.append(dest_name)
            shutil.copy2(src, out / dest_name)
            files.append(f"sld/{dest_name}")
            copied.append(f"{src_name}→{dest_name}")
    for dest_name, src_name in _SLD_RELATED:
        src = FLOW_GRAPH_VIEWS / src_name
        if src.is_file():
            shutil.copy2(src, out / dest_name)
            files.append(f"sld/{dest_name}")
            copied.append(src_name)
    (out / "BRIDGE.md").write_text(
        "\n".join(
            [
                "# SLD module — graph-driven EFD electrical layer",
                "",
                "Licence: CERN-OHL-S-2.0",
                "",
                "`sld.svg` / `sld.json` are copies of `views/efd-elec.*` "
                "(electrical single-line view filter of the plant flow graph).",
                "Related EFD thermal/ess layers live under `sld/`.",
                "",
                "Authority: `plant_flow_graph.json` → `render_layer_views.py`.",
                "Optional matplotlib `electrical_sld.png` is **not** this "
                "module (use export module `matplotlib`).",
                "",
                "Copied:",
                *([f"- `{c}`" for c in copied] or ["- (none)"]),
                "",
            ]
        ),
        encoding="utf-8",
    )
    files.append("sld/BRIDGE.md")
    if copied:
        notes.append(
            f"Module 'sld': graph EFD-elec → sld.svg/json (+ related under sld/)."
        )
    else:
        notes.append(
            "Module 'sld': efd-elec views missing; run render_layer_views.py."
        )


def _emit_bom(
    pack_dir: Path,
    rec: SandboxRecord,
    graph: dict[str, Any] | None,
    files: list[str],
    notes: list[str],
) -> None:
    """Equipment / module roll-up from graph nodes; self-copy flags from graph."""
    enabled = _enabled_sector_ids(rec)
    rows: list[dict[str, Any]] = []
    if graph and isinstance(graph.get("nodes"), list):
        for n in graph["nodes"]:
            if not isinstance(n, dict):
                continue
            sid = n.get("sector_id") or ""
            # Include nodes whose sector is enabled in the sandbox overlay.
            # Nodes with no sector_id are included with a blank sector.
            if sid and sid not in enabled:
                continue
            mods = n.get("modules") or []
            if isinstance(mods, list):
                mods_s = ";".join(
                    str(m.get("module_id", m)) if isinstance(m, dict) else str(m) for m in mods
                )
            else:
                mods_s = str(mods)
            kw = n.get("continuous_kw")
            rows.append(
                {
                    "unit_id": n.get("unit_id") or "",
                    "sector_id": sid,
                    "class": n.get("class") or "",
                    "presence": n.get("presence") or "",
                    "enabled": n.get("enabled"),
                    "continuous_kw": "" if kw is None else kw,
                    "modules": mods_s,
                    "electrical_role": n.get("electrical_role") or "",
                    "diagram_gap": n.get("diagram_gap") or "",
                    "notes": (n.get("notes") or "").replace("\n", " "),
                }
            )
    path = pack_dir / "bom.csv"
    cols = [
        "unit_id",
        "sector_id",
        "class",
        "presence",
        "enabled",
        "continuous_kw",
        "modules",
        "electrical_role",
        "diagram_gap",
        "notes",
    ]
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=cols)
        w.writeheader()
        for r in sorted(rows, key=lambda x: (x["sector_id"], x["unit_id"])):
            w.writerow(r)
    files.append("bom.csv")

    # Self-copy flags from graph mvs (AQS-BOM-SC-001) — no invented completeness
    self_copy: dict[str, Any] = {}
    bom_doc = "docs-authority/SELF_COPY_BOM.md"
    if graph:
        mvs = graph.get("mvs") or {}
        crit = mvs.get("mvs_criteria") or {}
        if isinstance(crit.get("self_copy"), dict):
            self_copy = dict(crit["self_copy"])
            bom_doc = self_copy.get("bom_doc") or bom_doc
    # Prefer sandbox overlay flags when present
    sc_model = getattr(rec.model.mvs_criteria, "self_copy", None)
    if sc_model is not None:
        self_copy = sc_model.model_dump(mode="json")
        bom_doc = self_copy.get("bom_doc") or bom_doc

    meta = {
        "doc_id": "AQS-BOM-SC-001",
        "module": "bom",
        "source": "plant_flow_graph.json nodes + mvs.mvs_criteria.self_copy",
        "authority_doc": bom_doc,
        "row_count": len(rows),
        "enabled_sectors": sorted(enabled),
        "self_copy": self_copy,
        "note": (
            "Equipment roll-up from graph nodes only. "
            "reprap_bom_complete and Present CAD flags are not invented here; "
            "see AQS-BOM-SC-001. continuous_kw left blank when null on graph."
        ),
    }
    (pack_dir / "bom_self_copy.json").write_text(
        json.dumps(meta, indent=2) + "\n", encoding="utf-8"
    )
    files.append("bom_self_copy.json")
    notes.append(
        f"Module 'bom': bom.csv ({len(rows)} units from graph nodes; "
        f"enabled sectors only) + bom_self_copy.json (AQS-BOM-SC-001 flags)."
    )


