def _freecad_dir() -> Path | None:
    """Hub models/freecad or share models/freecad beside design_tool parent."""
    parent = TOOL_ROOT.parent
    for c in (parent / "models" / "freecad", parent / "cad" / "freecad"):
        if c.is_dir():
            return c
    return None


def _load_geometry_bridge():
    """Import graph_geometry_bridge from hub/share freecad dir."""
    import importlib.util

    fc = _freecad_dir()
    if fc is None:
        raise ImportError("freecad dir not found beside design_tool parent")
    mod_path = fc / "graph_geometry_bridge.py"
    if not mod_path.is_file():
        raise ImportError(f"graph_geometry_bridge.py missing: {mod_path}")
    spec = importlib.util.spec_from_file_location(
        "aqs_graph_geometry_bridge_pack", mod_path
    )
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load {mod_path}")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod, fc


def _emit_3d(
    pack_dir: Path,
    rec: SandboxRecord,
    graph: dict[str, Any] | None,
    files: list[str],
    notes: list[str],
    params_emitted: bool,
) -> None:
    """Emit pack ``3d/recipe.json`` + README rebuild pointer (+ hashes)."""
    out = pack_dir / "3d"
    out.mkdir(parents=True, exist_ok=True)

    if graph is None:
        notes.append(
            "Module '3d': no flow_graph_snapshot — recipe inventory skipped; "
            "see 3d/README.md for baseline rebuild only."
        )
        (out / "README.md").write_text(
            "\n".join(
                [
                    "# Pack module `3d/` — rebuild pointer (incomplete)",
                    "",
                    "Licence: CERN-OHL-S-2.0",
                    "",
                    "No `flow_graph_snapshot.json` was available at export.",
                    "Rebuild baseline from share `models/REBUILD.sh` only;",
                    "presence filter needs a graph snapshot.",
                    "",
                ]
            ),
            encoding="utf-8",
        )
        files.append("3d/README.md")
        return

    try:
        bridge, fc_dir = _load_geometry_bridge()
    except ImportError as exc:
        notes.append(f"Module '3d': bridge import failed ({exc}); pointer-only README.")
        (out / "README.md").write_text(
            "\n".join(
                [
                    "# Pack module `3d/` — bridge unavailable",
                    "",
                    "Licence: CERN-OHL-S-2.0",
                    "",
                    f"Could not load graph_geometry_bridge: {exc}",
                    "Install share/hub freecad tree beside design_tool parent.",
                    "",
                ]
            ),
            encoding="utf-8",
        )
        files.append("3d/README.md")
        return

    unit_map = None
    map_path = fc_dir / "unit_freecad_map.json"
    if map_path.is_file():
        unit_map = bridge.load_unit_map(map_path)

    params_overlay = None
    params_path = pack_dir / "params.json"
    if params_path.is_file():
        params_overlay = json.loads(params_path.read_text(encoding="utf-8"))
    elif not params_emitted:
        # Prefer sandbox overlay fields when params module was not requested
        params_overlay = {
            "scale_m": rec.model.scale_m,
            "site": rec.model.site.model_dump(mode="json"),
            "electrical": rec.model.electrical.model_dump(mode="json"),
            "scale_rules": rec.model.scale_rules.model_dump(mode="json"),
            "note": "Overlay snapshot for 3d recipe — does not rewrite params.py",
            "topology_authority": "AQS-FLOW-GRAPH-001",
        }

    recipe = bridge.build_recipe(
        graph,
        params_overlay,
        unit_map=unit_map,
        map_path=map_path if map_path.is_file() else None,
        overlay_apply_result=None,
    )
    recipe["graph_ref"] = "flow_graph_snapshot.json"
    recipe["params_overlay_ref"] = (
        "params.json" if params_path.is_file() or params_overlay else None
    )
    # Relative name-map pointer for package users (share layout)
    recipe["name_map_ref"] = "models/freecad/unit_freecad_map.json"
    if recipe.get("freecad"):
        recipe["freecad"]["name_map_ref"] = "models/freecad/unit_freecad_map.json"
        recipe["freecad"]["rebuild_sh"] = "models/REBUILD.sh"

    # Full units + presence decisions in pack recipe
    full = dict(recipe)
    full["units"] = bridge.inventory(graph)["units"]
    if "_name_map_units" in full:
        full["name_map_units"] = full.pop("_name_map_units")
    if "_presence_decisions" in full:
        if full.get("presence_filter") is not None:
            full["presence_filter"] = dict(full["presence_filter"])
            full["presence_filter"]["decisions"] = full.pop("_presence_decisions")
        else:
            full.pop("_presence_decisions", None)
    full.pop("units_sample", None)

    recipe_path = out / "recipe.json"
    recipe_path.write_text(
        json.dumps(full, indent=2) + "\n", encoding="utf-8"
    )
    files.append("3d/recipe.json")

    pf = full.get("presence_filter") or {}
    cov = full.get("name_map_coverage") or {}
    sha = (full.get("outputs") or {}).get("sha256") or {}

    readme_lines = [
        "# Pack module `3d/` — graph → FreeCAD rebuild pointer",
        "",
        "Licence: CERN-OHL-S-2.0",
        "",
        "Vessel millimetres and stream rates are not derived from the graph.",
        "Solids come from share `models/freecad/params.py` + builders",
        "(`build_plant.py`), optionally via a **forked** `params_overlay.py`",
        "(allow-listed overlay keys only). Presence filter omits or tags Features whose",
        "graph nodes are `enabled=false` or `presence=placeholder` (unless",
        "map `status=massing_only`). Logical `unmapped` units stay skip.",
        "",
        "## Artefacts",
        "",
        "| File | Role |",
        "|---|---|",
        "| `recipe.json` | `aqs-3d-recipe-1.0` inventory + presence + map gaps + optional sha256 |",
        "| `README.md` | This rebuild pointer |",
        "",
        f"- Recipe status: `{full.get('status')}`",
        f"- Presence policy: `{full.get('presence_policy')}`",
        f"- Presence emit/skip: {pf.get('emit_count')}/{pf.get('skip_count')}",
        f"- Name-map present coverage: {cov.get('present_mapped_or_massing')}/{cov.get('present_nodes')} "
        f"({cov.get('present_coverage_pct')}%)",
        f"- Baseline sha256 keys: {', '.join(sha.keys()) or '(none beside bridge at export)'}",
        "",
        "## Rebuild from this pack",
        "",
        "```bash",
        "# 0) Prerequisites: /usr/bin/freecadcmd 1.0 — see docs-authority/BUILD_3D_FROM_FLOW.md",
        "cd models/freecad",
        "",
        "# 1) Inventory + recipe (optional re-emit)",
        "python3 graph_geometry_bridge.py \\",
        "  --graph /path/to/this-pack/flow_graph_snapshot.json \\",
        "  --params /path/to/this-pack/params.json \\",
        "  --map unit_freecad_map.json \\",
        "  --out /path/to/this-pack/3d/recipe.json",
        "",
        "# 2) Safe overlay fork (never gold params.py)",
        "python3 graph_geometry_bridge.py \\",
        "  --params /path/to/this-pack/params.json --apply-overlay",
        "",
        "# 3) Baseline rebuild (params-driven catalogue)",
        "bash ../REBUILD.sh --plant-only",
        "# or: python3 graph_geometry_bridge.py --graph ... --rebuild-baseline",
        "",
        "# 4) Presence post-pass on a *copy* of plant.FCStd",
        "python3 graph_geometry_bridge.py \\",
        "  --graph /path/to/this-pack/flow_graph_snapshot.json \\",
        "  --apply-presence --fcstd plant.FCStd \\",
        "  --fcstd-out out/plant_filtered.FCStd",
        "",
        "# 5) Filter tests (no FreeCAD geometry invention)",
        "python3 graph_geometry_bridge.py --self-test",
        "```",
        "",
        "Authority: pack `flow_graph_snapshot.json` (AQS-FLOW-GRAPH-001).",
        "Protocol: `docs-authority/AGENT_CAD_PROTOCOL.md` + `FREECAD_PROTOCOL.md`.",
        "",
    ]
    (out / "README.md").write_text("\n".join(readme_lines), encoding="utf-8")
    files.append("3d/README.md")

    notes.append(
        f"Module '3d': wrote 3d/recipe.json (schema {full.get('schema')}, "
        f"status={full.get('status')}; presence emit={pf.get('emit_count')} "
        f"skip={pf.get('skip_count')}) + 3d/README.md rebuild pointer."
    )



# QA R1 (2026-10-17): pack_name was joined into EXPORTS_DIR unsanitized, so a
# name like "../../x" escaped the exports root (path-traversal finding).
# Allow only a single path segment of [A-Za-z0-9._-] starting alphanumeric,
# and require the resolved target to stay inside EXPORTS_DIR (symlink belt).
_PACK_NAME_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*")


def validate_pack_name(name: str) -> None:
    """Raise ValueError unless ``name`` is a safe single-segment pack name."""
    if _PACK_NAME_RE.fullmatch(name) is None or not (EXPORTS_DIR / name).resolve(
    ).is_relative_to(EXPORTS_DIR.resolve()):
        raise ValueError(f"invalid pack_name: {name!r}")


def export_pack(rec: SandboxRecord, req: ExportRequest | None = None) -> ExportResponse:
    req = req or ExportRequest()
    EXPORTS_DIR.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(CT).strftime("%Y%m%d_%H%M%S")
    name = req.pack_name or f"{rec.sandbox_id}_{stamp}"
    validate_pack_name(name)  # QA R1: reject before any path join / mkdir
    pack_dir = EXPORTS_DIR / name
    pack_dir.mkdir(parents=True, exist_ok=False)

    files: list[str] = []
    notes: list[str] = [
        "Export is a new pack under design_tool/exports/; locked MVS untouched.",
        "Graph snapshot included (WP-Bp4); plant_flow_graph.json not modified.",
        "Gap flags included even when sandbox is incomplete vs MVS.",
        "WP-C1: pfd/sld/bom emit from graph when requested; unused modules off; "
        "matplotlib is optional exporter only; module 3d emits recipe.",
    ]

    # WP-Bp4: always include a read-only copy of the plant flow graph
    if FLOW_GRAPH_JSON.is_file():
        dest = pack_dir / "flow_graph_snapshot.json"
        shutil.copy2(FLOW_GRAPH_JSON, dest)
        files.append("flow_graph_snapshot.json")
        notes.append(
            f"flow_graph_snapshot.json copied from {FLOW_GRAPH_JSON.name} "
            "(sole topology authority)."
        )
    else:
        notes.append(
            f"WARNING: plant flow graph missing at {FLOW_GRAPH_JSON}; "
            "pack lacks flow_graph_snapshot.json."
        )

    # MVS snapshot = graph projection (not a divergent master file)
    mvs = load_mvs_from_graph()
    (pack_dir / "mvs_snapshot.json").write_text(
        json.dumps(mvs.model_dump(by_alias=True, mode="json"), indent=2) + "\n",
        encoding="utf-8",
    )
    files.append("mvs_snapshot.json")
    notes.append(
        "mvs_snapshot.json is the graph→MVS projection at export time "
        "(candidate_mvs role = generated projection)."
    )

    design = rec.model.model_dump(by_alias=True, mode="json")
    (pack_dir / "design.json").write_text(
        json.dumps(design, indent=2) + "\n", encoding="utf-8"
    )
    files.append("design.json")

    gaps_lines = [
        "# Gaps and unclosed streams",
        "",
        f"Sandbox: `{rec.sandbox_id}`",
        f"Parent MVS revision: {rec.parent_mvs_revision}",
        "",
        "## Gaps",
        "",
    ]
    if rec.last_solve and rec.last_solve.gaps:
        for g in rec.last_solve.gaps:
            gaps_lines.append(
                f"- `{g.sector_id or '—'}` / {g.sector_definition or '—'}: "
                f"{g.reason} — {g.detail or ''}"
            )
    elif rec.model.gaps:
        for g in rec.model.gaps:
            gaps_lines.append(
                f"- `{g.sector_id or '—'}` / {g.sector_definition or '—'}: "
                f"{g.reason} — {g.detail or ''}"
            )
    else:
        gaps_lines.append("- (none recorded — run POST …/solve first)")
    gaps_lines += ["", "## Unclosed streams", ""]
    unclosed = (
        rec.last_solve.unclosed_streams
        if rec.last_solve
        else rec.model.unclosed_streams
    )
    if unclosed:
        for u in unclosed:
            gaps_lines.append(f"- `{u.stream_id}`: {u.reason}")
    else:
        gaps_lines.append("- (none recorded)")
    gaps_lines.append("")
    (pack_dir / "gaps.md").write_text("\n".join(gaps_lines), encoding="utf-8")
    files.append("gaps.md")

    enabled = [s.sector_id for s in rec.model.sectors if s.enabled]
    mods = list(req.export_modules)
    readme = f"""# Design pack `{name}`

Licence: CERN-OHL-S-2.0  
Parent MVS: {rec.parent_mvs_revision} (`doc_id` AQS-MVS-001 candidate)  
Sandbox: `{rec.sandbox_id}` ({rec.label})  
Exported: {datetime.now(CT).strftime("%Y-%m-%d %H:%M:%S CT")}

## Authority (WP-Bp4 / WP-C1)

- Topology: `flow_graph_snapshot.json` (copy of `plant_flow_graph.json`)
- MVS projection: `mvs_snapshot.json` (from graph; not a second master)
- Sandbox overlay: `design.json`
- Graph layer packs: `pfd/`, `sld.svg`/`sld.json` when modules requested
- This pack does **not** replace locked / candidate MVS or rewrite the graph.
- Matplotlib (if present under `matplotlib/`) is optional bridged export only.

## Enabled sectors

{chr(10).join("- " + s for s in enabled)}

## Modules requested

{chr(10).join("- " + m for m in mods)}

## Module map (WP-C1)

| Key | Artefacts | Source |
|---|---|---|
| (always) | flow_graph_snapshot, mvs_snapshot, design, gaps, README | graph + sandbox |
| params | params.json | sandbox overlay |
| streams | streams.csv | sandbox streams (graph-backed) |
| compliance_flags | compliance_flags.md | last solve |
| pfd | pfd/*.svg/json | flow_graph/views (graph) |
| sld | sld.svg/json + sld/ | views/efd-elec (+ thermal/ess) |
| bom | bom.csv, bom_self_copy.json | graph nodes + AQS-BOM-SC-001 flags |
| matplotlib | matplotlib/*.png | optional hub bridged PNGs |
| 3d | 3d/recipe.json, 3d/README.md | bridge + map + presence filter |
"""
    (pack_dir / "README.md").write_text(readme, encoding="utf-8")
    files.append("README.md")

    modset = set(mods)
    if "params" in modset:
        params = {
            "scale_m": rec.model.scale_m,
            "site": rec.model.site.model_dump(mode="json"),
            "electrical": rec.model.electrical.model_dump(mode="json"),
            "scale_rules": rec.model.scale_rules.model_dump(mode="json"),
            "note": "Overlay only — does not rewrite models/freecad/params.py",
            "topology_authority": "AQS-FLOW-GRAPH-001",
        }
        (pack_dir / "params.json").write_text(
            json.dumps(params, indent=2) + "\n", encoding="utf-8"
        )
        files.append("params.json")

    if "streams" in modset:
        path = pack_dir / "streams.csv"
        with path.open("w", newline="", encoding="utf-8") as fh:
            w = csv.writer(fh)
            w.writerow(
                [
                    "stream_id",
                    "from_unit_id",
                    "to_unit_id",
                    "phase",
                    "carries",
                    "rate_value",
                    "rate_unit",
                    "rate_status",
                ]
            )
            for st in rec.model.streams:
                rv = st.rate
                w.writerow(
                    [
                        st.stream_id,
                        st.from_unit_id,
                        st.to_unit_id,
                        st.phase,
                        st.carries or "",
                        "" if rv is None or rv.value is None else rv.value,
                        "" if rv is None else rv.unit,
                        "" if rv is None else rv.status.value,
                    ]
                )
        files.append("streams.csv")

    if "compliance_flags" in modset:
        flags = ["# Compliance theme flags", ""]
        if rec.last_solve:
            for cf in rec.last_solve.code_flags:
                flags.append(
                    f"- {cf.theme} ({cf.controlling}): {', '.join(cf.refs)}"
                )
        else:
            flags.append("- Run solve to populate code flags.")
        flags.append("")
        (pack_dir / "compliance_flags.md").write_text(
            "\n".join(flags), encoding="utf-8"
        )
        files.append("compliance_flags.md")

    graph = _load_graph_snapshot(pack_dir)

    if "pfd" in modset:
        _emit_pfd(pack_dir, files, notes)
    if "sld" in modset:
        _emit_sld(pack_dir, files, notes)
    if "bom" in modset:
        _emit_bom(pack_dir, rec, graph, files, notes)
    if "matplotlib" in modset:
        _emit_matplotlib(pack_dir, files, notes)

    if "3d" in modset:
        _emit_3d(
            pack_dir,
            rec,
            graph,
            files,
            notes,
            params_emitted=("params" in modset),
        )

    unknown = modset - {
        "params",
        "streams",
        "gaps",
        "compliance_flags",
        "pfd",
        "sld",
        "bom",
        "matplotlib",
        "3d",
    }
    for u in sorted(unknown):
        notes.append(f"Module '{u}' requested but not recognized; skipped.")

    return ExportResponse(
        pack_dir=str(pack_dir),
        files=files,
        notes=notes,
    )
