"""Modular design-pack export (AQS-UI-001 §8). Never overwrites locked MVS.

WP-Bp4: pack consumes a graph snapshot (plant_flow_graph.json copy) plus the
sandbox overlay. MVS gold / graph write path remain untouched.

WP-C1: optional modules ``pfd`` / ``sld`` / ``bom`` emit from the graph
snapshot (or documented layer views). ``matplotlib`` is an optional exporter
only (copies bridged hub PNGs when present). Unused modules stay off.
"""

from __future__ import annotations

import csv
import json
import shutil
from datetime import datetime
from pathlib import Path
from typing import Any
from zoneinfo import ZoneInfo

from ..api.store import SandboxRecord, load_mvs_from_graph
from ..models import ExportRequest, ExportResponse
from ..paths import EXPORTS_DIR, FLOW_GRAPH_JSON, FLOW_GRAPH_VIEWS, TOOL_ROOT

CT = ZoneInfo("America/Chicago")

# Hub root (sibling of design_tool/) — optional matplotlib bridged PNGs live here
HUB_ROOT = TOOL_ROOT.parent

# Graph-driven layer views (AQS-FLOW-GRAPH-001 / render_layer_views.py)
_PFD_LAYER_FILES = (
    "pfd.svg",
    "pfd.json",
    "mfd.svg",
    "mfd.json",
)
_SLD_LAYER_MAP = (
    # pack name ← views/ name
    ("sld.svg", "efd-elec.svg"),
    ("sld.json", "efd-elec.json"),
)
_SLD_RELATED = (
    ("efd-thermal.svg", "efd-thermal.svg"),
    ("efd-thermal.json", "efd-thermal.json"),
    ("efd-ess.svg", "efd-ess.svg"),
    ("efd-ess.json", "efd-ess.json"),
)

# Optional matplotlib bridged sheets (not authority; copy-if-present only)
_MATPLOTLIB_OPTIONAL = (
    "electrical_sld.png",
    "mass_flow_pfd.png",
)


def _enabled_sector_ids(rec: SandboxRecord) -> set[str]:
    return {s.sector_id for s in rec.model.sectors if s.enabled}


def _load_graph_snapshot(pack_dir: Path) -> dict[str, Any] | None:
    snap = pack_dir / "flow_graph_snapshot.json"
    if not snap.is_file():
        if FLOW_GRAPH_JSON.is_file():
            return json.loads(FLOW_GRAPH_JSON.read_text(encoding="utf-8"))
        return None
    return json.loads(snap.read_text(encoding="utf-8"))


def _emit_pfd(
    pack_dir: Path, files: list[str], notes: list[str]
) -> None:
    """Copy graph layer PFD/MFD SVG+JSON into pack ``pfd/``."""
    out = pack_dir / "pfd"
    out.mkdir(parents=True, exist_ok=True)
    copied: list[str] = []
    missing: list[str] = []
    for name in _PFD_LAYER_FILES:
        src = FLOW_GRAPH_VIEWS / name
        if src.is_file():
            shutil.copy2(src, out / name)
            rel = f"pfd/{name}"
            files.append(rel)
            copied.append(name)
        else:
            missing.append(name)
    bridge = out / "BRIDGE.md"
    bridge.write_text(
        "\n".join(
            [
                "# PFD module — graph-driven layer views",
                "",
                "Licence: CERN-OHL-S-2.0",
                "",
                "Source: `flow_graph/views/` regenerated by "
                "`flow_graph/render_layer_views.py` from "
                "`plant_flow_graph.json` (sole topology authority).",
                "",
                "Copied:",
                *([f"- `{n}`" for n in copied] or ["- (none — views missing)"]),
                "",
                "Missing:" if missing else "Missing: (none)",
                *[f"- `{n}`" for n in missing],
                "",
                "Matplotlib `pfd_scripts` are **not** run by this module "
                "(optional `matplotlib` exporter only). No invented rates.",
                "",
            ]
        ),
        encoding="utf-8",
    )
    files.append("pfd/BRIDGE.md")
    if copied:
        notes.append(
            f"Module 'pfd': copied {len(copied)} graph layer artefact(s) "
            f"from flow_graph/views/ → pfd/."
        )
    else:
        notes.append(
            "Module 'pfd': no layer views found under flow_graph/views/; "
            "run render_layer_views.py."
        )


def _emit_sld(
    pack_dir: Path, files: list[str], notes: list[str]
) -> None:
    """Emit electrical SLD from graph EFD-elec layer (+ related EFD)."""
    out = pack_dir / "sld"
    out.mkdir(parents=True, exist_ok=True)
    copied: list[str] = []
    for dest_name, src_name in _SLD_LAYER_MAP:
        src = FLOW_GRAPH_VIEWS / src_name
        if src.is_file():
            # Pack-root aliases per AQS-UI-001 §8
            shutil.copy2(src, pack_dir / dest_name)
            files.append(dest_name)
            shutil.copy2(src, out / dest_name)
            files.append(f"sld/{dest_name}")
            copied.append(f"{src_name}→{dest_name}")
    for dest_name, src_name in _SLD_RELATED:
        src = FLOW_GRAPH_VIEWS / src_name
        if src.is_file():
            shutil.copy2(src, out / dest_name)
            files.append(f"sld/{dest_name}")
            copied.append(src_name)
    (out / "BRIDGE.md").write_text(
        "\n".join(
            [
                "# SLD module — graph-driven EFD electrical layer",
                "",
                "Licence: CERN-OHL-S-2.0",
                "",
                "`sld.svg` / `sld.json` are copies of `views/efd-elec.*` "
                "(electrical single-line view filter of the plant flow graph).",
                "Related EFD thermal/ess layers live under `sld/`.",
                "",
                "Authority: `plant_flow_graph.json` → `render_layer_views.py`.",
                "Optional matplotlib `electrical_sld.png` is **not** this "
                "module (use export module `matplotlib`).",
                "",
                "Copied:",
                *([f"- `{c}`" for c in copied] or ["- (none)"]),
                "",
            ]
        ),
        encoding="utf-8",
    )
    files.append("sld/BRIDGE.md")
    if copied:
        notes.append(
            f"Module 'sld': graph EFD-elec → sld.svg/json (+ related under sld/)."
        )
    else:
        notes.append(
            "Module 'sld': efd-elec views missing; run render_layer_views.py."
        )


def _emit_bom(
    pack_dir: Path,
    rec: SandboxRecord,
    graph: dict[str, Any] | None,
    files: list[str],
    notes: list[str],
) -> None:
    """Equipment / module roll-up from graph nodes; self-copy flags from graph."""
    enabled = _enabled_sector_ids(rec)
    rows: list[dict[str, Any]] = []
    if graph and isinstance(graph.get("nodes"), list):
        for n in graph["nodes"]:
            if not isinstance(n, dict):
                continue
            sid = n.get("sector_id") or ""
            # Include nodes whose sector is enabled in the sandbox overlay.
            # Nodes with no sector_id are included with a blank sector (honest).
            if sid and sid not in enabled:
                continue
            mods = n.get("modules") or []
            if isinstance(mods, list):
                mods_s = ";".join(str(m) for m in mods)
            else:
                mods_s = str(mods)
            kw = n.get("continuous_kw")
            rows.append(
                {
                    "unit_id": n.get("unit_id") or "",
                    "sector_id": sid,
                    "class": n.get("class") or "",
                    "presence": n.get("presence") or "",
                    "enabled": n.get("enabled"),
                    "continuous_kw": "" if kw is None else kw,
                    "modules": mods_s,
                    "electrical_role": n.get("electrical_role") or "",
                    "diagram_gap": n.get("diagram_gap") or "",
                    "notes": (n.get("notes") or "").replace("\n", " "),
                }
            )
    path = pack_dir / "bom.csv"
    cols = [
        "unit_id",
        "sector_id",
        "class",
        "presence",
        "enabled",
        "continuous_kw",
        "modules",
        "electrical_role",
        "diagram_gap",
        "notes",
    ]
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=cols)
        w.writeheader()
        for r in sorted(rows, key=lambda x: (x["sector_id"], x["unit_id"])):
            w.writerow(r)
    files.append("bom.csv")

    # Self-copy flags from graph mvs (AQS-BOM-SC-001) — no invented completeness
    self_copy: dict[str, Any] = {}
    bom_doc = "Diagrams/aqueous_diagrams/bom/SELF_COPY_BOM.md"
    if graph:
        mvs = graph.get("mvs") or {}
        crit = mvs.get("mvs_criteria") or {}
        if isinstance(crit.get("self_copy"), dict):
            self_copy = dict(crit["self_copy"])
            bom_doc = self_copy.get("bom_doc") or bom_doc
    # Prefer sandbox overlay flags when present
    sc_model = getattr(rec.model.mvs_criteria, "self_copy", None)
    if sc_model is not None:
        self_copy = sc_model.model_dump(mode="json")
        bom_doc = self_copy.get("bom_doc") or bom_doc

    meta = {
        "doc_id": "AQS-BOM-SC-001",
        "module": "bom",
        "source": "plant_flow_graph.json nodes + mvs.mvs_criteria.self_copy",
        "authority_doc": bom_doc,
        "row_count": len(rows),
        "enabled_sectors": sorted(enabled),
        "self_copy": self_copy,
        "note": (
            "Equipment roll-up from graph nodes only. "
            "reprap_bom_complete and Present CAD flags are not invented here; "
            "see AQS-BOM-SC-001. continuous_kw left blank when null on graph."
        ),
    }
    (pack_dir / "bom_self_copy.json").write_text(
        json.dumps(meta, indent=2) + "\n", encoding="utf-8"
    )
    files.append("bom_self_copy.json")
    notes.append(
        f"Module 'bom': bom.csv ({len(rows)} units from graph nodes; "
        f"enabled sectors only) + bom_self_copy.json (AQS-BOM-SC-001 flags)."
    )


def _emit_matplotlib(
    pack_dir: Path, files: list[str], notes: list[str]
) -> None:
    """Optional: copy existing graph-bridged hub PNGs; never run draw scripts."""
    out = pack_dir / "matplotlib"
    out.mkdir(parents=True, exist_ok=True)
    copied: list[str] = []
    missing: list[str] = []
    for name in _MATPLOTLIB_OPTIONAL:
        src = HUB_ROOT / name
        if src.is_file():
            shutil.copy2(src, out / name)
            files.append(f"matplotlib/{name}")
            copied.append(name)
        else:
            missing.append(name)
    (out / "README.md").write_text(
        "\n".join(
            [
                "# Optional matplotlib exporters (demoted)",
                "",
                "Licence: CERN-OHL-S-2.0",
                "",
                "These PNGs are **optional bridged sheets** from hub "
                "`pfd_scripts/` (graph-bridged where noted in "
                "`flow_graph/LEGACY_PFD_SCRIPTS.md`). They are **not** "
                "topology authority — the pack `flow_graph_snapshot.json` "
                "and `pfd/` / `sld` graph layers are.",
                "",
                "This module only **copies** existing files; it does not "
                "invoke matplotlib or invent rates/nameplates.",
                "",
                "Copied:",
                *([f"- `{n}`" for n in copied] or ["- (none present on hub)"]),
                "",
                "Not found (skipped):",
                *([f"- `{n}`" for n in missing] or ["- (none)"]),
                "",
            ]
        ),
        encoding="utf-8",
    )
    files.append("matplotlib/README.md")
    notes.append(
        f"Module 'matplotlib' (optional): copied {len(copied)} bridged PNG(s); "
        f"skipped {len(missing)} missing. Not authority."
    )


def export_pack(rec: SandboxRecord, req: ExportRequest | None = None) -> ExportResponse:
    req = req or ExportRequest()
    EXPORTS_DIR.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(CT).strftime("%Y%m%d_%H%M%S")
    name = req.pack_name or f"{rec.sandbox_id}_{stamp}"
    pack_dir = EXPORTS_DIR / name
    pack_dir.mkdir(parents=True, exist_ok=False)

    files: list[str] = []
    notes: list[str] = [
        "Export is a new pack under design_tool/exports/; locked MVS untouched.",
        "Graph snapshot included (WP-Bp4); plant_flow_graph.json not modified.",
        "Gap flags included even when sandbox is incomplete vs MVS.",
        "WP-C1: pfd/sld/bom emit from graph when requested; unused modules off; "
        "matplotlib is optional exporter only.",
    ]

    # WP-Bp4: always include a read-only copy of the plant flow graph
    if FLOW_GRAPH_JSON.is_file():
        dest = pack_dir / "flow_graph_snapshot.json"
        shutil.copy2(FLOW_GRAPH_JSON, dest)
        files.append("flow_graph_snapshot.json")
        notes.append(
            f"flow_graph_snapshot.json copied from {FLOW_GRAPH_JSON.name} "
            "(sole topology authority)."
        )
    else:
        notes.append(
            f"WARNING: plant flow graph missing at {FLOW_GRAPH_JSON}; "
            "pack lacks flow_graph_snapshot.json."
        )

    # MVS snapshot = graph projection (not a divergent master file)
    mvs = load_mvs_from_graph()
    (pack_dir / "mvs_snapshot.json").write_text(
        json.dumps(mvs.model_dump(by_alias=True, mode="json"), indent=2) + "\n",
        encoding="utf-8",
    )
    files.append("mvs_snapshot.json")
    notes.append(
        "mvs_snapshot.json is the graph→MVS projection at export time "
        "(candidate_mvs role = generated projection)."
    )

    design = rec.model.model_dump(by_alias=True, mode="json")
    (pack_dir / "design.json").write_text(
        json.dumps(design, indent=2) + "\n", encoding="utf-8"
    )
    files.append("design.json")

    gaps_lines = [
        "# Gaps and unclosed streams",
        "",
        f"Sandbox: `{rec.sandbox_id}`",
        f"Parent MVS revision: {rec.parent_mvs_revision}",
        "",
        "## Gaps",
        "",
    ]
    if rec.last_solve and rec.last_solve.gaps:
        for g in rec.last_solve.gaps:
            gaps_lines.append(
                f"- `{g.sector_id or '—'}` / {g.sector_definition or '—'}: "
                f"{g.reason} — {g.detail or ''}"
            )
    elif rec.model.gaps:
        for g in rec.model.gaps:
            gaps_lines.append(
                f"- `{g.sector_id or '—'}` / {g.sector_definition or '—'}: "
                f"{g.reason} — {g.detail or ''}"
            )
    else:
        gaps_lines.append("- (none recorded — run POST …/solve first)")
    gaps_lines += ["", "## Unclosed streams", ""]
    unclosed = (
        rec.last_solve.unclosed_streams
        if rec.last_solve
        else rec.model.unclosed_streams
    )
    if unclosed:
        for u in unclosed:
            gaps_lines.append(f"- `{u.stream_id}`: {u.reason}")
    else:
        gaps_lines.append("- (none recorded)")
    gaps_lines.append("")
    (pack_dir / "gaps.md").write_text("\n".join(gaps_lines), encoding="utf-8")
    files.append("gaps.md")

    enabled = [s.sector_id for s in rec.model.sectors if s.enabled]
    mods = list(req.export_modules)
    readme = f"""# Design pack `{name}`

Licence: CERN-OHL-S-2.0  
Parent MVS: {rec.parent_mvs_revision} (`doc_id` AQS-MVS-001 candidate)  
Sandbox: `{rec.sandbox_id}` ({rec.label})  
Exported: {datetime.now(CT).strftime("%Y-%m-%d %H:%M:%S CT")}

## Authority (WP-Bp4 / WP-C1)

- Topology: `flow_graph_snapshot.json` (copy of `plant_flow_graph.json`)
- MVS projection: `mvs_snapshot.json` (from graph; not a second master)
- Sandbox overlay: `design.json`
- Graph layer packs: `pfd/`, `sld.svg`/`sld.json` when modules requested
- This pack does **not** replace locked / candidate MVS or rewrite the graph.
- Matplotlib (if present under `matplotlib/`) is optional bridged export only.

## Enabled sectors

{chr(10).join("- " + s for s in enabled)}

## Modules requested

{chr(10).join("- " + m for m in mods)}

## Module map (WP-C1)

| Key | Artefacts | Source |
|---|---|---|
| (always) | flow_graph_snapshot, mvs_snapshot, design, gaps, README | graph + sandbox |
| params | params.json | sandbox overlay |
| streams | streams.csv | sandbox streams (graph-backed) |
| compliance_flags | compliance_flags.md | last solve |
| pfd | pfd/*.svg/json | flow_graph/views (graph) |
| sld | sld.svg/json + sld/ | views/efd-elec (+ thermal/ess) |
| bom | bom.csv, bom_self_copy.json | graph nodes + AQS-BOM-SC-001 flags |
| matplotlib | matplotlib/*.png | optional hub bridged PNGs |
| 3d | (deferred Phase D) | — |
"""
    (pack_dir / "README.md").write_text(readme, encoding="utf-8")
    files.append("README.md")

    modset = set(mods)
    if "params" in modset:
        params = {
            "scale_m": rec.model.scale_m,
            "site": rec.model.site.model_dump(mode="json"),
            "electrical": rec.model.electrical.model_dump(mode="json"),
            "scale_rules": rec.model.scale_rules.model_dump(mode="json"),
            "note": "Overlay only — does not rewrite cad/freecad/params.py",
            "topology_authority": "AQS-FLOW-GRAPH-001",
        }
        (pack_dir / "params.json").write_text(
            json.dumps(params, indent=2) + "\n", encoding="utf-8"
        )
        files.append("params.json")

    if "streams" in modset:
        path = pack_dir / "streams.csv"
        with path.open("w", newline="", encoding="utf-8") as fh:
            w = csv.writer(fh)
            w.writerow(
                [
                    "stream_id",
                    "from_unit_id",
                    "to_unit_id",
                    "phase",
                    "carries",
                    "rate_value",
                    "rate_unit",
                    "rate_status",
                ]
            )
            for st in rec.model.streams:
                rv = st.rate
                w.writerow(
                    [
                        st.stream_id,
                        st.from_unit_id,
                        st.to_unit_id,
                        st.phase,
                        st.carries or "",
                        "" if rv is None or rv.value is None else rv.value,
                        "" if rv is None else rv.unit,
                        "" if rv is None else rv.status.value,
                    ]
                )
        files.append("streams.csv")

    if "compliance_flags" in modset:
        flags = ["# Compliance theme flags", ""]
        if rec.last_solve:
            for cf in rec.last_solve.code_flags:
                flags.append(
                    f"- {cf.theme} ({cf.controlling}): {', '.join(cf.refs)}"
                )
        else:
            flags.append("- Run solve to populate code flags.")
        flags.append("")
        (pack_dir / "compliance_flags.md").write_text(
            "\n".join(flags), encoding="utf-8"
        )
        files.append("compliance_flags.md")

    graph = _load_graph_snapshot(pack_dir)

    if "pfd" in modset:
        _emit_pfd(pack_dir, files, notes)
    if "sld" in modset:
        _emit_sld(pack_dir, files, notes)
    if "bom" in modset:
        _emit_bom(pack_dir, rec, graph, files, notes)
    if "matplotlib" in modset:
        _emit_matplotlib(pack_dir, files, notes)

    if "3d" in modset:
        notes.append(
            "Module '3d' requested but deferred to Phase D "
            "(FreeCAD rebuild bias; WP-D3)."
        )

    unknown = modset - {
        "params",
        "streams",
        "gaps",
        "compliance_flags",
        "pfd",
        "sld",
        "bom",
        "matplotlib",
        "3d",
    }
    for u in sorted(unknown):
        notes.append(f"Module '{u}' requested but not recognized; skipped.")

    return ExportResponse(
        pack_dir=str(pack_dir),
        files=files,
        notes=notes,
    )
