"""X-BLD-04 access and electrical working-space check (AQS-BLD-012).
(1) NEC 2023 110.26(A)(1) Table 110.26(A)(1): 151-600 V to ground, Condition 2 depth 1067 mm (Condition 3, 1219 mm, reported);
    110.26(A)(2) width max(762 mm, equipment width). Pass if at least one face of each electrical row has that clear box free of other rows.
(2) Access aisle: NFPA 101 (2024) 7.3.4.1.1 / IBC 2021 1018.5 minimum clear width 914 mm (36 in): every row needs one face with a
    914 mm deep clear strip over its face length. Walls are modelled only as partition X lines; room walls pending the fit-out model (A-M-101).
Line items (plan dimension <= 100 mm) and members of one tool group are excluded as obstacles. Exit 1 on failure. Writes docs-authority/ACCESS_CHECK.md."""
import json, sys
ELEC = ['RECTIFIER','RECT_EW','SOL_ARK_60K','LOAD_AGG','BOUNDARY_EXPORT','BACKUP_GEN','FUEL_CELL','ZNBR2','MEOH_FC']
D2, D3, W_MIN, AISLE = 1067, 1219, 762, 914
import os; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); import ga_envelopes
B, G, Z = ga_envelopes.load()
U = [dict(unit_id=k, level=v[0], origin_mm=[v[1], v[2]], size_mm=[v[3], v[4]], group=G.get(k)) for k, v in B.items()]
def box(r): o, z = r['origin_mm'], r['size_mm']; return (o[0], o[1], o[0]+z[0], o[1]+z[1])
def solid(r): return min(r['size_mm']) > 100
def same_group(a, b): return G.get(a['unit_id']) == b['unit_id'] or G.get(b['unit_id']) == a['unit_id'] or (G.get(a['unit_id']) and G.get(a['unit_id']) == G.get(b['unit_id']))
def stacked(a, b):
    za, zb = Z.get(a['unit_id'], (0,0)), Z.get(b['unit_id'], (0,0))
    return za[1] and zb[1] and not (za[0] < zb[0]+zb[1] and zb[0] < za[0]+za[1])
def hit(a, b): return a[0] < b[2] and b[0] < a[2] and a[1] < b[3] and b[1] < a[3]
def faces(b, depth, wmin=0):
    x0,y0,x1,y1 = b; cx, cy = (x0+x1)/2, (y0+y1)/2; wx = max(wmin, x1-x0)/2; wy = max(wmin, y1-y0)/2
    return {'S': (cx-wx, y0-depth, cx+wx, y0), 'N': (cx-wx, y1, cx+wx, y1+depth), 'W': (x0-depth, cy-wy, x0, cy+wy), 'E': (x1, cy-wy, x1+depth, cy+wy)}
def clear_faces(r, depth, wmin=0):
    b = box(r); others = [box(o) for o in U if o is not r and o.get('level') == r.get('level') and solid(o) and not same_group(r, o) and not stacked(r, o)]
    return [f for f, fb in faces(b, depth, wmin).items() if not any(hit(fb, ob) for ob in others)]
lines, bad = [], 0
lines += ['## 1. NEC 110.26(A) working space', '', '| Row | Level | Faces clear at 1067 mm (Cond. 2) | Faces clear at 1219 mm (Cond. 3) | Result |', '|---|---|---|---|---|']
for u in ELEC:
    r = next((x for x in U if x['unit_id'] == u), None)
    if r is None: continue
    c2, c3 = clear_faces(r, D2, W_MIN), clear_faces(r, D3, W_MIN); ok = bool(c2); bad += not ok
    lines.append(f"| {u} | {r.get('level')} | {' '.join(c2) or '-'} | {' '.join(c3) or '-'} | {'pass' if ok else 'FAIL'} |")
lines += ['', '## 2. Access aisle (914 mm) to each row', '', '| Row | Level | Faces with 914 mm clear |', '|---|---|---|']
fails = []
for r in U:
    if str(r.get('level','')).endswith('T2'): continue   # tier-2 shelf: reached from the tier-1 aisle below
    if not solid(r) or (G.get(r['unit_id']) and G.get(r['unit_id']) != r['unit_id'] and G.get(r['unit_id']) in B): continue
    c = clear_faces(r, AISLE)
    if not c: fails.append(r['unit_id']); lines.append(f"| {r['unit_id']} | {r.get('level')} | none |")
bad += len(fails)
lines += ['', f'Rows checked for access: {sum(1 for r in U if solid(r))}; rows without a 914 mm face: {len(fails)}.', '', f'Failing items: {bad}.']
hdr = ['# Access and electrical working-space check', '', 'Document: AQS-BLD-012 Rev A. Generated by `flow_graph/access_check.py` from the AQS-BLD-010 envelope set (`flow_graph/ga_envelopes.py`). Study; AHJ and PE verification required.', '',
       'Basis: NEC 2023 110.26(A)(1)-(2); NFPA 101 (2024) 7.3.4.1.1 and IBC 2021 1018.5 minimum 914 mm clear width. Travel distance and exit count are in AQS-EGR-001 (EGRESS_CALC.md) and are not repeated here. '
       'Room walls other than the X=15000 partition are not modelled as obstacles (A-M-101).', '']
open('docs-authority/ACCESS_CHECK.md','w').write('\n'.join(hdr+lines)+'\n'); print('\n'.join(lines)); sys.exit(1 if bad else 0)
