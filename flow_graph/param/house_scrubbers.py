"""X-PAR-03 scrubber function applied to the house scrubbers ALK_SCRUBBER, ACID_POLISH_SCRUB, NOX_SCRUB and MET_SCRUB (A-M-164).
Gas volume from the graph gas inflow; diameter from flooding at the design fraction (sizing.scrubber, PERRY9_ABS) and not below
d/dp 8; bed = HTU x NTU for the removal target (irreversible absorption); liquid from the minimum wetting rate; fan on bed + 0.5 m
fixed losses (demister, distributor, ducts at 250 Pa); pump on head. Run: python3 -m flow_graph.param.house_scrubbers [--write]"""
import json, math, os, sys
from . import drivers as DR
from . import site as SITE
from .sizing import scrubber as S
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GP = os.path.join(ROOT, 'flow_graph/plant_flow_graph.json')
UNITS = {'ALK_SCRUBBER': 'NaOH scrub of the house acid-gas header', 'ACID_POLISH_SCRUB': 'acid polish of the same air (liquor to CRU)',
         'NOX_SCRUB': 'flue, leach off-gas and nitric vents', 'MET_SCRUB': 'metal-aisle fume and mist (wet scrubber ahead of the baghouse filter)'}
TAG = 'X-PAR-03 house scrubber (flow_graph/param/house_scrubbers.py, A-M-164)'
HSK = 'GAS.scrubbing-headers-train.scrubbing.'   # U4b: sizing literals single-sourced from drivers.json (A-M-164)
_D = DR.load()

def design(d, g):
    v = lambda k: DR.val(d, k)
    out = {}
    for u, duty in UNITS.items():
        gas = sum(float(e['rate']['value'] or 0) for e in g['edges'] if e['to_unit_id'] == u and 'mass' in e['layers'] and e['phase'].startswith(('G', 'L/G')))
        Q = gas/v(HSK+'hs_gas_rho_kg_m3')/86400                                          # m3/s at 1.2 kg/m3
        uf = S.flood_velocity_m_s(v('hs_Cs_flood_m_s'), 1000.0, v(HSK+'hs_gas_rho_kg_m3'))
        D = max(S.diameter_m(Q, uf, v('hs_frac_flood')), v('hs_dp_mm')*v('vs_d_over_dp')/1000)
        Z = max(v(HSK+'hs_bed_min_m'), S.packed_height_m(v('hs_htu_m'), 1.0, 1 - v('hs_removal')))
        L = S.min_liquid_m3_h(D, v('hs_a_m2_m3'), v('vs_mwr'))
        dP = v('hs_dP_Pa_m')*Z + v(HSK+'hs_fixed_dP_Pa')
        fan = Q*dP/v('hs_fan_eff'); pump = L/3600*1000*SITE.g()*v('hs_pump_head_m')/v('hs_pump_eff')
        Dmm = math.ceil(D*1000/50)*50; H = round(Z*1000) + v(HSK+'hs_vessel_allow_mm')      # sump 600, distributor and demister 900
        out[u] = dict(duty=duty, gas_kg_d=gas, Q_m3_s=Q, u_flood_m_s=uf, D_mm=Dmm, packed_mm=round(Z*1000), H_mm=H, recirc_m3_h=L, dP_Pa=dP,
                      fan_W=fan, pump_W=pump, kW=round((fan + pump)/1000, 4), material='PP-H shell and in-house cut PP rings; PP mesh demister')
    return out

def write(g, R):
    N = {n['unit_id']: n for n in g['nodes']}; E = {e['stream_id']: e for e in g['edges']}
    for u, r in R.items():
        n = N[u]; p = n.setdefault('params', {})
        p['design'] = {k: (round(x, 4) if isinstance(x, float) else x) for k, x in r.items()}
        p['size_mm'] = [r['D_mm'] + DR.val(_D, HSK+'hs_envelope_side_mm'), r['D_mm'] + DR.val(_D, HSK+'hs_envelope_side_mm'), r['H_mm'] + DR.val(_D, HSK+'hs_envelope_top_mm')]; p['size_note'] = 'L x W x H mm, set by flow_graph/param/house_scrubbers.py (X-PAR-03)'
        n['continuous_kw'] = {'value': r['kW'], 'unit': 'kW', 'status': 'study', 'note': f"{TAG}. Fan {r['fan_W']:.0f} W, pump {r['pump_W']:.0f} W."}
        for sid, a, b in ((f'SF-{u}', 'SOL_ARK_60K', u), (f'SQ-{u}', u, 'HEAT_SINK')):
            if sid in E: E[sid]['rate']['value'] = r['kW']; E[sid]['rate']['note'] = f'{TAG}.'
            elif a in N and b in N:   # R11 Rev AC regen: HEAT_SINK and the SQ-* heat edges died in Rev AC; only create edges whose endpoints exist
                g['edges'].append({'stream_id': sid, 'from_unit_id': a, 'to_unit_id': b, 'phase': 'E', 'layers': ['elec'] if sid.startswith('SF') else ['energy'], 'presence': 'present',
                     'carries': '480 V AC' if sid.startswith('SF') else 'electrical input leaving as heat', 'header': 'tray', 'forbidden': 'HDR_O2, HDR_CO2', 'claim_status': 'Claimed / Partial',
                     'rate': {'value': r['kW'], 'unit': 'kW', 'status': 'study', 'note': f'{TAG}.'}, 'from_sector_id': N[a].get('sector_id'), 'to_sector_id': N[b].get('sector_id'),
                     'open_boundary': False, 'namespace': 'S', 'gap_flags': [], 'notes': None})
    open(GP, 'w').write(json.dumps(g, indent=2))

def write_doc(d, R):
    md = """# House scrubbers

Document number: AQS-DUTY-079  
Former number: AQS-DUTY-064 (shared with sizing/STORAGE_HOLDUP.md until 2026-10-24; that page keeps it)
Revision: A
Date: 2026-10-15
Authority: AQS-PLAN-007 X-PAR-03 (scrubber function applied). Generated by `flow_graph/param/house_scrubbers.py`. Study. A-M-164.

| Unit | Duty | Gas, kg/d | Gas, m3/s | Flood velocity, m/s | Diameter, mm | Bed, mm | Height, mm | Liquid, m3/h | dP, Pa | Fan, W | Pump, W | kW |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
"""
    for u, r in R.items():
        md += f"| {u} | {r['duty']} | {r['gas_kg_d']:.1f} | {r['Q_m3_s']:.4f} | {r['u_flood_m_s']:.2f} | {r['D_mm']} | {r['packed_mm']} | {r['H_mm']} | {r['recirc_m3_h']:.3f} | {r['dP_Pa']:.0f} | {r['fan_W']:.1f} | {r['pump_W']:.1f} | {r['kW']} |\n"
    md += f"""
Basis: flooding u_f = C_s sqrt((rho_L - rho_G)/rho_G), D at {DR.val(d,'hs_frac_flood')} of flood (PERRY9_ABS), not below {DR.val(d,'vs_d_over_dp'):.0f} packing diameters; bed = HTU x ln(1/(1 - {DR.val(d,'hs_removal')})) with a 0.5 m minimum; minimum wetting rate {DR.val(d,'vs_mwr')} m3/(m h) (PERRY9_ABS). Packing is the in-house {DR.val(d,'hs_dp_mm'):.0f} mm cut PP ring: C_s {DR.val(d,'hs_Cs_flood_m_s')} m/s, HTU {DR.val(d,'hs_htu_m')} m, {DR.val(d,'hs_dP_Pa_m'):.0f} Pa/m and a = {DR.val(d,'hs_a_m2_m3'):.0f} m2/m3 are assumptions (A-M-164) until the column flooding and absorption tests on the in-house packing are run. Gas density {DR.val(d,HSK+'hs_gas_rho_kg_m3')} kg/m3. The scrub chemistry is AQS SCRUBBER_CHEMISTRY.md; EVAP_ACID_VS stays on its own design (X-PAR-10).
"""
    open(os.path.join(ROOT, 'docs-authority/sizing/HOUSE_SCRUBBERS.md'), 'w').write(md)

def main():
    d = DR.load(); g = json.load(open(GP)); R = design(d, g)
    for u, r in R.items(): print(u, {k: (round(x, 3) if isinstance(x, float) else x) for k, x in r.items() if k != 'duty'})
    if '--write' in sys.argv: write(g, R); write_doc(d, R)

if __name__ == '__main__': main()
