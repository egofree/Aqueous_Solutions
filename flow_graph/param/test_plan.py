"""X-PAR-05. Writes docs-authority/TEST_PLAN.md (AQS-TST-001): every needs_verification driver
(flow_graph/param/drivers.json) and register entry (assumptions_manual.json, AQS-REG-002) mapped to a
test or data source and a rollout phase. Classification is by the verification_test text (rules below,
first match wins); the generator fails if any item is unmapped.
Run: python3 -m flow_graph.param.test_plan"""
import json, os, re
from . import drivers as DR, solver
ROOT = solver.ROOT
PH = [  # (phase, title, regex on verification_test, what closes it)
 ('T1', 'Owner and site data', r'owner|ASCE|geotech|building official|Wenner|AHJ|parcel|site survey|site plan|utility', 'Owner decision or site investigation report'),
 ('T4', 'Pilot runs', r'pilot', 'Pilot campaign on plant brine / feed'),
 ('T3', 'Bench and laboratory tests', r'bench|cell test|polari[sz]ation|leach test|float/sink|density of|titration|assay|XRF|ICP|characteris|analysis of|chloride and pH|decomposition|deposit|hydrogen content|just-suspended|precipitation|conductivity', 'Bench test report with method, data and result'),
 ('T2', 'In-house design tests and standard data', r'in-house|coupon|bench run|stack test|trial run|data sheet|nameplate|time-current|device curves', 'In-house test record or standard data filed against the item'),
 ('T6', 'Commissioning measurements', r'commissioning|^measured|operating|installed|built tank', 'Commissioning record'),
 ('T5', 'Design calculations and drawings', r'.', 'Calculation or drawing issued under the named task'),
]
def classify(t):
    for ph, _, rx, _ in PH:
        if re.search(rx, t, re.I): return ph
def items():
    d = DR.load(); man = json.load(open(os.path.join(ROOT, 'docs-authority/assumptions_manual.json')))
    out = [dict(id=f'driver {k}', value=f"{json.dumps(v['value'])} {v['units']}", test=v['verification_test'], task='X-PAR', driver=True) for k, v in d.items() if v.get('needs_verification')]
    out += [dict(id=m['id'], value=f"{str(m['value'])[:60]} {m.get('units','')}", test=m['verification_test'], task=m.get('task',''), driver=False) for m in man if m.get('needs_verification')]
    for x in out: x['phase'] = classify(x['test'])
    assert all(x['phase'] for x in out)
    return out
def main():
    it = items(); cnt = {p[0]: sum(1 for x in it if x['phase'] == p[0]) for p in PH}
    L = ['# Testing and prototyping rollout plan', '', 'Document number: AQS-TST-001', 'Revision: A', 'Date: 2026-10-15',
         'Authority: AQS-PLAN-007 X-PAR-05. Generated by `python3 -m flow_graph.param.test_plan` from the AQS-PAR-001 verification list (drivers.json and AQS-REG-002). Study.', '',
         '| Rev | Description | Date |', '| --- | --- | --- |', '| A | First issue. Every needs_verification driver and register entry mapped to a test and phase. | 2026-10-15 |', '',
         '## 1. Rollout', '',
         'Phases run in the order below; T1 and T2 start at once and in parallel. T3 bench tests start with the drivers that set equipment size (acid loop, BMED, EW). T4 pilots follow the bench results they depend on. T5 calculations close inside their unit tasks. T6 closes at commissioning. A closed item updates its driver or register entry (value, source, needs_verification false) and the commit reruns the solver, `write_graph`, and the checks.', '',
         '| Phase | Scope | Items | Closes with |', '| --- | --- | --- | --- |']
    order = ['T1','T2','T3','T4','T5','T6']; P = {p[0]: p for p in PH}
    L += [f'| {p} | {P[p][1]} | {cnt[p]} | {P[p][3]} |' for p in order]
    L += ['', f'Total {len(it)} items: {sum(x["driver"] for x in it)} drivers, {sum(not x["driver"] for x in it)} register entries. Classification rule: first match of the phase regex on the verification test text (see the generator).', '']
    for i, p in enumerate(order, 2):
        L += [f'## {i}. {p} {P[p][1]}', '', '| Item | Value | Test | Task |', '| --- | --- | --- | --- |']
        rows = sorted([x for x in it if x['phase'] == p], key=lambda x: (not x['driver'], x['id']))
        L += [f"| {x['id']} | {x['value'].replace('|','/')} | {x['test'].replace('|','/')} | {x['task']} |" for x in rows] + ['']
    open(os.path.join(ROOT, 'docs-authority/TEST_PLAN.md'), 'w').write('\n'.join(L))
    print(cnt)
if __name__ == '__main__': main()
