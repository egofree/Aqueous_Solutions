"""High-pressure gas receivers CRYO_H2 and CRYO_O2 (A-M-167): banks of seamless SA-312 TP316L DN100 Sch 160 tubes (ASME B36.10M OD 114.3,
t 13.49 mm). 316L serves both gases: austenitic (hydrogen), and stainless in oxygen (CGA_S1_1 relief, O2 cleaning ASTM G93 per the graph).
Wall: B31.3 304.1.2 / UG-27 outside-radius form t = P D/(2(S E + P Y)) with Y 0.4, S from ASME_II_D, E 1, 12.5 % mill tolerance.
ID 87 mm is below the 152 mm Section VIII limit (ASME_VIII1_U1), so the tubes are piping components (ASME_B31_3). Water volume from the graph
store (store_water_volume_m3); tubes in two manifolded halves so one leaking tube or half is isolated with the rest in service (redundancy rule).
Run: python3 -m flow_graph.param.receivers [--write]"""
import json, math, os, sys
from . import drivers as DR
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GP = os.path.join(ROOT, 'flow_graph/plant_flow_graph.json')
OD, T = 114.3, 13.49
def design(d, g):
    N = {n['unit_id']: n for n in g['nodes']}; S = DR.val(d, 's_316L_38C_MPa'); L = DR.val(d, 'rcv_tube_len_m'); out = {}
    for u in ('CRYO_H2', 'CRYO_O2'):
        p = N[u]['params']; P = p['design_kPa']/1000; t_req = P*OD/(2*(S + P*0.4)); tmin = T*0.875
        ID = OD - 2*T; a = math.pi*(ID/1000)**2/4
        banks = [('main', p['store_water_volume_m3'])]
        if u == 'CRYO_O2' and p.get('crew_reserve_kg'): banks.append(('crew reserve', p['store_water_volume_m3']*p['crew_reserve_kg']/p['store_kg']))
        bk = []
        for name, V in banks:
            n = max(2, math.ceil(V/(a*L))); n += n % 2
            bk.append(dict(bank=name, V_m3=V, tubes=n, halves=2))
        nt = sum(b['tubes'] for b in bk); rows = math.ceil(nt/8)
        out[u] = dict(P_design_MPa=P, S_MPa=S, t_req_mm=t_req, t_min_mm=tmin, t_ok=tmin >= t_req, OD_mm=OD, ID_mm=ID, tube_m=L, banks=bk, tubes=nt,
                      steel_kg=nt*L*28.3, D_mm=round(OD), wall_mm=T, H_mm=rows*150 + 300, T_C=25, rack_mm=[round(L*1000) + 600, 8*150 + 300, rows*150 + 300],
                      material='SA-312 TP316L seamless DN100 Sch 160, B16.11 Class 9000 fittings / autoclave cone-and-thread, O2 bank cleaned to ASTM G93')
    return out
def write(g, R):
    N = {n['unit_id']: n for n in g['nodes']}
    for u, r in R.items():
        p = N[u]['params']; p['design'] = {k: (round(x, 4) if isinstance(x, float) else x) for k, x in r.items()}; p['size_mm'] = r['rack_mm']
        p['size_note'] = 'L x W x H mm tube rack, set by flow_graph/param/receivers.py (A-M-167)'
    open(GP, 'w').write(json.dumps(g, indent=2))
def write_doc(R):
    md = ['# High-pressure gas receivers', '', 'Document number: AQS-DUTY-065', 'Revision: A', 'Date: 2026-10-15',
          'Authority: X-MFG-40 follow-on (CRYO_H2, CRYO_O2 were Section VIII-1 awaiting size). Generated by `flow_graph/param/receivers.py`. Study. A-M-167.', '',
          '| Unit | Design MPa | t req / min, mm | Tube | Banks | Tubes | Steel, kg | Rack L x W x H, mm |', '|---|---|---|---|---|---|---|---|']
    for u, r in R.items():
        md.append(f"| {u} | {r['P_design_MPa']:.1f} | {r['t_req_mm']:.2f} / {r['t_min_mm']:.2f} {'ok' if r['t_ok'] else 'NOT OK'} | DN100 Sch 160 316L x {r['tube_m']} m (ID {r['ID_mm']:.1f}) | " + '; '.join(f"{b['bank']} {b['V_m3']:.3f} m3" for b in r['banks']) + f" | {r['tubes']} | {r['steel_kg']:.0f} | {' x '.join(str(x) for x in r['rack_mm'])} |")
    md += ['', 'Wall per ASME_B31_3 304.1.2 (outside-diameter form, Y 0.4) with S 115 MPa (ASME_II_D, SA-312 TP316L to 38 C), E 1, no corrosion allowance (dry gas), Sch 160 less 12.5 % mill tolerance. ID 87.3 mm is under the 152 mm Section VIII-1 size limit (ASME_VIII1_U1), so each tube is a piping component. Each bank is two manifolded halves with isolation and its own relief (pressure_nodes.py blocked-outlet case), so a leaking tube takes out at most half a bank. Fatigue from daily cycling and hydrogen-assisted fatigue of 316L are checked at the first-article cycle test (A-M-167).']
    open(os.path.join(ROOT, 'docs-authority/sizing/GAS_RECEIVERS.md'), 'w').write('\n'.join(md) + '\n')
def main():
    d = DR.load(); g = json.load(open(GP)); R = design(d, g)
    for u, r in R.items(): print(u, r['t_req_mm'], r['t_ok'], r['tubes'], r['banks'], round(r['steel_kg']))
    if '--write' in sys.argv: write(g, R); write_doc(R)
if __name__ == '__main__': main()
