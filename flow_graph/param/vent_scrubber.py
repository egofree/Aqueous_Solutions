"""X-PAR-10 vent scrubber EVAP_ACID_VS on the EVAP_ACID column vent (owner decision 2026-10-15): small packed alkali scrubber,
NaOH bleed from BMED_BASE (2 M, no dedicated alkali cell), spent liquor to BMED_ACID. Sized by sizing.scrubber.vent_scrubber.
Run: python3 -m flow_graph.param.vent_scrubber [--write]"""
import json, math, os, sys
from . import drivers as DR
from .sizing import scrubber as S, hcl_vle as V, evaporator as EV
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

def case(d, feed_kg_d, w_cond_pct):
    v = lambda k: DR.val(d, k); T = v('vs_T_C'); TK = T + 273.15
    ph = 10**V._lp(V.H, w_cond_pct, TK)*0.133322                       # kPa; below 2 wt% the 2 wt% row is used (bounding high)
    pw = 10**V._lp(V.W, w_cond_pct, TK)*0.133322 if w_cond_pct >= 6 else EV.psat_kPa(T)
    r = S.vent_scrubber(feed_kg_d, v('vs_air_mg_kg'), T, ph, pw, v('vs_y_out_ppm'), None, v('vs_margin'), v('vs_dp_mm'), v('vs_d_over_dp'),
                        v('vs_a_m2_m3'), v('vs_mwr'), v('vs_naoh_excess'), v('bmed_product_wt_base'))
    r.update(w_cond_pct=w_cond_pct, p_hcl_kPa=ph); return r

def design(d, ea):
    """Design case = upset (column bypassed: condensate at the body vapour composition); normal = column working."""
    up = case(d, ea['feed_kg_d'], ea['design']['column']['y_eq_body_pct']); nm = case(d, ea['feed_kg_d'], ea['cond_hcl_wt']*100)
    D = up['D_m']; DN = next(x for x in (100, 125, 150, 200) if x >= D*1000)
    sump_L = 20.0                                                          # charge of 2 M NaOH (study, A-M-111)
    pump_kW = up['recirc_m3_h']/3600*1000*9.81*10.0/0.4/1000               # 10 m head, 40 % small-pump efficiency (study)
    return dict(upset=up, normal=nm, DN=DN, packed_mm=math.ceil(up['packed_m']*1000/100)*100, sump_L=sump_L,
                sump_mol=sump_L*DR.val(d, 'bmed_product_molarity'), pump_kW=pump_kW, height_mm=math.ceil(up['packed_m']*1000/100)*100 + 900,
                material='PVC-U pipe and fittings (ASTM D1785 Sch 80), in-house cut PVC tube rings, PVC mesh demister (PERRY9_MAT: PVC to 60 C in HCl and NaOH)')

def main(write=False):
    from . import solver
    d, g, s = solver.solve(); x = s['vs']
    print(json.dumps({k: (round(v, 6) if isinstance(v, float) else v) for k, v in x.items() if k not in ('upset', 'normal')}))
    print('upset', {k: round(v, 6) for k, v in x['upset'].items()}); print('normal', {k: round(v, 6) for k, v in x['normal'].items()})
    if write: write_doc(d, s)

