"""X-MFG-38 in-house PV cell line tools for SOLAR_PV_CELL (AQS-DUTY-071, A-M-178). One batch a day of pv_cells_per_d cells through
texture, POCl3 diffusion, PSG etch, PECVD SiNx, screen print, fast firing and IV test. Energy from the physics of each tool:
baths and furnaces = heat-up of the heated mass m cp dT plus the insulated loss at temperature (ASTM_C680 radial method, sizing/heat.py
insulated_cylinder, INCROPERA7); PECVD = RF power density x electrode area x deposition time plus heater and vacuum pump; print, fire
and IV = drive or lamp power x time. Nameplate = the largest heat-up rate. Replaces the ST-SOLAR-01 datasheet share.
Run: python3 -m flow_graph.param.pv_cell_line [--write]"""
import json, os, sys
from . import drivers as DR
from .sizing import heat as HT
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GP = os.path.join(ROOT, 'flow_graph/plant_flow_graph.json')
def design(d):
    v = lambda k: DR.val(d, k); T = []
    # texture: water bath heat-up and an insulated tank loss at temperature
    q = v('pvl_tex_L')*4.18*(v('pvl_tex_C') - 25)/3600; _, loss = HT.insulated_cylinder(v('pvl_tex_C'), 250, 0.3)
    T.append(('PV-TEX-01', 'KOH texture bath, 10 L PP tank, immersion heater', q/v('pvl_tex_heat_h') + loss/1000, q + loss/1000*v('pvl_tex_run_h')))
    # diffusion tube furnace
    q = v('pvl_diff_mass_kg')*1.0*(v('pvl_diff_C') - 25)/3600
    t, loss = HT.insulated_cylinder(v('pvl_diff_C'), v('pvl_diff_D_mm'), v('pvl_diff_L_m'), k_a=v('pvl_hot_k_a'), k_b=v('pvl_hot_k_b'))
    T.append(('PV-EMIT-01', f"POCl3 diffusion, quartz tube {v('pvl_diff_D_mm'):.0f} mm x {v('pvl_diff_L_m'):.1f} m, {t} mm ceramic fibre", q/v('pvl_diff_heat_h') + loss/1000, q + loss/1000*(v('pvl_diff_run_h') + v('pvl_diff_heat_h')/2)))
    T.append(('PV-PSG-01', 'HF PSG etch, room temperature PP bath', 0.0, 0.0))
    rf = v('pvl_pecvd_W_cm2')*v('pvl_pecvd_area_m2')*1e4/1000; qh = 5.0*0.5*(v('pvl_pecvd_C') - 25)/3600; _, lh = HT.insulated_cylinder(v('pvl_pecvd_C'), 300, 0.4, k_a=v('pvl_hot_k_a'), k_b=v('pvl_hot_k_b'))
    T.append(('PV-ARC-01', 'PECVD SiNx, parallel-plate RF, 5 kg heated platen, dry vacuum pump', rf + qh/0.5 + lh/1000 + v('pvl_vac_kW'),
              rf*v('pvl_pecvd_dep_h') + qh + lh/1000*v('pvl_vac_h') + v('pvl_vac_kW')*v('pvl_vac_h')))
    T.append(('PV-CON-01', 'Screen printer and 200 C dryer', v('pvl_print_kW') + v('pvl_dry_kW'), (v('pvl_print_kW') + v('pvl_dry_kW'))*v('pvl_print_h')))
    T.append(('PV-FIRE-01', 'IR lamp fast-firing furnace', v('pvl_fire_kW'), v('pvl_fire_kW')*v('pvl_fire_h')))
    T.append(('PV-IV-01', 'Flash IV tester', v('pvl_iv_kW'), v('pvl_iv_kW')*v('pvl_iv_h')))
    E = sum(t[3] for t in T)
    return dict(cells_per_d=v('pv_cells_per_d'), tools=[dict(id=a, design=b, peak_kW=c, kWh_d=e) for a, b, c, e in T], kWh_d=E, avg_kW=E/24, peak_kW=max(t[2] for t in T),
                kWh_per_cell=E/v('pv_cells_per_d'))
def write(g, r):
    N = {n['unit_id']: n for n in g['nodes']}; E = {e['stream_id']: e for e in g['edges']}; n = N['SOLAR_PV_CELL']; TAG = 'X-MFG-38 (A-M-178, AQS-DUTY-071)'
    n['continuous_kw'] = {'value': round(r['avg_kW'], 4), 'unit': 'kW', 'status': 'study', 'note': f"{TAG}: {r['kWh_d']:.2f} kWh/d for {r['cells_per_d']} cells, one batch; peak {r['peak_kW']:.2f} kW (one tool at a time)."}
    n['params']['avg_kw'] = round(r['avg_kW'], 4); n['params']['design'] = json.loads(json.dumps(r, default=float))
    for sid in ('SF-SOLAR_PV_CELL', 'SQ-SOLAR_PV_CELL'):   # R11 Rev AC regen: SQ-* heat edges died with HEAT_SINK in Rev AC; update what exists
        if sid in E: E[sid]['rate']['value'] = round(r['avg_kW'], 4)
    open(GP, 'w').write(json.dumps(g, indent=2))
    md = ['# PV cell line tools', '', 'Document number: AQS-DUTY-071', 'Revision: A', 'Date: 2026-10-16', 'Authority: AQS-PLAN-007 X-MFG-38; ST-SOLAR-01. Generated by `flow_graph/param/pv_cell_line.py`. Study. A-M-178.', '',
          f"{r['cells_per_d']} cells a day in one batch; tools run one after another, so the peak is the largest single tool.", '',
          '| Tool | Design | Peak kW | kWh/d |', '|---|---|---|---|']
    md += [f"| {t['id']} | {t['design']} | {t['peak_kW']:.2f} | {t['kWh_d']:.2f} |" for t in r['tools']]
    md += [f"| Total | | {r['peak_kW']:.2f} (largest) | {r['kWh_d']:.2f} = {r['avg_kW']:.3f} kW average, {r['kWh_per_cell']:.2f} kWh per cell |", '',
           'Heat-up masses, RF power density, lamp power and run times are assumptions until the first-article tool runs (A-M-178). The diffusion furnace dominates; a second batch in the same heat would halve its energy per cell.']
    open(os.path.join(ROOT, 'docs-authority/sizing/PV_CELL_LINE.md'), 'w').write('\n'.join(md) + '\n')
def main():
    d = DR.load(); r = design(d); print(json.dumps(r, default=float))
    if '--write' in sys.argv: write(json.load(open(GP)), r)
if __name__ == '__main__': main()
