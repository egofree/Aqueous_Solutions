"""Incompatible hazardous-material separation check (AQS-BLD-011). Pairs from CAMEO_REACT; rule IFC2027_5003 / NFPA400_2025:
edge-to-edge gap >= 6096 mm, or a named 1 h partition line X=<mm> between the rows (WS_HF_ED source: 1 h partition at X=15000).
Approved cabinets are not credited (not yet specified). Writes docs-authority/HAZMAT_SEPARATION.md; exit 1 on a failing pair."""
import json, math, sys
SEP = 6096; PART_X = [15000]
PAIRS = [('WS_PEROX','WS_AMMONIA'),('WS_PEROX','WS_KOH'),('WS_PEROX','WS_SOLV'),('WS_NITRIC','WS_AMMONIA'),('WS_NITRIC','WS_KOH'),
         ('WS_NITRIC','WS_SOLV'),('WS_HF_ED','WS_AMMONIA'),('WS_HF_ED','WS_KOH'),('WS_PHOS','WS_AMMONIA'),('WS_PHOS','WS_KOH')]
R = {r['unit_id']: r for r in json.load(open('flow_graph/placement_seed.json'))['units']}
def gap(a, b):
    (ax,ay),(bx,by) = a['origin_mm'][:2], b['origin_mm'][:2]; (aw,ad),(bw,bd) = a['size_mm'][:2], b['size_mm'][:2]
    return math.hypot(max(0, bx-(ax+aw), ax-(bx+bw)), max(0, by-(ay+ad), ay-(by+bd)))
def wall(a, b):
    return any((a['origin_mm'][0]+a['size_mm'][0] <= x <= b['origin_mm'][0]) or (b['origin_mm'][0]+b['size_mm'][0] <= x <= a['origin_mm'][0]) for x in PART_X)
rows, bad = [], 0
for p, q in PAIRS:
    g = gap(R[p], R[q]); w = wall(R[p], R[q]); ok = g >= SEP or w; bad += not ok
    rows.append(f'| {p} | {q} | {g:.0f} | {"yes" if w else "no"} | {"pass" if ok else "FAIL"} |')
md = ['# Incompatible hazardous-material separation', '', 'Document number: AQS-BLD-011', 'Revision: B', 'Date: 2026-10-25',
      'Source: generated by `flow_graph/sep_check.py` from the unit placement in `flow_graph/placement_seed.json`. Do not edit this page by hand.', '',
      '| Rev | Description | Date |', '|---|---|---|', '| A | First issue | 2026-10-15 |',
      '| B | Purpose and scope added; text rewritten to the documentation style guide (AQS-DOC-002). No pair or rule changed. | 2026-10-25 |', '',
      '## 1. Purpose and scope', '',
      'Some chemicals react dangerously if they come into contact, for example an oxidizer with a base or with a solvent. Fire codes therefore '
      'require stored quantities of incompatible materials to be kept apart. This page checks, for each incompatible pair of wet synthesis (WS) '
      'reagent units, that the units are far enough apart or are separated by a fire barrier.', '',
      '## 2. Rule', '',
      'IFC 2027 section 5003.9.8 and NFPA 400 (2025) section 6.1.12.1 require incompatible materials in quantities above 2.3 kg or 2 L to be '
      'separated by at least 6096 mm (20 ft), by a fire barrier with a 1 h rating, or by storage in approved cabinets. The incompatible pairs are '
      'taken from the reactivity groups of the NOAA CAMEO Chemicals database. Cabinets are not credited, because none has yet been specified. '
      f'The 1 h partition on the line X = {PART_X[0]} mm is credited as a barrier (assumption A-M-100).', '',
      'The gap is measured edge to edge between the plan footprints of the two units. A pair passes if the gap is at least 6096 mm or if the '
      'partition lies between the two units.', '',
      '## 3. Results', '',
      'Table 3.1 gives the result for each pair.', '',
      'Table 3.1. Separation of incompatible pairs', '',
      '| Row A | Row B | Edge gap (mm) | 1 h partition between | Result |', '|---|---|---|---|---|'] + rows + ['',
      ('No pair fails the rule.' if not bad else f'{bad} of the pairs fail the rule.')]
open('docs-authority/HAZMAT_SEPARATION.md','w').write('\n'.join(md)+'\n'); print('\n'.join(rows))
import sys as _sys, os as _os; _sys.path.insert(0, _os.path.dirname(_os.path.dirname(_os.path.abspath(__file__))))
from flow_graph.param import code_basis as _CB; _CB.append(_CB.PATHS['HAZMAT_SEPARATION'], 'HAZMAT_SEPARATION')
sys.exit(1 if bad else 0)
