def test_tampered_page_fails_the_fragment_check(tmp_path, model):
    """The rule's teeth: an altered fragment fails the check (and only the
    fragment's absence - position is never asserted); a committed copy
    passes; a missing page is a named failure."""
    entry = next(e for e in fragment_entries(model)
                 if e[1] == 'section-1' and e[0].endswith('DUCK_PEN.md'))
    page_path, fid, fn_r = entry
    fresh = fn_r(model, INPUTS)
    with open(os.path.join(ROOT, page_path), 'rb') as f:
        committed_bytes = f.read()
    assert fresh in committed_bytes
    root_ok = tmp_path / 'ok'
    dst = root_ok / page_path
    dst.parent.mkdir(parents=True)
    dst.write_bytes(committed_bytes)
    ok, lines = CK.check_fragments(model, INPUTS, [entry], root=str(root_ok))
    assert ok and not lines
    root_bad = tmp_path / 'bad'
    dst = root_bad / page_path
    dst.parent.mkdir(parents=True)
    dst.write_bytes(committed_bytes.replace(fresh, b'1. Basis. (a stale hand-era basis line).', 1))
    ok, lines = CK.check_fragments(model, INPUTS, [entry], root=str(root_bad))
    assert not ok and any('stale (fragment)' in ln and fid in ln for ln in lines)
    ok, lines = CK.check_fragments(model, INPUTS, [entry], root=str(tmp_path / 'empty'))
    assert not ok and any('(page missing)' in ln for ln in lines)


def test_patch_fragments_regenerates_stale_pages(tmp_path, model):
    """The update-side: a drifted page is regenerated with its v1 patch idiom
    (the section-1 line replace, the envelope bullet replace), converges so
    the check passes, and the second pass is a no-op."""
    sec1 = next(e for e in fragment_entries(model)
                if e[1] == 'section-1' and e[0].endswith('DUCK_PEN.md'))
    env = next(e for e in fragment_entries(model)
               if e[1] == 'section-2-envelope' and e[0].endswith('DUCK_PEN.md'))
    root = tmp_path / 'pages'
    for entry in (sec1, env):
        dst = root / entry[0]
        dst.parent.mkdir(parents=True, exist_ok=True)
        with open(os.path.join(ROOT, entry[0]), 'rb') as f:
            dst.write_bytes(f.read())
    assert CK.patch_fragments(model, INPUTS, [sec1, env], root=str(root)) == []   # fresh: nothing to patch
    dst = root / sec1[0]
    text = dst.read_text(encoding='utf-8')
    fresh1 = sec1[2](model, INPUTS).decode('utf-8')
    fresh2 = env[2](model, INPUTS).decode('utf-8')
    assert fresh1 in text and fresh2 in text
    drifted2 = re.sub(r'would be [\d.]+ h', 'would be 9999.9 h', fresh2)
    dst.write_text(text.replace(fresh1, '1. Basis. (stale).', 1).replace(fresh2, drifted2, 1),
                   encoding='utf-8')
    applied = CK.patch_fragments(model, INPUTS, [sec1, env], root=str(root))
    assert sorted(applied) == sorted([(sec1[0], sec1[1]), (env[0], env[1])])
    ok, lines = CK.check_fragments(model, INPUTS, [sec1, env], root=str(root))
    assert ok, lines
    assert CK.patch_fragments(model, INPUTS, [sec1, env], root=str(root)) == []   # idempotent


