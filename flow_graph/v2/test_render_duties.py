def test_duties_module_pure():
    """No I/O in the render modules: no open(), no banned imports, no float
    literals - duties.py and the declared-bases data module duty_bases.py
    alike (the engine lint's os.walk already covers render/; mirrored here
    as the wave's declared discipline, in the render_sizing shape)."""
    banned = {'datetime', 'random', 'uuid', 'time', 'tempfile'}
    import flow_graph.v2.render.duty_bases as DBM
    for mod in (DU, DBM):
        path = mod.__file__
        with open(path, encoding='utf-8') as f:
            tree = ast.parse(f.read())
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for a in node.names:
                    assert a.name.split('.')[0] not in banned, f'{path}: banned import {a.name}'
            elif isinstance(node, ast.ImportFrom):
                assert (node.module or '').split('.')[0] not in banned, f'{path}: banned import from {node.module}'
            elif isinstance(node, ast.Constant):
                assert not isinstance(node.value, float), f'{path}:{node.lineno}: float literal'
            elif isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == 'open':
                raise AssertionError(f'{path}:{node.lineno}: file I/O in a render module')


# ---- the fragment staleness rule (the patch fixpoint as a content rule) ------

def seed_blocks():
    """The placement-seed records (the v1 hidden read, at the test's I/O)."""
    with open(SEED, encoding='utf-8') as f:
        return {u['unit_id']: u for u in json.load(f).get('units', []) if u.get('unit_id')}


def envelope_page_ids():
    """Ids whose committed page carries the section 2 envelope bullet at all
    (the page-state fact the v1 patch idiom keys on: it refreshes a bullet in
    place, it never adds one)."""
    out = set()
    for uid in sheet_ids():
        with open(os.path.join(DUTIES_DIR, uid + '.md'), 'rb') as f:
            if re.search(rb'^- Envelope \d', f.read(), flags=re.M):
                out.add(uid)
    return out


def fragment_entries(m):
    """The fragment registry, enumerated exactly as the check enumerates it."""
    return DU.FRAGMENTS(m, set(sheet_ids()), envelope_page_ids(), seed_blocks())


def test_fragment_census_covers_the_declared_classes(model):
    """The fragment set is non-empty, lands one section-1 fragment per unit
    with a sheet, and covers each declared class: the issued section 3 lines,
    the hvac and cycling section 2 blocks, and the envelope bullets outside
    the documented historical skip set. Every entry's page exists."""
    entries = fragment_entries(model)
    assert entries
    by_kind = {}
    for path, fid, _fn in entries:
        by_kind.setdefault(fid, []).append(path)
        assert os.path.exists(os.path.join(ROOT, path)), path
    units = units_with_sheets(model)
    assert len(by_kind['section-1']) == len(units)
    assert len(by_kind.get('section-3-issued', [])) == \
        sum(1 for u in units if ((model.nodes[u].get('params') or {}).get('sec3_material') or {}).get('mat'))
    assert len(by_kind.get('section-2-hvac', [])) == \
        sum(1 for u in units if ((model.nodes[u].get('params') or {}).get('hvac') or {}).get('total_kW') is not None)
    assert len(by_kind.get('section-2-cycling', [])) == \
        sum(1 for u in units if (model.nodes[u].get('params') or {}).get('cycling_thermal'))
    stamped = {u for u in units
               if ((model.nodes[u].get('params') or {}).get('envelope') or {}).get('size_mm')
               or (model.nodes[u].get('params') or {}).get('size_mm')}
    assert len(by_kind.get('section-2-envelope', [])) == len(stamped & (envelope_page_ids() - DU.ENVELOPE_SKIP)) > 0
    assert len(entries) == sum(len(v) for v in by_kind.values())


