    """The generator-owned section 1 line re-renders byte-exactly onto the
    committed page (the v1 patch fixpoint)."""
    line = DU.render_section1(model, uid)
    page = committed(uid)
    assert re.search(r'^1\. Basis\..*$', page, flags=re.M), uid
