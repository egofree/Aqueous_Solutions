"""AQS-ELEC-002 Rev C one-line, generated from the graph electrical edges, AQS-ELEC-003 load list and AQS-ELEC-004.
Writes docs-authority/ONE_LINE.md and returns the bus table as JSON on stdout."""
import json, math, re, subprocess
g=json.load(open('flow_graph/plant_flow_graph.json'))
V=480.0; PF=0.90; BRK=[15,20,25,30,40,50,60,70,80,90,100,110,125,150,175,200,225,250,300,350,400]   # NEC 240.6(A)
rect=json.loads(subprocess.run(['python3','docs-authority/_rect_ew_sizing.py'],capture_output=True,text=True,check=True).stdout)['total']
ll=[l.split('|')[1:-1] for l in open('docs-authority/LOAD_LIST.md') if l.startswith('| ') and not l.startswith('| Unit') and not l.startswith('| ---')]
L={}
for r in ll:
    if len(r)!=5: continue
    try: L[r[0].strip()]=(r[1].strip(),float(r[2]),float(r[3]) if r[3].strip() else None)
    except ValueError: pass
el=[e for e in g['edges'] if 'elec' in (e.get('layers') or [])]
src=[(e['from_unit_id'],e['stream_id'],e['rate']['value']) for e in el if e['to_unit_id']=='SOL_ARK_60K']
fed={e['to_unit_id']:(e['stream_id'],e['rate']['value']) for e in el if e['from_unit_id']=='SOL_ARK_60K'}
PK={n['unit_id']:n.get('params',{}).get('peak_kw') for n in g['nodes'] if isinstance(n.get('params',{}).get('peak_kw'),(int,float))}
def amps(kw,ph=3,v=V): return kw*1000/((math.sqrt(3) if ph==3 else 1)*v*PF)
def brk(a): return next(b for b in BRK if b>=1.25*a)
INV=next(n for n in g['nodes'] if n['unit_id']=='SOL_ARK_60K')['params']
INVTXT=f"{INV.get('count',1)} × 60 = {INV.get('kW',60):.0f} kW inverters"
rows=[]
for u,(sid,kw) in fed.items():
    if u=='BOUNDARY_EXPORT': continue
    rows.append(('SOL_ARK 480 V',u,kw,f'graph {sid}'))
if 'RECT_EW' not in fed: rows.append(('SOL_ARK 480 V','RECT-EW (EW_1–EW_9)',rect['Pac_kW'],'AQS-ELEC-004 bounding AC'))
skip=set(fed)|{f'EW_{i}' for i in range(1,10)}|{'SOL_ARK_60K'}
for u,(role,kw,c) in L.items():
    if u in skip or role not in ('load','—') : continue
    k=c if c is not None else kw
    if k<=0: continue
    rows.append(('MCC-1 480 V' if k>=1.0 else 'PP-1 208/120 V',u,k,'AQS-ELEC-003 '+('calculated' if c is not None else 'study share')))
bus={}
for b,u,k,_ in rows: bus[b]=bus.get(b,0)+k
pp=bus.get('PP-1 208/120 V',0); xf=next(s for s in (15,30,45,75,112.5) if s>=pp/PF*1.25)
gen=sum(k for _,_,k in src); demand=sum(bus.values())
out=[f"""# One line

Document number: AQS-ELEC-002
Revision: C
Date: 2026-10-15
Authority: graph Rev BH; AQS-PLAN-007 X-ELS-03. Generated by `docs-authority/_one_line.py` from the graph electrical edges, AQS-ELEC-003 and AQS-ELEC-004. Study. Not a PE stamp. Breakers per NEC 240.6(A) at 125 % of continuous current; power factor 0.90 (study).

| Rev | Description | Date |
| --- | --- | --- |
| C | Generated one-line against the load list; buses MCC-1 and PP-1; RECT-EW feeder. | 2026-10-15 |
| B | Inverter feeder 2 AWG; 400 kW retired. | 2026-10-12 |

```mermaid
flowchart LEFT_RIGHT_PLACEHOLDER
""".replace('LEFT_RIGHT_PLACEHOLDER','LR')]
for u,sid,k in src: out.append(f'  {u}["{u} {k:.2f} kW"] -->|{sid}| BUS')
out.append(f'  BUS(["SOL_ARK_60K 480 V 3φ, {INVTXT}"])')
out.append(f'  BUS --> MCC["MCC-1 480 V {bus.get("MCC-1 480 V",0):.1f} kW"]')
out.append(f'  BUS --> XF["T-1 {xf} kVA 480–208/120 V"] --> PP["PP-1 {pp:.1f} kW"]')
for u,(sid,kw) in fed.items(): out.append(f'  BUS -->|{sid}| {u.replace("-","_")}["{u} {kw:.2f} kW"]')
out.append(f'  BUS --> RECTEW["RECT-EW 9 × 6 V DC channels, {rect["Pac_kW"]:.1f} kW AC"]')
out.append('```\n')
out.append('| Bus | Load | kW | A | Breaker A | Basis |\n| --- | --- | --- | --- | --- | --- |')
for b,u,k,bs in sorted(rows,key=lambda r:(r[0],-r[2])):
    kp=max(k,PK.get(u) or 0); a=amps(kp) if '480' in b else amps(kp,3,208); bs=bs+(f'; feeder on peak {kp:.1f} kW' if kp>k else ''); out.append(f'| {b} | {u} | {k:.2f} | {a:.1f} | {brk(a)} | {bs} |')
out.append(f"""
## Totals

| Item | kW |
| --- | --- |
| Sources on the bus (graph edges) | {gen:.2f} |
| Demand on the bus (this page) | {demand:.2f} |
| Inverter rating (SOL_ARK_60K) | 60.0 |
| Shortfall against sources | {demand-gen:.2f} |
| Shortfall against inverter | {demand-60:.2f} |

## Findings

1. Bus demand at the bounding EW case is {demand:.1f} kW against {gen:.1f} kW of graph sources and {INVTXT}. The RECT-EW feeder alone is {rect['Pac_kW']:.1f} kW. Supply nameplates follow AQS-ELEC-007 bounding case (X-RSZ-02); the gap between graph sources and bus demand is loads without graph feeds, booked in the X-RSZ-07 sweep.
2. {sum(1 for r in rows if 'study share' in r[3])} feeders are study shares; they become calculated as each unit's task 02 closes (X-ELS-02).
3. Most loads have no electrical edge on the graph; only RECTIFIER (S17) and GROW_BED (S20) do. The one-line assigns the rest to MCC-1 and PP-1 by size. Graph electrical edges for them belong to X-ELS-02.
4. The 48 V shop and farm rails stay as AQS-PWR-001 behind RECTIFIER (S17). MFG_SHOP's 12 kW share may overlap the 20 kW shop rail; the overlap is resolved with MFG_SHOP task 02.
""")
open('docs-authority/ONE_LINE.md','w').write('\n'.join(out)+'\n')
print(json.dumps(dict(bus=bus,xf=xf,gen=gen,demand=demand)))
