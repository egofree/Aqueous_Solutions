"""AQS-BLD-015 lifting and cranes (X-BLD-06, A-M-192). Heaviest single lift per level from the AQS-BLD-013 empty weights
(docs-authority/inventory/STRUCT_ROWS.json). Units built in place are not lifted whole: tanks and reservoirs (fabricated in place), gas-receiver tube racks (set as two halves), the PV
array (modules lifted one at a time), farm beds and habitation rooms (assembled from parts), headers (spool by spool). Hoist rated load =
next standard size >= (heaviest lift x (1 + rigging allowance)); load test 125 % (ASME_B30_2 2-2.2.2); maintenance service CMAA70_2020
class C. Two hoists per level where the level has more than one lift zone, so a failed hoist does not stop maintenance (redundancy rule).
Run: python3 docs-authority/_lifting.py"""
import json, os, sys, collections
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); os.chdir(R); sys.path.insert(0, R)
from flow_graph.param.refs import cite
for k in ('ASME_B30_2', 'ASME_B30_16', 'CMAA70_2020'): cite(k)
g = json.load(open('flow_graph/plant_flow_graph.json')); C = {n['unit_id']: n.get('class') for n in g['nodes']}; N = {n['unit_id']: n for n in g['nodes']}
# X-FARM: the raceway basin is a lined excavation; the hab rooms assemble from panels
INPLACE = {'tank', 'pv', 'farm', 'hab', 'building', 'boundary', 'header', 'recycle_pipe', 'shop', 'dock', 'duckweed', 'room'}
SIZES = [0.25, 0.5, 1.0, 2.0, 3.2, 5.0, 10.0, 16.0, 20.0]; RIG = 0.10
rows = json.load(open('docs-authority/inventory/STRUCT_ROWS.json')); L = collections.defaultdict(list)
for r in rows:
    b = r['unit'].split('/')[0]
    if C.get(b) in INPLACE or b.startswith('HYDRO_RES'): continue
    ds = ((N.get(b) or {}).get('params') or {}).get('design') or {}
    if ds.get('banks'): r = dict(r, unit=r['unit'] + ' (one bank half)', empty_kg=r['empty_kg']/2)   # tube racks are set as two manifolded halves
    L[r['level']].append(r)
md = ['# Lifting and cranes', '', 'Document number: AQS-BLD-015', 'Revision: B', 'Date: 2026-10-25',
      'Authority: AQS-PLAN-007 task X-BLD-06; assumption A-M-192. Generated by `docs-authority/_lifting.py` from the '
      'structural loads (AQS-BLD-013). Do not edit this page by hand. Study.', '',
      '| Rev | Description | Date |', '|---|---|---|',
      '| A | First issue | 2026-10-16 |',
      '| B | Purpose and scope added; text rewritten to the documentation style guide (AQS-DOC-002); the list of levels without lifted equipment no longer contradicts the table. No hoist size changed. | 2026-10-25 |', '',
      '## 1. Purpose and scope', '',
      'Equipment in the plant has to be lifted into place when it is installed and lifted out when it is replaced. '
      'This page sizes the hoist on each level of the building from the heaviest single item that must be lifted '
      'there. The empty weights come from the structural loads (AQS-BLD-013).', '',
      'Units that are built in place are lifted in parts and are not listed. They are tanks and reservoirs, which are '
      'fabricated in place; the PV array, whose modules are lifted one at a time; farm beds and habitation rooms, '
      'which are assembled from parts; and headers, which are installed spool by spool. Gas-receiver tube racks are '
      'set as two manifolded halves, so the lift is one half.', '',
      '## 2. Sizing rule', '',
      f'The rated load of a hoist is the next standard size at or above the heaviest lift plus a rigging allowance of '
      f'{RIG*100:.0f} %. Each hoist is load-tested at 125 % of its rated load (ASME B30.2). Underhung hoists follow '
      'ASME B30.16, and the service class is CMAA 70 class C, which covers maintenance duty. A level with more than '
      'ten lifted items has two hoists, so that a failed hoist does not stop maintenance.', '',
      '## 3. Hoists by level', '',
      'Table 3.1 gives, for each level with lifted equipment, the heaviest lift, the next three heaviest, and the '
      'hoist selected.', '',
      'Table 3.1. Hoists by level', '',
      '| Level | Heaviest lift | Empty mass (kg) | Next three (kg) | Hoist rated load (t) | Test load (t) | Hoists |', '|---|---|---|---|---|---|---|']
for lv in sorted(L):
    v = sorted(L[lv], key=lambda r: -r['empty_kg']); h = v[0]; need = h['empty_kg']*(1 + RIG)/1000; t = next(s for s in SIZES if s >= need)
    md.append(f"| {lv} | {h['unit']} | {h['empty_kg']:.0f} | " + ', '.join(f"{x['unit']} {x['empty_kg']:.0f}" for x in v[1:4]) + f" | {t} | {1.25*t:.2f} | {2 if len(v) > 10 else 1} |")
md += ['', 'Levels that do not appear in Table 3.1, such as the reservoir levels, have no lifted equipment; their '
       'cells are entered through a hatch for inspection. On the roof, PV modules are carried by hand or lifted by a '
       '0.25 t davit at the roof stair.', '',
       'The hoist beams and their supports are loads on the structural frame (task X-BLD-01) at the rated load '
       'multiplied by an impact factor of 1.25.']
open('docs-authority/LIFTING.md', 'w').write('\n'.join(md) + '\n'); print(md[-4:-2])
