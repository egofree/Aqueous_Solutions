"""AQS-EGR-002 extension hall egress (X-STD-01). Most restrictive of NFPA 101-2027 and IBC 2027 governs (AQS-EGR-001 2.1).
Occupancy: general industrial, ordinary hazard (hall programme open; NFPA 101 40.1.4.1.1 / IBC F-1), sprinklered throughout to NFPA 13.
Limits: travel 76.2 m (NFPA 101 Table 40.2.6 ordinary hazard sprinklered 250 ft; IBC 1017.2.2 would allow 122 m at 7.3 m clear, so NFPA governs);
common path 30.5 m (NFPA 101 40.2.5, 100 ft sprinklered); occupant load 9.29 m2/person gross (NFPA 101 Table 7.3.1.2 industrial, 100 ft2;
IBC Table 1004.5 same); four exits minimum above 1000 occupants (NFPA 101 7.4.1.2, IBC Table 1006.3.3); egress capacity 5.1 mm/person for
level components and doors (NFPA 101 Table 7.3.3.1, 0.2 in); door clear width >= 813 mm per leaf (NFPA 101 7.2.1.2.3, 32 in).
Layout: exterior doors on the hall perimeter and an interior 2 h exit passageway (NFPA 101 7.2.6, IBC 1024) along the long axis at mid-depth,
discharging at both ends, with doors on both faces. Door spacing is solved so that the worst rectilinear travel on a 1 m grid is within the limit.
Writes docs-authority/HALL_EGRESS.md and the passageway block into flow_graph/placement_seed.json. Study; not a PE stamp."""
import json, math
LIM = 76.2; LOAD = 9.29; CAP = 0.0051; LEAF = 0.813; PAIR = 2*LEAF
g = json.load(open('flow_graph/plant_flow_graph.json')); rf = next(n for n in g['nodes'] if n['unit_id'] == 'PV_ARRAY')['params']['roof']
W, D = rf['footprint_mm'][0]/1000, rf['footprint_mm'][1]/1000; BX, BY = 24.0, 18.0          # base plate in the SW corner (own egress, AQS-EGR-001)
A = W*D - BX*BY; occ = math.ceil(A/LOAD)
pw = None
def doors(s, yp):
    """door points: perimeter (outside the base plate) every s m; passageway faces every s m."""
    P = []
    n = max(2, math.ceil(W/s)); P += [(W*(i+0.5)/n, D) for i in range(n)]                                   # north wall
    P += [(BX + (W-BX)*(i+0.5)/max(1, math.ceil((W-BX)/s)), 0.0) for i in range(max(1, math.ceil((W-BX)/s)))]   # south wall east of the plate
    m = max(2, math.ceil(D/s)); P += [(W, D*(i+0.5)/m) for i in range(m)]                                   # east wall
    P += [(0.0, BY + (D-BY)*(i+0.5)/max(1, math.ceil((D-BY)/s))) for i in range(max(1, math.ceil((D-BY)/s)))]   # west wall north of the plate
    k = max(2, math.ceil(W/s)); P += [(W*(i+0.5)/k, yp) for i in range(k)]                                  # passageway doors (both faces)
    return P
def worst(P, yp, wp):
    w = 0.0; wpt = None
    for x in range(0, int(W)+1, 2):
        for y in range(0, int(D)+1, 2):
            if x < BX and y < BY: continue
            if abs(y - yp) < wp/2: continue
            dmin = min(abs(x-a) + abs(y-b) for a, b in P)
            if dmin > w: w, wpt = dmin, (x, y)
    return w, wpt
yp = D/2
for s in range(90, 20, -5):
    P = doors(s, yp)
    w, wpt = worst(P, yp, 3.5)
    if w <= LIM: break
n_ext = len(P) - max(2, math.ceil(W/s))
share_pw = max(2, math.ceil(W/s))/len(P); occ_pw = math.ceil(occ*share_pw)
wp = max(1.12, occ_pw*CAP/2)                       # discharges at both ends; NFPA 101 7.2.6.4 width for the load served, 1120 mm minimum (7.3.4.1)
wp = math.ceil(wp*10)/10
occ_ext = occ - occ_pw; need_ext = occ_ext*CAP; have_ext = n_ext*PAIR
w, wpt = worst(doors(s, yp), yp, wp)
res = dict(W=W, D=D, A=A, occ=occ, spacing_m=s, worst_m=w, worst_at=wpt, doors_total=len(P), exterior_doors=n_ext, passageway_doors=len(P)-n_ext,
           passageway_w_m=wp, passageway_occ=occ_pw, ext_need_m=need_ext, ext_have_m=have_ext, exits=n_ext+2, pass_travel=w <= LIM, pass_capacity=have_ext >= need_ext, pass_exits=n_ext+2 >= 4)
S = 'flow_graph/placement_seed.json'; sd = json.load(open(S))
sd['blocks'] = [b for b in sd['blocks'] if b['block_id'] != 'EXIT_PASSAGE_HALL'] + [dict(block_id='EXIT_PASSAGE_HALL', level='L0', origin_mm=[0, int(yp*1000 - wp*500)], size_mm=[int(W*1000), int(wp*1000), 6000], unit_ids=[],
    source=f'X-STD-01 AQS-EGR-002: 2 h exit passageway (NFPA 101 7.2.6, IBC 1024), {wp} m clear, across the hall at mid-depth, discharging at both ends.')]
json.dump(sd, open(S, 'w'), indent=2, ensure_ascii=True)
