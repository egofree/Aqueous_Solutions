"""Cross-locale comparison (AQS-PLAN-011 section 5.6, task X-LOC-12). Generated from the committed
site profiles and the locale outputs under sites/<site_id>/: the scaling actions each profile takes,
the power portfolio each site balances, and the unit sizes that move between locales. A locale whose
outputs are missing is marked so; nothing is recomputed here that the locale run already proved.

    python3 docs-authority/_site_comparison.py [--write]   # docs-authority/SITE_COMPARISON.md"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); os.chdir(ROOT)
sys.path.insert(0, ROOT)
from flow_graph.param import site as S, scaling as SC, portfolio as PF

OUT = 'docs-authority/SITE_COMPARISON.md'
WATCH = [('PV_ARRAY', 'nameplate_kw', 'PV nameplate', 'kWp'),
         ('ZNBR2', 'kWh', 'zinc-bromine storage', 'kWh'),
         ('LIO_BAT', 'kWh', 'lithium-ion storage', 'kWh'),
         ('EXT_HALL', 'roof', None, None),
         ('RAD_PANEL', 'rated_kW', 'radiator duty', 'kW'),
         ('HYDRO_SET', 'params.volume_m3', None, None)]


def locale_graph(sid):
    p = f'sites/{sid}/flow_graph/plant_flow_graph.json'
    if not os.path.exists(p): return None
    return {n['unit_id']: n for n in json.load(open(p))['nodes']}


def main(write=False):
    sids = S.available()
    profs = {sid: S.load_profile(sid) for sid in sids}
    plans, errs = {}, {}
    for sid in sids:
        try: plans[sid] = SC.resolve(profs[sid])[0]
        except SystemExit as e: errs[sid] = str(e)[:80]
    graphs = {sid: locale_graph(sid) for sid in sids}

    L = ['# Site comparison', '', 'Document number: AQS-SITE-011', 'Revision: A', 'Date: 2026-10-26',
         'Licence: CERN-OHL-S-2.0.', '',
         'Generated by `docs-authority/_site_comparison.py` from the committed site profiles '
         '(`flow_graph/param/sites/`) and the locale outputs under `sites/<site_id>/` (X-LOC-12). '
         'Do not edit by hand. A locale whose outputs are not present is marked so.', '',
         f'Profiles: {len(sids)}. ' + ('All scaling resolutions pass.' if not errs else
                                       'Scaling resolutions failing: ' + ', '.join(sorted(errs)) + '.'), '',
         '## 1. Scaling actions', '',
         'Table 1 lists the units each locale eliminates or replaces, against the reference plant. '
         '`-` means the locale keeps the unit as designed.', '',
         'Table 1. Scaling actions by locale', '',
         '| Unit | ' + ' | '.join(sids) + ' |', '| --- ' * (len(sids) + 1) + '|']
    touched = sorted({a['target'] for sid in sids for a in SC.actions(profs[sid])})
    for u in touched:
        row = [u]
        for sid in sids:
            act = next((a for a in SC.actions(profs[sid]) if a['target'] == u), None)
            if not act: row.append('-'); continue
            what = act.get('replacement') or ('imported module' if act.get('import_path') else None)
            if not what:
                verb = act.get('action', '?')
                f = act.get('factor'); c = act.get('count')
                what = {'size': f"size x{f:g}" if isinstance(f, (int, float)) else 'size',
                        'duplicate': f"duplicate x{c}" if c else 'duplicate'}.get(verb, verb)
            row.append(what)
        L.append('| ' + ' | '.join(row) + ' |')

    L += ['', '## 2. Power portfolios', '',
          'Table 2 lists the primary sources, the storage that carries the worst stretch and the '
          'balancing mean generation per kW of demand (portfolio.balance), from each profile.', '',
          'Table 2. Portfolios', '',
          '| Site | Primary | Storage | Worst stretch | G/P |', '| --- ' * 5 + '|']
    for sid in sids:
        try:
            pf = PF.portfolio(profs[sid]); eta = 0.7
            g_per_kW = PF.mean_generation_per_kW(profs[sid], eta)
            prim = ', '.join(s['id'] for s in pf['sources'] if s['role'] == 'primary')
            sto = ', '.join(st['unit'] for st in pf['storage']) or '-'
            L.append(f'| {sid} | {prim} | {sto} | {pf["worst_stretch"]["kind"]} | {g_per_kW:.3f} |')
        except Exception as e:
            L.append(f'| {sid} | portfolio error: {str(e)[:40]} | | | | |')

    L += ['', '## 3. Unit sizes that move', '',
          'Table 3 lists the solved sizes that differ between locales, from the locale graphs under '
          '`sites/<site_id>/`. A value is the locale graph; `-` means the locale outputs are absent '
          'or the unit carries the reference value.', '',
          'Table 3. Sizes by locale', '',
          '| Quantity | ' + ' | '.join(sids) + ' |', '| --- ' * (len(sids) + 1) + '|']
    def pick(g, unit, key):
        if not g or unit not in g: return None
        p = g[unit].get('params', {})
        if key == 'roof':
            r = p.get('roof', {})
            return f'{r.get("footprint_m2", 0):.0f} m2 roof' if r else None
        v = p.get(key)
        return f'{v:g}' if isinstance(v, (int, float)) else None
    rows = [('PV nameplate', 'PV_ARRAY', 'nameplate_kw'), ('ZnBr2 storage', 'ZNBR2', 'kWh'),
            ('Li-ion storage', 'LIO_BAT', 'kWh'), ('Radiator duty', 'RAD_PANEL', 'rated_kW'),
            ('Roof footprint', 'PV_ARRAY', 'roof'), ('Hall load kW', 'EXT_HALL', 'continuous_kw')]
    for label, unit, key in rows:
        row = [label]
        for sid in sids:
            g = graphs[sid]
            if key == 'continuous_kw':
                ck = (g or {}).get(unit, {}).get('continuous_kw') or {}
                v = ck.get('value') if isinstance(ck, dict) else None
                row.append(f'{v:g}' if isinstance(v, (int, float)) else '-')
            else:
                v = pick(g, unit, key)
                row.append(v if v is not None else '-')
        L.append('| ' + ' | '.join(row) + ' |')

    L += ['', '## 4. Reading the comparison', '',
          'The reference plant is the baseline profile; a locale differs from it only where the site '
          'capabilities require it (AQS-PLAN-011 section 5). Section 1 shows the replacement logic: '
          'the Mars and LEO locales eliminate the same vent, combustion and gravity-bound set and '
          'share the replacement units; the Earth locales mostly keep the reference design and move '
          'the sizes. Section 3 shows how far the solved plant moves: the array grows with the '
          'resource and the stretch, the storage with the hours a site spends without its primary '
          'source.', '']
    txt = '\n'.join(L) + '\n'
    if write:
        open(OUT, 'w').write(txt); print(f'{OUT}: written')
    else:
        sys.stdout.write(txt)


if __name__ == '__main__':
    main('--write' in sys.argv)
