"""X-ASM-02 rigging plans, one per heavy lift (AQS-ASM-003).

Reads the heavy-lift roster emitted by X-ASM-01 (docs-authority/INSTALL_SEQUENCE.md section 2,
>= 1.0 t per lift) and issues one rigging plan per lift, with every rating taken verbatim from
the registered rules - no load path is invented:

  - mass per lift is the AQS-BLD-013 booked empty mass (tube racks halved, AQS-BLD-015 rule);
  - design load = mass per lift x (1 + 10 % rigging allowance) - the AQS-BLD-015 allowance rule;
  - the hoist is the level's booked hoist (AQS-BLD-015: rated = next standard size at or above the
    heaviest level lift + 10 % rigging; the plan asserts the booked rated covers this design load);
  - load test 125 % of rated (ASME B30.2 2-2.2.2, AQS-BLD-015); underhung hoists per ASME B30.16;
    maintenance service CMAA70 (2020) class C; hoist beams load the X-BLD-01 frame at rated x 1.25
    impact; two hoists per level with more than one lift zone;
  - lift points are named at the unit's work order: this study plan books the rigging duty, not
    the lug geometry - a load path (sling angle, lug placement) not modeled anywhere would be an
    invented load path, so it stays an explicit fabricator hold per lift.

Outputs docs-authority/RIGGING_PLANS.md. Run: python3 docs-authority/_rigging_plans.py
"""
import collections, json, os, re, sys

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(R, 'docs-authority'))
from _install_seq import hoist_book, graph_index, inplace, lift_kg  # noqa: E402

SIZES = [0.25, 0.5, 1.0, 2.0, 3.2, 5.0, 10.0, 16.0, 20.0]   # the AQS-BLD-015 standard hoist sizes
RIG = 0.10


def main():
    rows = json.load(open(os.path.join(R, 'docs-authority/inventory/STRUCT_ROWS.json')))
    book = hoist_book()
    classes, nodes = graph_index()

    lifts = []
    for r in rows:
        if inplace(r, classes):
            continue
        kg, suffix = lift_kg(r, nodes)
        if kg >= 1000.0:
            lifts.append((r['level'], r['unit'], kg, suffix))

    assert lifts, 'no heavy lifts found - the X-ASM-01 roster changed?'
    L = ['# Rigging plans', '',
         'Document number: AQS-ASM-003', 'Revision: A', 'Date: 2026-10-21',
         'Authority: AQS-PLAN-007 X-ASM-02 (X-ASM-01 done). Generated by `docs-authority/_rigging_plans.py` from the '
         'AQS-ASM-002 heavy-lift roster and the AQS-BLD-015 hoist book. Study. Not a PE stamp.',
         '',
         '| Rev | Description | Date |', '| --- | --- | --- |',
         '| A | First issue: one plan per lift over 1000 kg, ratings verbatim from AQS-BLD-015. | 2026-10-21 |']
    L += ['', '## 1. Rules (registered, applied verbatim)', '',
          '- Rigging allowance 10 %; design load = mass per lift x 1.10 (AQS-BLD-015).',
          '- The hoist is the level\u2019s booked hoist (AQS-BLD-015 duty book verbatim); this plan asserts the booked rated',
          '  load covers the design load - it does not re-pick the hoist.',
          '- Load test 125 % of rated (ASME B30.2 2-2.2.2); underhung hoists per ASME B30.16; maintenance service CMAA70',
          '  (2020) class C; two hoists per level with more than one lift zone (AQS-BLD-015 redundancy rule).',
          '- Hoist beams and supports load the X-BLD-01 frame at rated load x 1.25 impact (AQS-BLD-015).',
          '- **Lift points are named at the unit work order, not here.** A sling angle or a lug position not modeled by any',
          '  registered artifact would be an invented load path; each plan therefore ends at the duty numbers and names the',
          '  lift-point design as an open fabricator item on that unit\u2019s work order.',
          '- A lift is rigged to its seat number in the AQS-ASM-002 sequence; connections are made after seating, never',
          '  rigged as a hanging load.']

    L += ['', '## 2. Roster', '',
          'The X-ASM-002 heavy-lift roster reproduced with the plan numbers (one plan per lift follows):', '',
          '| Lift | Level | Unit | Mass per lift kg | Design load kg | Hoist rated t (book) | Test load t |', '|---|---|---|---|---|---|---|']
    counters = collections.Counter(lv for lv, *_ in lifts)
    for n, (lv, u, kg, suffix) in enumerate(lifts, 1):
        b = book.get(lv, {})
        design = kg * (1 + RIG)
        rated = b.get('hoist_t')
        assert rated and rated * 1000.0 >= design, f'{u}: booked hoist {rated} t under design load {design:.0f} kg'
        L.append(f'| {n} | {lv} | {u}{suffix} | {kg:.0f} | {design:.0f} | {rated} | {b.get("test_t")} |')

    L += ['', '## 3. Plans', '']
    for n, (lv, u, kg, suffix) in enumerate(lifts, 1):
        b = book.get(lv, {})
        design = kg * (1 + RIG)
        L += [f'### Plan {n}: {u}{suffix} to {lv}', '',
              f'- **Mass per lift**: {kg:.0f} kg (AQS-BLD-013 booked empty mass{", one bank half" if suffix else ""}).',
              f'- **Design load**: {kg:.0f} x 1.10 = {design:.0f} kg.',
              f'- **Hoist**: the {lv} booked hoist, rated {b.get("hoist_t")} t, load-tested to {b.get("test_t")} t '
              f'(125 % of rated, ASME B30.2) - covers the design load with margin '
              f'{(b.get("hoist_t") * 1000.0 - design) / design * 100:.0f} %.',
              f'- **Lift points**: open item on the {u} unit work order (no lug geometry is modeled in this study plan).',
              f'- **Sequence context**: seat per section {lv} of AQS-ASM-002; hoist runs the lightest-remaining duty after',
              '  the heavier lifts of the level are seated; nothing hangs while connections are made.']
    L += ['', f'## 4. Coverage', '',
          f'- One plan per lift over 1000 kg: {len(lifts)} plans, matching the AQS-ASM-002 roster exactly.',
          '- Implementation is openly noted per the repo rules: the duty numbers are engineered (AQS-BLD-015 verbatim);',
          '  the lug design, the sling set and the shop execution stay named holds on each work order.']
    open(os.path.join(R, 'docs-authority/RIGGING_PLANS.md'), 'w').write('\n'.join(L) + '\n')
    print(dict(plans=len(lifts), levels=dict(counters)))


if __name__ == '__main__':
    main()
