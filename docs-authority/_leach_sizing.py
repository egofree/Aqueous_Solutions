       '## 5. Mass', '',
       'From the model, by part: CPVC tank 297.6 kg, FRP belts 66.5 kg, glass coil 24.8 kg, PTFE pads 2.5 kg, PVDF agitator 9.6 kg; empty 401 kg; operating about 2760 kg.', '',
