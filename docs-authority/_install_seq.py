"""X-ASM-01 ordered lift and connect sequence per level (AQS-ASM-002).

Reads the structural load rows (docs-authority/inventory/STRUCT_ROWS.json, AQS-BLD-013: unit,
level, empty/operation/test kg), the hoist duty book (docs-authority/LIFTING.md, AQS-BLD-015 from
X-BLD-06) and the live graph (present edges), and issues, per physical level in the build order
L-2 -> L-1 -> L0 -> L1 -> R1 -> R2 -> R3 -> ROOF:

  1. the ordered lift sequence: Kahn topological order over the present edges among the level's
     units (upstream units seat first so connections are made to seated partners), heaviest-first
     tiebreak (the hoist headroom argument of AQS-BLD-015: the heaviest lift goes up on the
     emptiest floor), with every unit's inbound/outbound connection list named;
  2. the connect rows per unit: present graph edges (stream id, partner, what it carries) split
     into same-level (made in sequence) and cross-level (made after both ends are seated);
  3. cross-checks: the level's heaviest lift and empty mass against the AQS-BLD-015 hoist duty row,
     and every unit present in STRUCT_ROWS connecting to at least one edge or standing as an
     accounting node boundary.

The registered rules the sequence rests on: hoist rated load = next standard size at or above the
heaviest lift + 10 % rigging, load test 125 % of rated (ASME B30.2); hoist beams load the X-BLD-01
frame at rated x 1.25 impact (both carried verbatim from AQS-BLD-015). Units between lifts are
leak/pressure-tested per AQS-STD-001 sec. 4 before the next lift blocks access.

Outputs docs-authority/INSTALL_SEQUENCE.md. Heavy-lift rigging plans are X-ASM-02 (AQS-ASM-003);
this doc names the roster of lifts that needs them. Run: python3 docs-authority/_install_seq.py
"""
import collections, json, os, re

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LEVELS = ['L-2', 'L-1', 'L0', 'L1', 'L2', 'R1', 'R2', 'R3', 'ROOF']

## the built-in-place classes of AQS-BLD-015 (docs-authority/_lifting.py): these are assembled on the
# level, not lifted whole, so the hoist book - and this sequence - does not count them as lifts.
# The pytest gate asserts this set stays identical to the one in _lifting.py.
# X-FARM: the raceway basin is a lined excavation; the hab rooms assemble from panels
INPLACE = {'tank', 'pv', 'farm', 'hab', 'building', 'boundary', 'header', 'recycle_pipe', 'shop', 'dock', 'duckweed', 'room'}


def graph_index():
    g = json.load(open(os.path.join(R, 'flow_graph/plant_flow_graph.json')))
    classes = {n['unit_id']: n.get('class') for n in g['nodes']}
    nodes = {n['unit_id']: n for n in g['nodes']}
    return classes, nodes


def inplace(r, classes):
    """True when the unit is built on the level, not lifted whole (AQS-BLD-015 rule)."""
    base = r['unit'].split('/')[0]
    return classes.get(base) in INPLACE or base.startswith('HYDRO_RES')


def lift_kg(r, nodes):
    """Mass per lift: tube racks are set as two manifolded halves (AQS-BLD-015 rule)."""
    base = r['unit'].split('/')[0]
    ds = ((nodes.get(base) or {}).get('params') or {}).get('design') or {}
    half = 2 if ds.get('banks') else 1
    if half == 2:
        return r['empty_kg'] / half, ' (one bank half)'
    return r['empty_kg'], ''



def hoist_book():
    """Level -> (heaviest unit, empty kg, hoist rated t) from the generated AQS-BLD-015 table."""
    out = {}
    for line in open(os.path.join(R, 'docs-authority/LIFTING.md')):
        # heaviest-lift cell may carry a note, e.g. "CRYO_H2 (one bank half)"
        m = re.match(r'^\| (L-?\d+|ROOF) \| ([^|]+?) \| ([\d.]+) \| [^|]*? \| ([\d.]+) \| ([\d.]+) \| (\d+) \|$', line)
        if m:
            out[m.group(1)] = dict(heaviest=m.group(2), empty_kg=float(m.group(3)),
                                   hoist_t=float(m.group(4)), test_t=float(m.group(5)), hoists=int(m.group(6)))
    return out


def main():
    rows = json.load(open(os.path.join(R, 'docs-authority/inventory/STRUCT_ROWS.json')))
    by_unit = {r['unit']: r for r in rows}
    book = hoist_book()
    classes, nodes = graph_index()
    g = json.load(open(os.path.join(R, 'flow_graph/plant_flow_graph.json')))
    present_all = [e for e in g['edges'] if e.get('presence') == 'present']
    present = [e for e in present_all if
               e.get('from_unit_id') in by_unit and e.get('to_unit_id') in by_unit]

    L = ['# Install sequence', '',
         'Document number: AQS-ASM-002', 'Revision: A', 'Date: 2026-10-21',
         'Authority: AQS-PLAN-007 X-ASM-01 (X-BLD-06 and unit task 13 done). Generated by `docs-authority/_install_seq.py` '
         'from AQS-BLD-013 structural rows, AQS-BLD-015 hoist duty and the graph. Study. Not a PE stamp.',
         '',
         '| Rev | Description | Date |', '| --- | --- | --- |',
         '| A | First issue: ordered lift and connect sequence per level, heavy-lift roster for AQS-ASM-003. | 2026-10-21 |']
    L += ['', '## 1. Rules', '',
          '- Build order of levels: L-2 -> L-1 -> L0 -> L1 -> R1 -> R2 -> R3 -> ROOF (foundation out, reservoir ring last).',
          '- Within a level: Kahn topological order over the present graph edges among that level\'s units - a unit seats',
          '  after its same-level process inputs, so every connection is made to a partner already seated. The tiebreak among',
          '  simultaneously-available units is heaviest-first: the hoist lifts the largest mass on the emptiest floor (AQS-BLD-015',
          '  beam-load argument: rated load x 1.25 impact on the X-BLD-01 frame).',
          '- Hoist duty is the AQS-BLD-015 book verbatim: rated load = next standard size at or above the heaviest lift + 10 %',
          '  rigging; load test 125 % of rated (ASME B30.2).',
          '- Built-in-place classes are assembled on the level, not lifted whole (the AQS-BLD-015 rule: tanks and reservoirs',
          '  fabricated in place, the PV array module by module, farm beds and habitation rooms from parts, headers spool by',
          '  spool); they still appear in the seat order - their connections are made as they are built - but they carry no',
          '  hoist duty. Gas-receiver tube racks are set as two manifolded halves (the mass per lift is half the booked mass).',
          '- A unit is leak/pressure-tested per AQS-STD-001 sec. 4 after its connections are made, before the next lift blocks access.',
          '- Cross-level connections are named per unit (made after both ends are seated), not sequenced globally.',
          '- Partners with no structural row (module interiors, headers, stores, product sinks, docks - outside the',
          '  AQS-BLD-013 census) are named with "no structural booking": the connection lands with the module or the',
          '  header they belong to, at that module\u2019s set.']


    L += ['', '## 2. Heavy-lift roster (also the work order of AQS-ASM-003)', '',
          '| Level | Heavy lifts: unit / empty kg (>= 1.0 t of the level book) | Hoist rated t | Test load t |', '|---|---|---|---|']
    heavy = collections.defaultdict(list)
    lifts = []   # (level, unit, per-lift kg) for the hoisted units only
    for r in rows:
        if inplace(r, classes):
            continue
        kg, suffix = lift_kg(r, nodes)
        lifts.append((r['level'], r['unit'], kg, suffix))
        if kg >= 1000.0:
            heavy[r['level']].append((r['unit'], kg, suffix))
    diffs = []
    for lv in LEVELS:
        b = book.get(lv)
        hoisted_lv = [(k, u) for (llv, u, k, _s) in lifts if llv == lv]
        top_kg = max((k for k, _u in hoisted_lv), default=0.0)
        top_u = max(hoisted_lv, key=lambda x: x[0])[1] if hoisted_lv else None
        if b and (top_u != b['heaviest'].split(' (')[0] or abs(top_kg - b['empty_kg']) > 0.5):   # the book may annotate, e.g. "(one bank half)"
            diffs.append((lv, f"book names {b['heaviest']} {b['empty_kg']:.0f} kg; sequence top hoisted lift is {top_u} {top_kg:.0f} kg"))
        hl = '; '.join(f'{u} / {kg:.0f}{suf}' for u, kg, suf in sorted(heavy.get(lv, []), key=lambda x: -x[1]))
        if not hl and b:
            hl = f'{b["heaviest"]} / {b["empty_kg"]:.0f} (level book; under the 1.0 t roster cut)'
        L.append(f'| {lv} | {hl or "none"} | {b.get("hoist_t", "-") if b else "-"} | {b.get("test_t", "-") if b else "-"} |')
    if diffs:
        L += ['', 'Cross-check mismatch between the level book and the hoisted lifts:'] + [f'- {lv}: {why}' for lv, why in diffs]

    ncross_fail = []
    for lv in LEVELS:
        lvl = [r for r in rows if r['level'] == lv]
        if not lvl:
            continue
        indeg = collections.Counter()
        for e in present:
            if by_unit[e['to_unit_id']]['level'] == lv and by_unit[e['from_unit_id']]['level'] == lv:
                indeg[e['to_unit_id']] += 1
        tiein = collections.defaultdict(int)
        heap = collections.deque(sorted((r for r in lvl if indeg[r['unit']] == 0), key=lambda r: -r['empty_kg']))
        done, seq = set(), []
        counts = collections.Counter(e['to_unit_id'] for e in present
                                     if by_unit[e['to_unit_id']]['level'] == lv == by_unit[e['from_unit_id']]['level'])
        while heap or any(v > 0 for v in indeg.values()):
            if heap:
                u = heap.popleft()
                if u['unit'] in done:
                    continue
            else:
                # same-level recycle loops close physical cycles: seat the remaining unit with the
                # fewest remaining same-level inputs (heaviest tiebreak); its unseated inbound edges
                # go to the tie-in pass after both ends are seated (spools are prefabricated).
                rem = sorted((by_unit[u] for u in indeg if indeg[u] > 0 and u not in done
                              and by_unit[u]['level'] == lv),
                             key=lambda r: (counts[r['unit']], -r['empty_kg']))
                if not rem:
                    break
                u = rem[0]
                tiein[u['unit']] = indeg[u['unit']]
                indeg[u['unit']] = 0
            done.add(u['unit'])
            seq.append(u)
            for e in present:
                if e['from_unit_id'] == u['unit'] and by_unit[e['to_unit_id']]['level'] == lv:
                    indeg[e['to_unit_id']] -= 1
                    if indeg[e['to_unit_id']] == 0 and e['to_unit_id'] not in done:
                        r2 = by_unit[e['to_unit_id']]
                        heap.append(r2)
            heap = collections.deque(sorted(heap, key=lambda r: -r['empty_kg']))
        if len(done) != len(lvl):
            # zero-flow units (trace supplements, standby equipment) have no mass-flow
            # ordering constraint: they are placed at the end of the level sequence
            leftover = sorted((r for r in lvl if r['unit'] not in done), key=lambda r: -r['empty_kg'])
            for r in leftover:
                seq.append(r)
                done.add(r['unit'])

        L += [f'', f'## {lv} ({len(lvl)} unit{"s" if len(seq) != 1 else ""}, hoist {b.get("hoist_t", "-") if (b := book.get(lv)) else "-"} t)', '']
        L.append('| Seq | Unit | Empty kg | Operation kg | Placed by | Same-level connections | Cross-level connections |')
        L.append('|---|---|---|---|---|---|---|')
        for i, r in enumerate(seq, 1):
            u = r['unit']
            u_edges = [e for e in present_all if e['from_unit_id'] == u or e['to_unit_id'] == u]
            same = [(e['stream_id'], e['to_unit_id'] if e['from_unit_id'] == u else e['from_unit_id'])
                    for e in u_edges if e['from_unit_id'] in by_unit and e['to_unit_id'] in by_unit
                    and by_unit[e['from_unit_id']]['level'] == lv == by_unit[e['to_unit_id']]['level']]
            crs = []
            for e in u_edges:
                p = e['to_unit_id'] if e['from_unit_id'] == u else e['from_unit_id']
                if p in by_unit:
                    if by_unit[p]['level'] != lv:
                        crs.append((e['stream_id'], p, by_unit[p]['level']))
                else:
                    # partner with no structural booking (module interior, header, store, product
                    # sink, dock): the connection lands with the module or header it belongs to
                    crs.append((e['stream_id'], p, 'no structural booking'))
            if not u_edges:
                ncross_fail.append(u)
            same_s = '; '.join(f'{s} -> {t}' for s, t, *_ in sorted(same)) or 'initial feed'
            crs_s = '; '.join(f'{s} -> {t} ({lv2})' for s, t, lv2 in sorted(crs)) or '-'
            L.append(f'| {i} | {u} | {r["empty_kg"]:.0f} | {r["op_kg"]:.0f} | '
                     f'{"built in place" if inplace(r, classes) else "hoist"} | {same_s} | {crs_s} |')
        if tiein:
            L += [f'', f'Recycle-loop tie-in pass: {sum(tiein.values())} same-level connections of {sorted(tiein)} are made after both ends are seated (spools prefabricated).']

    L += ['', '## Coverage', '',
          f'- All {len(rows)} structural-row units sequenced across the {len(LEVELS)} levels.',
          f'- Units with no process edge at all (boundaries and flow-side nodes without placements): {len(ncross_fail)} '
          + (f'- first: {", ".join(sorted(ncross_fail)[:6])}...' if ncross_fail else ''),
          '- Cross-check against AQS-BLD-015 hoist rows: '
          + ('clean, no level mismatch' if not diffs else f'{len(diffs)} mismatch(es) listed in section 2')]
    open(os.path.join(R, 'docs-authority/INSTALL_SEQUENCE.md'), 'w').write('\n'.join(L) + '\n')
    print(dict(levels=len(LEVELS), units=len(rows), heavy=sum(len(v) for v in heavy.values()), mismatch=len(diffs)))


if __name__ == '__main__':
    main()
