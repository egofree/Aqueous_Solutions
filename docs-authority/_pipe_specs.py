"""X-INV-04-PF-01..18 pipe-family production plans (AQS-INV-006).

One production plan per pipe family in inventory/PIPE_FAMILIES.csv (AQS-INV-003), joined to the
issued authorities rather than re-deriving them:

  - class basis and ratings come from the AQS-PIP-003 class sheets (letters P1..P5, M1, M2, F1);
  - joint procedures come from the AQS-WLD-002 WPS register, keyed by (material, joint_type) -
    the same eight procedures the register issues (solvent, fusion, butt weld, butt-and-strap);
  - the making-route disposition is stated honestly: the graph books no plastic pipe extrusion
    line and no tube mill (EXTRUDE is the 50 t billet/rod/profile press feeding WIRE_DRAW;
    FILM_CAST is the 0.14 kg/d PVDF cast sheet line), so stock is bought to the family standard
    and the shop plan covers identity receipt, cut to the registered stock lengths with the
    booked offcut budget, fittings disposition, joint execution and the class test. In-house
    extrusion or a tube mill is an open capital option (would need a new booked machine and a
    unit task); it is named, not assumed.

Fittings: bought to the family fitting standard (socket D2467/F439, butt-fusion D3261,
ISO 10931/15494 stub ends, wrought ASME B16.9 LR elbows with A403/A234 material, B16.5 flanges);
pipework-grade FRP (F1) elbows and stub ends are contact-moulded in the shop to ASTM D5421,
which is the same laminate discipline the class sheet and WPS-08 issue.

Outputs docs-authority/PIPE_SPECS.md. Run: python3 docs-authority/_pipe_specs.py
"""
import collections, os, re, sys

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); os.chdir(R)

FAM = list(__import__('csv').DictReader(open('docs-authority/inventory/PIPE_FAMILIES.csv')))
assert FAM, 'no pipe families'

# the class sheets of AQS-PIP-003: letter -> sheet title (the sheet itself carries the rating basis)
CLS = {}
for line in open('docs-authority/PIPING_CLASSES.md'):
    m = re.match(r'^\| (P[1-5]|M[12]|F1) \| ([^|]+) \|', line)
    if m and m.group(1) not in CLS:
        CLS[m.group(1)] = m.group(2).strip()

# the issued joint procedures of AQS-WLD-002: (material, joint_type) -> WPS id and process
WPS = {}
for line in open('docs-authority/WPS_REGISTER.md'):
    m = re.match(r'^\| (WPS-\d+) \| ([^|]+) \| ([^|]+) \| \d+ \| \d+ \| ([^|]+) \|', line)
    if m:
        WPS[(m.group(2).strip(), m.group(3).strip())] = (m.group(1), m.group(4).strip())

MAKING = ('No unit on the plant graph extrudes plastic pipe or forms metal tube. EXTRUDE presses copper and aluminium '
          'rod and profile for WIRE_DRAW, and FILM_CAST casts PVDF sheet. Pipe is therefore bought to the family standard '
          'and class sheet. Making pipe in house remains an open capital option; it would need a new unit on the graph and '
          'its own task, and this page does not assume it.')

md = ['# Pipe family production plans', '',
      'Document number: AQS-INV-006', 'Revision: B', 'Date: 2026-10-29',
      'Generated by `docs-authority/_pipe_specs.py` from `inventory/PIPE_FAMILIES.csv` (AQS-INV-003), the class sheets of '
      'AQS-PIP-003 and the welding procedure register AQS-WLD-002. Do not edit by hand; change the generator or its inputs and '
      'run `python3 -m flow_graph.param.regen`.',
      'Authority: tasks X-INV-04-PF of AQS-PLAN-007. Study. Not a PE stamp.',
      '',
      '| Rev | Description | Date |', '| --- | --- | --- |',
      '| A | First issue: one production plan per pipe family, with quantities, cut plan, fittings, welding procedures and class test | 2026-10-21 |',
      '| B | Purpose and scope added; the rules and each family plan written as sentences; the fixed family count in the coverage section replaced by the count from the inventory | 2026-10-29 |',
      '', '## 1. Purpose and scope', '',
      'This page gives the production plan of each pipe family in the pipe inventory AQS-INV-003. A pipe family is the pipe of one '
      'piping class, size and material. For each family the plan states how much pipe is bought, how it is cut, which fittings it '
      'needs, which welding procedure (WPS) joins it and how it is tested. The material, fitting standard, temperature rating and '
      'design basis of each class are given in its class sheet in AQS-PIP-003 and are not repeated here.']

tot_m = sum(float(f['pipe_m']) for f in FAM)
tot_len = sum(int(f['stock_lengths_6m']) for f in FAM)
tot_off = sum(float(f['offcut_m']) for f in FAM)
tot_el = sum(int(f['elbows_90']) for f in FAM)
tot_fl = sum(int(f['flanges']) for f in FAM)
tot_j = sum(int(f['joints']) for f in FAM)
md += ['', '## 2. Summary and rules', '',
       f'The inventory has {len(FAM)} families with {tot_m:,.1f} m of pipe in {sum(int(f["lines"]) for f in FAM)} lines. The pipe is '
       f'delivered as {tot_len} stock lengths of 6.096 m, with a cutting allowance of {tot_off:,.1f} m, which is '
       f'{tot_off / tot_m * 100:.1f} % of the installed length. The families need {tot_el} elbows and {tot_fl} flange sets and have '
       f'{tot_j} joints. Every figure is taken line by line from AQS-INV-003.',
       '',
       'The following rules apply to every family.', '',
       '1. ' + MAKING,
       '2. Fittings are bought to the fitting standard of the family: socket fittings to ASTM D2467 or F439, butt-fusion fittings to '
       'ASTM D3261 or ISO 10931 and ISO 15494 with stub ends and backing rings, wrought long-radius elbows to ASME B16.9 in A403 or '
       'A234 material, and flanges to ASME B16.5 in A182 or A105 material. The elbows and stub ends of the FRP class F1 are '
       'contact-moulded in the shop to ASTM D5421, under the laminating rules of sheet F1 and WPS-08, which include a laminator '
       'demonstration to Part 7 of [ASME_RTP1].',
       '3. Joints are made to the issued WPS of AQS-WLD-002 for the material and joint type. The extent of examination is that of the '
       'register row, which is 5 % random examination for normal fluid service under paragraph 341.4.1 of ASME B31.3.',
       '4. On receipt, the pipe is checked against the family standard. It is then tested to its class sheet in AQS-PIP-003, which '
       'is a hydrostatic test as stated on the sheet. Solvent-cemented and fused joints are inspected after the cure time in the WPS '
       'and before they are covered.']

md += ['', '## 3. Families', '', 'Table 3.1 lists the families with their quantities and welding procedure.', '',
       'Table 3.1. Pipe families', '',
       '| Family | Class | DN | Material | Pipe m | Lines | Stock 6.096 m | Offcut m | Joints | WPS |',
       '|---|---|---|---|---|---|---|---|---|---|']
for f in FAM:
    key = (f['material'], f['joint_type'])
    assert key in WPS, f'{f["family"]}: no issued WPS for {key}'
    assert f['cls'] in CLS, f'{f["family"]}: class {f["cls"]} not in AQS-PIP-003'
    md.append(f"| {f['family']} | {f['cls']} | {f['DN']} | {f['material']} | {f['pipe_m']} | {f['lines']} | "
              f"{f['stock_lengths_6m']} | {f['offcut_m']} | {f['joints']} | {WPS[key][0]} |")

md += ['', '## 4. Family plans', '', 'Each subsection gives the plan of one family. The rules of section 2 apply to every family.', '']
for f in FAM:
    w, proc = WPS[(f['material'], f['joint_type'])]
    md += [f"### {f['family']}: {f['cls']} DN{f['DN']}, {f['material']}", '',
           f"The family has {f['pipe_m']} m of pipe in {f['lines']} lines, cut from {f['stock_lengths_6m']} stock lengths of 6.096 m "
           f"with a cutting allowance of {f['offcut_m']} m; the off-cuts return to the store for spool pieces. The pipe is bought "
           f"mill stock to class sheet {f['cls']} of AQS-PIP-003 ({CLS[f['cls']]}).",
           f"It needs {f['elbows_90']} elbows to {f['elbow_std']}, {f['flanges']} flanges to {f['flange_std']}, {f['gaskets']} gaskets "
           f"and {f['stud_bolts']} stud bolts of {f['stud_size']}. Its {f['joints']} joints are made to {w}: {proc}. It is tested to "
           f"class sheet {f['cls']}.", '']

md += ['', '## 5. Coverage', '',
       f'This page has one plan for each of the {len(FAM)} families of AQS-INV-003 and no other. The totals of section 2 agree with '
       'the inventory file for length, stock lengths, off-cuts, joints, elbows and flanges. Two items remain open: making pipe in '
       'house (rule 1 of section 2), and the production runs and joint examinations, which are shop work.']
open('docs-authority/PIPE_SPECS.md', 'w').write('\n'.join(md) + '\n')
print(len(FAM), round(tot_m, 1), tot_len, tot_j)
