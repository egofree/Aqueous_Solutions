"""X-INV-04-PF-01..18 pipe-family production plans (AQS-INV-006).

One production plan per pipe family in inventory/PIPE_FAMILIES.csv (AQS-INV-003), joined to the
issued authorities rather than re-deriving them:

  - class basis and ratings come from the AQS-PIP-003 class sheets (letters P1..P5, M1, M2, F1);
  - joint procedures come from the AQS-WLD-002 WPS register, keyed by (material, joint_type) -
    the same eight procedures the register issues (solvent, fusion, butt weld, butt-and-strap);
  - the making-route disposition is stated honestly: the graph books no plastic pipe extrusion
    line and no tube mill (EXTRUDE is the 50 t billet/rod/profile press feeding WIRE_DRAW;
    FILM_CAST is the 0.14 kg/d PVDF cast sheet line), so stock is bought to the family standard
    and the shop plan covers identity receipt, cut to the registered stock lengths with the
    booked offcut budget, fittings disposition, joint execution and the class test. In-house
    extrusion or a tube mill is an open capital option (would need a new booked machine and a
    unit task); it is named, not assumed.

Fittings: bought to the family fitting standard (socket D2467/F439, butt-fusion D3261,
ISO 10931/15494 stub ends, wrought ASME B16.9 LR elbows with A403/A234 material, B16.5 flanges);
pipework-grade FRP (F1) elbows and stub ends are contact-moulded in the shop to ASTM D5421,
which is the same laminate discipline the class sheet and WPS-08 issue.

Outputs docs-authority/PIPE_SPECS.md. Run: python3 docs-authority/_pipe_specs.py
"""
import collections, os, re, sys

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); os.chdir(R)

FAM = list(__import__('csv').DictReader(open('docs-authority/inventory/PIPE_FAMILIES.csv')))
assert FAM, 'no pipe families'

# the class sheets of AQS-PIP-003: letter -> sheet title (the sheet itself carries the rating basis)
CLS = {}
for line in open('docs-authority/PIPING_CLASSES.md'):
    m = re.match(r'^\| (P[1-5]|M[12]|F1) \| ([^|]+) \|', line)
    if m and m.group(1) not in CLS:
        CLS[m.group(1)] = m.group(2).strip()

# the issued joint procedures of AQS-WLD-002: (material, joint_type) -> WPS id and process
WPS = {}
for line in open('docs-authority/WPS_REGISTER.md'):
    m = re.match(r'^\| (WPS-\d+) \| ([^|]+) \| ([^|]+) \| \d+ \| \d+ \| ([^|]+) \|', line)
    if m:
        WPS[(m.group(2).strip(), m.group(3).strip())] = (m.group(1), m.group(4).strip())

MAKING = ('The graph books no plastic pipe extrusion line and no tube mill (EXTRUDE is the 50 t '
          'billet-to-rod/profile press of the Cu/Al profile class feeding WIRE_DRAW; FILM_CAST is '
          'the 0.14 kg/d PVDF cast sheet line). Stock is therefore bought to the family standard '
          'and class sheet, and in-house extrusion or a tube mill stays an open capital option - '
          'it would need a new booked machine and a named unit task, and nothing here assumes it.')

md = ['# Pipe family production plans', '',
      'Document number: AQS-INV-006', 'Revision: A', 'Date: 2026-10-21',
      'Authority: AQS-PLAN-007 X-INV-04-PF-01..18. Generated by `docs-authority/_pipe_specs.py` from '
      '`inventory/PIPE_FAMILIES.csv` (AQS-INV-003); joins the AQS-PIP-003 class sheets (letter per family) and the '
      'AQS-WLD-002 WPS register (procedure per material and joint). A-M-217 discipline. Study. Not a PE stamp.',
      '',
      '| Rev | Description | Date |', '| --- | --- | --- |',
      '| A | First issue: one production plan per pipe family - quantities, cut plan, fittings, WPS joints, class test; making-route disposition stated. | 2026-10-21 |']

tot_m = sum(float(f['pipe_m']) for f in FAM)
tot_len = sum(int(f['stock_lengths_6m']) for f in FAM)
tot_off = sum(float(f['offcut_m']) for f in FAM)
tot_el = sum(int(f['elbows_90']) for f in FAM)
tot_fl = sum(int(f['flanges']) for f in FAM)
tot_j = sum(int(f['joints']) for f in FAM)
md += ['', '## 1. Summary and dispositions', '',
       f'{len(FAM)} families, {tot_m:,.1f} m pipe in {sum(int(f["lines"]) for f in FAM)} lines, delivered as {tot_len} stock lengths of '
       f'6.096 m with a booked cutting allowance of {tot_off:,.1f} m ({tot_off / tot_m * 100:.1f} % of installed length); '
       f'{tot_el} elbows, {tot_fl} flange sets, {tot_j} joints. Every figure is the AQS-INV-003 inventory roster, line by line.',
       '',
       '- **Class authority**: the AQS-PIP-003 class sheet letter per family (P1..P5, M1, M2, F1) carries the material, '
       '  fitting standard, temperature rating and design basis; this desk does not restate them.',
       '- **Making route**: ' + MAKING,
       '- **Fittings**: bought to the family fitting standard (socket D2467/F439, butt-fusion D3261 and ISO 10931/15494 '
       '  stub ends with backing rings, wrought ASME B16.9 LR elbows on A403/A234 body material, ASME B16.5 flanges on '
       '  A182/A105). The F1 FRP elbows and stub ends are contact-moulded in the shop to ASTM D5421 - the class '
       '  laminate discipline of sheet F1 and WPS-08 (laminator demonstration, ASME_RTP1 Part 7).',
       '- **Joints**: executed to the issued WPS of AQS-WLD-002 per material and joint type; examination extent is the '
       '  register row (ASME B31.3 341.4.1 normal fluid service, 5 % random).',
       '- **Test**: receipt identity check against the family standard, then the class test of the AQS-PIP-003 letter '
       '  (hydrostatic per the sheet; solvent and fusion joints sighted per the WPS cure table before any covering).']

md += ['', '## 2. Roster', '', '| Family | Class | DN | Material | Pipe m | Lines | Stock 6.096 m | Offcut m | Joints | WPS |',
       '|---|---|---|---|---|---|---|---|---|---|']
for f in FAM:
    key = (f['material'], f['joint_type'])
    assert key in WPS, f'{f["family"]}: no issued WPS for {key}'
    assert f['cls'] in CLS, f'{f["family"]}: class {f["cls"]} not in AQS-PIP-003'
    md.append(f"| {f['family']} | {f['cls']} | {f['DN']} | {f['material']} | {f['pipe_m']} | {f['lines']} | "
              f"{f['stock_lengths_6m']} | {f['offcut_m']} | {f['joints']} | {WPS[key][0]} |")

md += ['', '## 3. Family plans', '']
for f in FAM:
    w, proc = WPS[(f['material'], f['joint_type'])]
    md += [f"### {f['family']}: {f['cls']} DN{f['DN']}, {f['material']}", '',
           f"- **Quantity basis**: {f['pipe_m']} m in {f['lines']} lines; cut to {f['stock_lengths_6m']} stock lengths of 6.096 m; "
           f"cutting allowance {f['offcut_m']} m booked; off-drops returned to the store for spool pieces.",
           f"- **Stock**: bought mill stock to the family standard, verified by the receipt identity check; class sheet "
           f"**{f['cls']}** of AQS-PIP-003 (sheet title: {CLS[f['cls']]}).",
           f"- **Fittings**: {f['elbows_90']} x {f['elbow_std']}; {f['flanges']} x {f['flange_std']}; {f['gaskets']} gaskets; "
           f"{f['stud_bolts']} stud bolts {f['stud_size']}.",
           f"- **Joints**: {f['joints']} joints to **{w}** - {proc}.",
           f"- **Test**: to the {f['cls']} class sheet (hydro and inspection per AQS-PIP-003; the standard's receipt "
           f"marking and material checks).",
           f"- **Making route**: " + MAKING, '']

md += ['', '## 4. Coverage', '',
       f'- One plan per family: {len(FAM)} families, exactly the AQS-INV-003 roster (18 names present, none extra).',
       '- Totals reconciled to the CSV: m, stock lengths, offcut, joints, elbows, flanges.',
       '- Open items stay named: in-house extrusion or a tube mill (capital option above); the production runs and the '
       '  joint examinations remain the open part of the shop work.']
open('docs-authority/PIPE_SPECS.md', 'w').write('\n'.join(md) + '\n')
print(len(FAM), round(tot_m, 1), tot_len, tot_j)
