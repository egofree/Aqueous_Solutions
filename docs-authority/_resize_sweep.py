"""X-RSZ-07 held-rate sweep (AQS-PLAN-010 rev B, A-M-216). Every feed-driven unit is checked against the bounding feed cases
of AQS-ASSAY-001 (A regolith, B mixed, MSW) and resized where a case exceeds its design-day throughput.
Method: the class increment of each case (as _bounding_case_study.py: silicate on IA-SINK-01, water on IA-EW-04, organic ratio
on IA-PLAST-01) is injected on its edge and carried downstream linearly: a unit passes its inflow increment to its kg/d out-edges
in proportion to their design-day rates (recycles iterated to convergence). Unit throughput = sum of kg/d in-edges. A unit whose
bounding throughput exceeds its design-day throughput by more than 2 % gets params.design_capacity_kg_d (value, case, basis).
Writes the graph, docs-authority/RESIZE_SWEEP.md section 2 and docs-authority/inventory/RESIZE_SWEEP.csv."""
import json, os, csv, collections, sys
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); os.chdir(R)
sys.path.insert(0, R)
from flow_graph.param import drivers as _DR
_d = _DR.load()
GP = 'flow_graph/plant_flow_graph.json'; g = json.load(open(GP)); N = {n['unit_id']: n for n in g['nodes']}
F = _DR.val(_d, 'feed_rate_kg_d')   # D6: single source (drivers.json; was a 102.68 hardcode duplicating AQS-ASSAY-001 Rev C)
C = {'A': dict(water=0, silicate_oxide=0.99, organic=0), 'B': dict(water=0.03, silicate_oxide=0.30, organic=0.25),
     'MSW': dict(water=0.25, silicate_oxide=0.05, organic=0.30), 'ref': dict(water=0.05, silicate_oxide=0.18, organic=0.22)}
M = [e for e in g['edges'] if e.get('presence') == 'present' and (e.get('rate') or {}).get('unit') == 'kg/d' and (e['rate'].get('value') or 0) > 0]
RT = {e['stream_id']: e['rate']['value'] for e in M}
out = collections.defaultdict(list); inn = collections.defaultdict(list)
for e in M:
    out[e['from_unit_id']].append(e); inn[e['to_unit_id']].append(e)
def inject(k):
    d = collections.defaultdict(float)
    d['IA-SINK-01'] = F*(C[k]['silicate_oxide'] - C['ref']['silicate_oxide'])
    d['IA-EW-04'] = F*(C[k]['water'] - C['ref']['water'])
    d['IA-PLAST-01'] = RT['IA-PLAST-01']*(C[k]['organic']/C['ref']['organic'] - 1)
    return d
def propagate(k):
    seed = inject(k); D = dict(seed)
    for _ in range(60):
        new = dict(seed)
        for u, es in out.items():
            din = sum(D.get(e['stream_id'], 0) for e in inn.get(u, []))
            if abs(din) < 1e-9: continue
            tot = sum(RT[e['stream_id']] for e in es)
            for e in es:
                if e['stream_id'] in seed: continue
                new[e['stream_id']] = new.get(e['stream_id'], 0) + din*RT[e['stream_id']]/tot
        if all(abs(new.get(s, 0) - D.get(s, 0)) < 1e-6 for s in set(new) | set(D)): D = new; break
        D = new
    return D
DK = {k: propagate(k) for k in ('A', 'B', 'MSW')}
rows = []
for u in sorted(N):
    if not inn.get(u): continue
    base = sum(RT[e['stream_id']] for e in inn[u])
    ks = {k: base + sum(DK[k].get(e['stream_id'], 0) for e in inn[u]) for k in DK}
    if all(abs(v - base) < 1e-6 for v in ks.values()): continue  # not feed-driven
    kmax = max(ks, key=ks.get); p = N[u].setdefault('params', {}); cap = (p.get('design_capacity_kg_d') or {}).get('value')
    need = ks[kmax]; act = 'ok'
    if need > base*1.02 and (cap is None or cap < need*0.999):
        p['design_capacity_kg_d'] = dict(value=round(need, 2), case=kmax, basis=f'bounding case {kmax}, linear class-increment carry (AQS-PLAN-010 rev B)', task='X-RSZ-07 sweep')
        act = 'resized' if cap is None else f'raised from {cap:.2f}'
    elif cap is not None: act = 'resized (this sweep)' if 'linear class-increment' in str(p['design_capacity_kg_d'].get('basis')) else f'kept {cap:.2f}'
    rows.append(dict(unit=u, design_day_kg_d=round(base, 2), A=round(ks['A'], 2), B=round(ks['B'], 2), MSW=round(ks['MSW'], 2), governing=kmax, ratio=round(need/base, 3), action=act))
json.dump(g, open(GP, 'w'), indent=1)
os.makedirs('docs-authority/inventory', exist_ok=True)
with open('docs-authority/inventory/RESIZE_SWEEP.csv', 'w', newline='') as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
md = open('docs-authority/RESIZE_SWEEP.md').read().split('\n## 2.')[0].replace('Revision: A', 'Revision: B').replace('Date: 2026-10-15', 'Date: 2026-10-16')
rs = [r for r in rows if r['action'] != 'ok' and not r['action'].startswith('kept')]
md += (f"\n## 2. Automatic sweep, every feed-driven unit (X-RSZ-07, A-M-216)\n\nGenerated by `docs-authority/_resize_sweep.py`; table in `inventory/RESIZE_SWEEP.csv`. "
       f"{len(rows)} units see a feed-case change; {sum(r['ratio'] > 1.02 for r in rows)} exceed design day by more than 2 %; {len(rs)} resized or raised by this sweep "
       "(params.design_capacity_kg_d on the node). Units whose bounding flow is below design day keep the design day. The carry is linear: a unit's outlet split is held at its "
       "design-day split, so separation units that would change split with composition (FLOAT_SINK, LEACH_CSTR_1) are bounded, not modelled. Equipment envelopes and loads "
       "booked from design-day rates are scaled where a module reads design_capacity_kg_d; others are listed for X-RSZ-08. Small (< 10 %) rises on units off the feed path (BACKUP_GEN, NORTH_DOCK, AFTERBURNER_FLUE) come from recycle links in the linear carry and are kept as conservative bounds.\n\n"
       "| Unit | Design day kg/d | Case A | Case B | MSW | Governs | Ratio | Action |\n|---|---|---|---|---|---|---|---|\n")
for r in sorted(rows, key=lambda r: -r['ratio']):
    md += f"| {r['unit']} | {r['design_day_kg_d']} | {r['A']} | {r['B']} | {r['MSW']} | {r['governing']} | {r['ratio']} | {r['action']} |\n"
open('docs-authority/RESIZE_SWEEP.md', 'w').write(md)
print(len(rows), 'units', len(rs), 'resized')
