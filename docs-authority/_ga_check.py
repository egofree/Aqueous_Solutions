"""AQS-BLD-010 general-arrangement clash check (X-BLD-04). Every real envelope
(seed rows, study rows; block-sized placeholders excluded) checked pairwise per
level and tier for overlap and for the 600 mm maintenance clearance."""
import json, itertools, sys
sys.path.insert(0,'flow_graph'); import study_place as sp
seed=json.load(open(sp.SEED)); rep=json.load(open(sp.REP)); st=json.load(open('flow_graph/placement_study.json'))
BLK={tuple(b['size_mm'][:2]) for b in seed['blocks']}
B={}
for r in seed['units']+rep.get('moves',[])+rep.get('create_moves',[])+rep.get('apply_moves',[]):
    o,z=r.get('origin_mm'),r.get('size_mm')
    if not(o and z and len(z)>=2) or tuple(z[:2]) in BLK: continue
    if r['unit_id'] in B and r in seed['units']: pass
    B[r['unit_id']]=(r.get('level'),o[0],o[1],z[0],z[1])
for r in seed['units']:   # seed is the issued table; it wins
    o,z=r['origin_mm'],r['size_mm']
    if tuple(z[:2]) not in BLK: B[r['unit_id']]=(r['level'],o[0],o[1],z[0],z[1])
for r in st['units']:
    o,z=r['origin_mm'],r['size_mm']; B[r['unit_id']]=(r['level']+('T2' if r.get('tier')==2 else ''),o[0],o[1],z[0],z[1])
lines=[r['unit_id'] for r in seed['units'] if str(r.get('source','')).lower().find('header')>=0]
G={r['unit_id']:r.get('group') for r in seed['units']}
Z={r['unit_id']:(r['origin_mm'][2] if len(r['origin_mm'])>2 else 0,(r['size_mm']+[0,0,0])[2]) for r in seed['units']+st['units']}
def thin(p): return min(p[3],p[4])<=100
ov=[];cl=[]
for (a,p),(b,q) in itertools.combinations(B.items(),2):
    if p[0]!=q[0]: continue
    if G.get(a)==b or G.get(b)==a or (G.get(a) and G.get(a)==G.get(b)): continue   # tool group: members abut
    za,zb=Z.get(a,(0,0)),Z.get(b,(0,0))
    if za[1] and zb[1] and not(za[0]<zb[0]+zb[1] and zb[0]<za[0]+za[1]): continue      # stacked, no vertical overlap
    if thin(p) or thin(q): continue                                                     # line envelope: no-overlap rule only, checked by routing
    over=p[1]<q[1]+q[3] and q[1]<p[1]+p[3] and p[2]<q[2]+q[4] and q[2]<p[2]+p[4]
    if over: ov.append((a,b))
    elif sp.hit(p,q): cl.append((a,b))
out=f"""# General arrangement clash check

Document number: AQS-BLD-010
Revision: A
Date: 2026-10-15
Authority: placement seed Rev J, AQS-PLACE-STUDY-001. Generated by `docs-authority/_ga_check.py`. Study.

{len(B)} envelopes. Overlaps: {len(ov)}. Inside 600 mm clearance (no overlap): {len(cl)}. Headers and racks that run through rooms are listed but are line envelopes (seed clearance_scope: lines need no overlap only).

## Overlaps

| A | B |
| --- | --- |
"""+"\n".join(f"| {a} | {b} |" for a,b in ov)+"""

## Clearance below 600 mm

| A | B |
| --- | --- |
"""+"\n".join(f"| {a} | {b} |" for a,b in cl)+"\n"
open('docs-authority/GA_CHECK.md','w').write(out)
print(len(B),len(ov),len(cl)); print(ov[:30]); print(cl[:30])
