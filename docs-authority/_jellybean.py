    frows = [f"| {s} | {k} | {g} | {q} | {'ISO 4014 / ISO 4032 / ISO 7089' if k in ('hex bolt', 'stud') else 'DIN 3570 (U-bolt)' if k == 'U-bolt' else 'ISO 4017 + chemical anchor (ETAG 001)'} |" for (s, k, g), q in sorted(F.items())]
