"""AQS-ELEC-003 load list. Every present node with continuous_kw, the graph value, and the calculated value
where a sizing document exists. Writes docs-authority/LOAD_LIST.md. Calculated entries are listed in CALC."""
import json, subprocess, os
g=json.load(open('flow_graph/plant_flow_graph.json'))
ew=json.loads(subprocess.run(['python3','docs-authority/_ew_sizing.py'],capture_output=True,text=True,check=True).stdout)['rows']
CALC={r['cell']:(r['P_kW'],'AQS-DUTY-051 DC at the bounding current; fed from RECT_EW (DC, not in the AC sum)') for r in ew}
DC_BEHIND={r['cell'] for r in ew}
CALC['LEACH_CSTR_1']=(0.75,'AQS-DUTY-050 agitator motor; heat by Q3 (HX-5), not electric')
CALC['CRYO_ASU']=(3.03,'Air set by IA-ASU-N2 243.28 kg/d / 0.755 N2 mass fraction = 322 kg/d = 249 Nm3/d; 1.4 kWh/Nm3 O2 (80 m3/h plant, S23 IJRET 2013) / 4.8 Nm3 air per Nm3 O2 = 0.292 kWh/Nm3 air. Lower bound: the plant is about 57x smaller than the reference')
_s25=next(e['rate']['value'] for e in g['edges'] if e['stream_id']=='S25')
CALC['BMED_UPW_POLISH']=(round(_s25/1000*3.5/24,3),f'S25 {_s25:.2f} kg/d feed; brackish RO 3.0 kWh/m3 upper (S24 Greenlee 2009) + EDI 0.5 kWh/m3 upper (S25 Alvarado and Chen 2014)')
CALC['GROW_BED']=(2.25,'LED: 28 m2 x DLI 17 mol/m2/d (S26 Both, Cornell CEA lettuce) / 2.5 umol/J = 2.20 kW; recirculation 18909 kg/d at 10 m head, 50% wire-to-water = 0.043 kW')
CALC['CRYO_H2']=(0.565,'S05 6.63 kg/d, 10 to 200 bar, RT ln(20)/M / 0.5 = 2.05 kWh/kg (compressed basis, A-M register)')
CALC['H2_PURIFIER']=(0.05,'TSA regeneration average (study)')
_mf=json.loads(subprocess.run(['python3','docs-authority/_mfg_tools.py'],capture_output=True,text=True,check=True).stdout)
CALC['MFG_SHOP']=(_mf['avg'],f"AQS-MFG-010 tool list, one shift; peak {_mf['peak']} kW")
CALC['WS_PEROX']=(0.0308,'AQS-DSN-OX-001 cell 12.31 A at 2.5 V')
rows=[]
for n in g['nodes']:
    if n.get('presence')!='present' or not isinstance(n.get('continuous_kw'),dict): continue
    u=n['unit_id']; kw=n['continuous_kw'].get('value') or 0; role=n.get('electrical_role') or '—'
    c=CALC.get(u); rows.append((u,role,kw,c[0] if c else None,c[1] if c else 'study share; held for unit task 02'))
for u,c in CALC.items():
    if not any(r[0]==u for r in rows): rows.append((u,'load',0,c[0],c[1]))
rows.sort(key=lambda r:(r[3] is None,-(r[3] if r[3] is not None else r[2])))
nc=sum(1 for r in rows if r[3] is not None); loads=[r for r in rows if (r[1]=='load' or r[3] is not None) and r[0] not in DC_BEHIND]
gsum=sum(r[2] for r in loads); csum=sum((r[3] if r[3] is not None else r[2]) for r in loads)
out=[f"""# Load list

Document number: AQS-ELEC-003
Revision: A
Date: 2026-10-15
Authority: graph Rev BH; AQS-PLAN-007 X-ELS-02. Generated by `docs-authority/_load_list.py`. Study. Not a PE stamp.

| Rev | Description | Date |
| --- | --- | --- |
| A | First issue. Graph values beside calculated values where a sizing exists. | 2026-10-15 |

Status. {nc} of {len(rows)} nodes have a calculated load. The rest are study shares and close with each unit's task 02. X-ELS-02 stays open until all are calculated. Graph `continuous_kw` is not changed here; where the calculated value differs, the node is flagged.

Loads: graph sum {gsum:.1f} kW; with calculated values substituted {csum:.1f} kW.

| Unit | Role | Graph kW | Calculated kW | Basis |
| --- | --- | --- | --- | --- |"""]
for u,role,kw,c,b in rows: out.append(f"| {u} | {role} | {kw:.3f} | {'' if c is None else f'{c:.3f}'} | {b} |")
open('docs-authority/LOAD_LIST.md','w').write('\n'.join(out)+'\n'); print(nc,len(rows),round(gsum,1),round(csum,1))
