"""Build and validate AQS-REG-002, the assumptions register.

Sources: graph params with status study/assumption or text naming an assumption; models/mfg/*/params.json
'assumptions'; Markdown lines in docs-authority that label an assumption; and the curated entries in
docs-authority/assumptions_manual.json (full fields; every new assumption is added there in its commit).
Run: python3 docs-authority/_assumptions_register.py   (writes ASSUMPTIONS_REGISTER.md, exits 1 on a validation error)
"""
import json, os, re, sys, glob, hashlib
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from flow_graph.param.indexes import is_index_output  # noqa: E402
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); os.chdir(R)
REQ = ['id', 'value', 'units', 'where', 'basis', 'sensitivity', 'replaced_by', 'task']
man = json.load(open('docs-authority/assumptions_manual.json'))
err = []
ids = [m['id'] for m in man]
if len(ids) != len(set(ids)): err.append('duplicate manual id')
for m in man:
    for k in REQ:
        if not str(m.get(k, '')).strip(): err.append(f"{m.get('id')}: missing {k}")
    if m.get('needs_verification') and not str(m.get('verification_test','')).strip(): err.append(f"{m.get('id')}: needs_verification without verification_test")
    for w in m.get('files', []):
        if not os.path.exists(w): err.append(f"{m['id']}: file {w} missing")
def hid(p, s): return p + hashlib.sha1(s.encode()).hexdigest()[:6]
scan = []
g = json.load(open('flow_graph/plant_flow_graph.json'))
def walk(o, path, owner, task):
    if isinstance(o, dict):
        st = str(o.get('status', '')).lower()
        txt = ' '.join(str(o.get(k, '')) for k in ('note', 'basis', 'source', 'rate_basis'))
        if st in ('study', 'assumption') or 'ssumption' in txt:
            val = o.get('value', '')
            scan.append(dict(id=hid('A-G-', owner + path), value=val, units=o.get('unit', ''), where=f'graph {owner} {path}',
                             basis=(txt.strip()[:160].rsplit(' ', 1)[0].rstrip(' ,;:(') + ' ...') if len(txt.strip()) > 160 and txt.strip()[159] not in ' 	' else txt.strip() or st, task=task))
        for k, v in o.items():
            if k not in ('note', 'basis', 'source'): walk(v, f'{path}.{k}' if path else k, owner, task)
    elif isinstance(o, list):
        for i, v in enumerate(o): walk(v, f'{path}[{i}]', owner, task)
for n in g['nodes']:
    if n.get('presence') == 'present':
        walk({k: v for k, v in n.items() if k in ('params', 'continuous_kw')}, '', n['unit_id'], f"unit task 02 ({n['unit_id']})")
for e in g['edges']:
    if e.get('presence') != 'absent':
        walk({k: v for k, v in e.items() if k in ('rate', 'params')}, '', e['stream_id'], 'X-BAS-02')
for p in sorted(glob.glob('models/mfg/*/params.json')):
    u = p.split('/')[2]
    for k, v in json.load(open(p)).get('assumptions', {}).items():
        val = v.get('value') if isinstance(v, dict) else v
        note = v.get('note', '') if isinstance(v, dict) else 'assumption'
        scan.append(dict(id=hid('A-P-', p + k), value=val, units='mm' if k.endswith('_mm') else '', where=f'{p} {k}', basis=(note[:160].rsplit(' ', 1)[0].rstrip(' ,;:(') + ' ...') if len(note) > 160 and note[159] not in ' 	' else note, task=f'unit task 10 ({u})'))
# Scanned ids are content hashes; identical lines (repeated table headers on one page) would share an id.
# Later repeats take a -2, -3 ... suffix in scan order, so every id is unique and stable while the page is.
_seen = {}
for s in scan:
    n = _seen.get(s['id'], 0) + 1; _seen[s['id']] = n
    if n > 1: s['id'] = f"{s['id']}-{n}"
comp = json.load(open('docs-authority/assumptions_complete.json')) if os.path.exists('docs-authority/assumptions_complete.json') else {}
byw = {x['where']: x for x in scan}
for w, c in comp.items():
    if w not in byw: err.append(f'complete: {w} not in scan (stale key)'); continue
    for k in ('basis', 'replaced_by'):
        if not str(c.get(k, '')).strip(): err.append(f'complete: {w} missing {k}')
    byw[w].update({k: c[k] for k in ('basis', 'sensitivity', 'replaced_by') if k in c}); byw[w]['done'] = 1
if err:
    print('\n'.join(err)); sys.exit(1)
cell = lambda s: str(s).replace('|', '/').replace('\n', ' ')
out = [f'''# Assumptions register

Document number: AQS-REG-002  
Revision: C  
Date: 2026-10-25  
Basis: AQS-PLAN-007, task X-GOV-07.  
Source: generated by `docs-authority/_assumptions_register.py` from `docs-authority/assumptions_manual.json`, `docs-authority/assumptions_complete.json`, the plant graph, the model parameter files and the documents. Do not edit this page by hand.

| Rev | Description | Date |
| --- | --- | --- |
| A | First issue. | 2026-10-15 |
| B | Purpose, terms and procedure added; table captions added; entries unchanged. | 2026-10-24 |
| C | The document-line mining section removed: it re-quoted hundreds of document lines as hash-id rows with empty values and carried no design content. The curated assumptions, the graph scan and the model-parameter scan stay. | 2026-10-25 |

## Purpose and scope

The design uses some values that have not yet been measured, quoted by a supplier or taken from a published source. This register lists every such value in one place, says why it was chosen, and names the measurement or test that will replace it. A reviewer can use it to see which results depend on unconfirmed inputs.

The register covers values in the plant graph, the model parameter files and the documents of this repository. Values backed by a cited published source are not assumptions and are not listed.

## Terms

Assumption: a value used in the design that is not yet confirmed by measurement, a supplier quotation or a cited published source. Study values are a kind of assumption.

Curated entry: an assumption written into `assumptions_manual.json` with its full record (Table A). Curated entries have IDs beginning `A-M-`.

Scanned entry: a value the generator finds automatically because it is marked as a study or assumed value. IDs beginning `A-G-` come from the plant graph, `A-P-` from model parameter files and A scanned entry has no sensitivity assessment of its own; the owning task assesses it when the task closes. Where `assumptions_complete.json` gives a basis and replacing test for a scanned entry (matched on the Where column), the register shows them.

Table A. Columns of the register

| Column | Meaning |
| --- | --- |
| ID | Register identifier |
| Value, Units | The assumed value and its units |
| Where used | Graph element, parameter file or document that uses the value |
| Basis or source | Why the value was chosen |
| Sensitivity | What changes if the value is wrong (curated entries only) |
| Replaced by | Measurement, test or quotation that will confirm or replace the value |
| Task | Plan task that owns the replacement |

## Procedure for a new assumption

Every new assumption gets a curated entry in `assumptions_manual.json` in the same commit that introduces it, with value, units, where used, basis, sensitivity, the measurement or test that replaces it, and the owning plan task. Then run `python3 -m flow_graph.param.regen` to rebuild this page.

## 1. Curated

Table 1.1. Curated assumptions

| ID | Value | Units | Where used | Basis or source | Sensitivity | Replaced by | Task |
| --- | --- | --- | --- | --- | --- | --- | --- |''']
for m in man:
    out.append('| ' + ' | '.join(cell(m[k]) for k in REQ) + ' |')
for title, pre in (('2. Graph study and assumed values', 'A-G-'), ('3. Model parameters', 'A-P-')):
    out += ['', f'## {title}', '', f'Table {title[0]}.1. {title[3:]}', '', '| ID | Value | Units | Where used | Basis | Replaced by | Task |', '| --- | --- | --- | --- | --- | --- | --- |']
    out += ['| ' + ' | '.join(cell(s.get(k, '')) for k in ('id', 'value', 'units', 'where', 'basis', 'replaced_by', 'task')) + ' |' for s in scan if s['id'].startswith(pre)]
open('docs-authority/ASSUMPTIONS_REGISTER.md', 'w').write('\n'.join(out) + '\n')
print(f'curated {len(man)} scanned {len(scan)}')
