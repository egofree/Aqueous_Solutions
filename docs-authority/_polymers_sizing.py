"""AQS-DUTY-073. POLYMERS sector sizing (unit task 02) from the live graph.
Reads the graph, re-derives the polymer chain via flow_graph.param.foundry_poly.solve()
(same transfer functions the balance runs), prints JSON and writes
docs-authority/sizing/POLYMERS_LINE.md. Run: python3 docs-authority/_polymers_sizing.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from flow_graph.param import drivers as DR
from flow_graph.param.foundry_poly import solve, DOC_P

_d = DR.load()   # U4b: POLY_OLEFIN feed-heating inputs from drivers.json
PO = 'POLYMERS.polyolefin-train.POLY_OLEFIN.'
FP = 'POLYMERS.fluoropolymer-train.'
g = json.load(open('flow_graph/plant_flow_graph.json'))
s = solve(g)
LIVE = [e for e in g['edges'] if e.get('presence') != 'retired']
E = {e['stream_id']: e for e in LIVE}
N = {n['unit_id']: n for n in g['nodes']}


def v(k):
    r = (E.get(k) or {}).get('rate') or {}
    return float(r.get('value') or 0) if r.get('unit') == 'kg/d' else 0.0


def kw(u):
    r = (E.get('SF-' + u) or {}).get('rate') or {}
    return r.get('value') if isinstance(r.get('value'), (int, float)) else None


def flows(u):
    tin = sum(v(e['stream_id']) for e in LIVE if e['to_unit_id'] == u)
    tout = sum(v(e['stream_id']) for e in LIVE if e['from_unit_id'] == u)
    return tin, tout


def _and(xs):
    return ', '.join(xs[:-1]) + ' and ' + xs[-1] if len(xs) > 1 else ''.join(xs)


UNITS = ['F_RECOVER', 'HF_GEN', 'ACID_PLANT', 'VDF_SYN', 'TFE_SYN', 'POLY_F', 'POLY_OLEFIN', 'POLY_COND', 'PELLET', 'POWDER_RESIN', 'FILM_CAST', 'POLY_STOCK']
UNITS = [u for u in UNITS if u in N and N[u].get('presence') != 'retired']
rows = []
for u in [x for x in UNITS if x != 'F_RECOVER']:
    tin, tout = flows(u)
    rows.append(dict(unit=u, in_kg_d=round(tin, 6), out_kg_d=round(tout, 6), sizing=N[u]['params'].get('sizing')))

heat_W = s['poly_feed'] * DR.val(_d, PO+'feed_cp_kJ_kgK') * DR.val(_d, PO+'feed_dT_K') / 86400
FTRAIN = [u for u in ('F_RECOVER', 'HF_GEN', 'ACID_PLANT', 'VDF_SYN', 'TFE_SYN', 'POLY_F', 'POWDER_RESIN', 'FILM_CAST') if u in UNITS]
f_live = any(flows(u)[1] > 0 for u in FTRAIN)
film_in = flows('FILM_CAST')[0] if 'FILM_CAST' in UNITS else 0.0

