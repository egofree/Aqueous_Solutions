"""X-BAS-04 codes and standards list per discipline (AQS-STD-004), generated from the registered references (flow_graph/param/refs.py)
and the places each key is cited in the repository. Run: python3 docs-authority/_standards_list.py"""
import os, re, subprocess, sys
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, R)
from flow_graph.param.refs import REFS
from flow_graph.param.indexes import is_index_output  # noqa: E402
CODE = re.compile(r'^(ANSI|API|ASCE|ASHRAE|ASME|ASTM|AWS|AWWA|CGA|DVS|IBC|IEC|IECC|IEEE|IFC|ISO|NEC|NFPA|UL)')
DISC = [('Pressure equipment and piping', ('ASME_II', 'ASME_VIII', 'API', 'ISO4126', 'ISO16528', 'ISO23251', 'ASTM_D1785', 'ISO1452', 'CGA', 'DVS', 'AWS')),
        ('Drawings and documentation', ('ASME_Y14', 'ISO_7200', 'ISO_10628')),
        ('Electrical', ('NEC', 'NFPA70E', 'IEEE', 'IEC', 'UL', 'ANSI_C12', 'NFPA110', 'NFPA111')),
        ('Fire, life safety and hazardous materials', ('NFPA', 'IFC', 'IBC', 'ISO7010', 'ISO45001', 'ISO14122')),
        ('Mechanical, HVAC and energy', ('ASHRAE', 'IECC', 'ISO16798', 'ASTM_C')),
        ('Structural and water storage', ('ASCE', 'AWWA')),
        ('Hydrogen and gases', ('ISO22734', 'ISO16069', 'NFPA2')),
        ('Sanitation', ('ISO30500',))]
def disc(k):
    for name, pre in DISC:
        if any(k.startswith(p) for p in pre) and not (name.startswith('Fire') and k.startswith(('NFPA70E', 'NFPA110', 'NFPA111', 'NFPA2_'))): return name
    return 'Other'
def uses(k):
    out = [f for f in subprocess.run(['git', 'grep', '-l', '-w', k, '--', '*.py', '*.md', '*.json'], cwd=R, capture_output=True, text=True).stdout.split()
           if not is_index_output(f)]   # indexes are not citing sources
    return [f for f in out if f not in ('flow_graph/param/refs.py', 'docs-authority/STANDARDS_LIST.md')]
def main():
    rows = {}
    for k, v in sorted(REFS.items()):
        if CODE.match(k): rows.setdefault(disc(k), []).append((k, v, uses(k)))
    n_all = sum(len(x) for x in rows.values())
    n_unc = sum(1 for x in rows.values() for _, _, u in x if not u)
    md = ['# Codes and standards list', '', 'Document number: AQS-STD-004', 'Revision: B', 'Date: 2026-10-29',
          'Generated by `docs-authority/_standards_list.py` from the registered references in `flow_graph/param/refs.py`. Do not edit by hand; register a reference there and run `python3 -m flow_graph.param.regen`.',
          'Authority: task X-BAS-04 of AQS-PLAN-007. Jurisdiction: USA (AQS-STD-003, AQS-HSE-001). Study. This list is not a code-compliance review, which is task X-COD-01.', '',
          '| Rev | Description | Date |', '| --- | --- | --- |',
          '| A | First issue: the registered codes and standards grouped by discipline, with the files that cite each | 2026-10-15 |',
          '| B | Record of revisions, purpose and scope added; tables numbered; standard titles no longer cut short | 2026-10-29 |', '',
          '## 1. Purpose and scope', '',
          'This list gives the codes and standards that the project cites, grouped by discipline. It is built from the register of references in `flow_graph/param/refs.py`: every key there that names a code or standard is listed, with the number of repository files that cite it and up to three of those files. A key that no file cites yet is marked as registered but not cited.', '',
          f'The list has {n_all} codes and standards in {len(rows)} disciplines; ' + ('every one is cited by at least one file. ' if not n_unc else f'{n_unc} of them are not yet cited. ') + f'Quantities are in SI units, with US customary units only where a code states them, such as NEC conductor sizes and ASME B16.5 pressure classes.', '']
    sec = 1
    for name, _ in DISC + [('Other', ())]:
        if name not in rows: continue
        sec += 1
        md += [f'## {sec}. {name}', '', f'Table {sec}.1 lists the codes and standards of this discipline.', '',
               f'Table {sec}.1. {name}', '', '| Key | Standard | Files citing it | First files |', '|---|---|---|---|']
        md += [f"| {k} | {v.split(':')[0].strip()} | {len(u)} | {', '.join(u[:3]) if u else 'Registered, not yet cited'} |" for k, v, u in rows[name]]
        md += ['']
    open(os.path.join(R, 'docs-authority/STANDARDS_LIST.md'), 'w').write('\n'.join(md)); print(n_all)
if __name__ == '__main__': main()
