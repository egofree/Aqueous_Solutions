"""X-PRO-02 bought-item specification sheets (AQS-PRO-002).

A datasheet per bought item, where 'bought item' is the honest roster of this study: every
AQS-INV-004 family outside the 'fabricated part' category (the shop fabricates envelopes,
weldments and internals; it buys catalog components to standard classes). The datasheet of a
bought item IS the standard class it is bought to - the Spec column of AQS-INV-004 - plus the
sizes and ratings in use (from the graph counts), the interface, and the citations. No internals
are invented; the interface is the standard itself (X-MFG-40 lineage). Instrument purchases keep
their per-tag specification on AQS-CTL-001; valve seal classes and the mechanical seal tie to
AQS-STD-002 Rev N section 14; pipe class sheets stay in AQS-PIP-003.

Outputs docs-authority/BOUGHT_SPECS.md. Run: python3 docs-authority/_bought_specs.py
"""
import csv, os, collections

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(R, 'docs-authority/inventory')

TAB = lambda name, cols, rows: (
    [f'## {name}', '', '| ' + ' | '.join(cols) + ' |', '|' + '---|' * len(cols)] +
    ['| ' + ' | '.join(str(c)[:150] for c in r) + ' |' for r in rows])


def main():
    fams = [r for r in csv.DictReader(open(os.path.join(D, 'OTHER_FAMILIES.csv')))
            if r['category'] != 'fabricated part']
    bases = collections.defaultdict(set)
    for r in csv.DictReader(open(os.path.join(D, 'OTHER_INVENTORY.csv'))):
        bases[(r['category'], r['item'], r['spec'])].add(r['basis'][:80])

    cat_qty = collections.Counter()
    for f in fams:
        cat_qty[f['category']] += int(f['qty'])

    L = ['# Bought-item specification sheets', '',
         'Document number: AQS-PRO-002', 'Revision: A', 'Date: 2026-10-21',
         'Authority: AQS-PLAN-007 X-PRO-02. Generated by `docs-authority/_bought_specs.py` from the AQS-INV-004 inventory '
         '(64 bought families of 65; the one fabricated-part family is in-house work, not a purchase). Study. Not a PE stamp.',
         '',
         '| Rev | Description | Date |', '| --- | --- | --- |',
         '| A | First issue: datasheet per bought item. The standard class, the sizes in use, the interface and the citations. | 2026-10-21 |']

    L += TAB('1. The roster by category', ['Category', 'Items'],
             [(c, n) for c, n in sorted(cat_qty.items(), key=lambda x: -x[1])])
    L += ['', '## 2. What a datasheet is here', '',
          '- The shop buys to a **standard class**, not a marque: a bearing is an ISO 15 class, a PLC I/O point is IEC 61131-2,',
          '  an isolation valve is an ISO 16135 class with the seal class named. The standard is the datasheet; the class fixes',
          '  the interface the standard fixes, and no internals are invented (the X-MFG-40 lineage and A-M-125 counting rule',
          '  carry the numbers).',
          '- **Sizes in use** are the graph counts (the sizes column of AQS-INV-004); where a size is booked it is booked. A spec',
          '  that no graph row uses is not bought.',
          '- Instruments: the per-tag range, signal and loop stay on AQS-CTL-001; the 12 instrument families here carry the',
          '  physical device class and the sizes in use. The 713 analog input points and the 713 instrument channels are one',
          '  count, not two.',
          '- Valve seal classes (EPDM/FKM/PTFE seats) and the EN 12756 mechanical seal ties: AQS-STD-002 Rev N section 14;',
          '  the section 14.2 maker-table holds name what still waits on the maker tables before order.',
          '- Pipe class sheets (pipe, fittings, flange studs, gaskets) remain AQS-PIP-003 and AQS-INV-003: those are issued',
          '  elsewhere and are not duplicated here.']
    # fix any accidental non-ascii slip
    L = [x.replace('规', ' spec') for x in L]

    order = ['bearing', 'electronics', 'instrument', 'protection', 'seal', 'support', 'valve', 'fastener']
    n = 3
    for cat in order:
        rows = sorted((f for f in fams if f['category'] == cat), key=lambda f: f['family'])
        if not rows:
            continue
        dsrows = []
        for f in rows:
            key = (f['category'], f['item'], f['spec'])
            bs = '; '.join(sorted(bases.get(key, set()))[:3]) or 'AQS-INV-004 family roll-up'
            note = ''
            if cat == 'instrument':
                note = 'spec per tag on AQS-CTL-001'
            elif cat == 'valve' and 'actuator' in f['item']:
                note = 'fail-safe per IEC 61511, settled with AQS-CTL-003'
            dsrows.append((f['family'], f['item'], f['spec'], f['sizes'], f['qty'], f['units'], bs, note))
        L += TAB(f'{n}. {cat.title()} datasheets', ['Family', 'Item', 'Standard class (bought to)', 'Sizes in use',
                  'Qty', 'Units', 'Basis', 'Interface note'], dsrows)
        n += 1

    L += ['', f'## {n}. Coverage gate', '',
          f'- Bought families covered: {len(fams)} of {len(fams) + 1} (the excluded one is OF-13, the fabricated-part set:',
          '  sheets like those are `models/mfg/*/bom.csv` + `WORK_ORDER.md`, in-house work).',
          '- Items rest on the A-M-125 counting rule where the roll-up assumed; the count is the basis, not a measurement.']
    open(os.path.join(R, 'docs-authority/BOUGHT_SPECS.md'), 'w').write('\n'.join(L) + '\n')
    print(dict(families=len(fams), cats=dict(cat_qty)))


if __name__ == '__main__':
    main()
