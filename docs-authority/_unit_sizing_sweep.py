"""Unit sizing sweep: one sizing page, AQS-SIZE-<UNIT>, for each present unit that the sweep owns.
Generated by this script from the graph (params.design, params.sizing, params.envelope or params.size_mm, and the
incident edges) and from section 3 of the unit's duty sheet in docs-authority/duties/. Read-only on the graph.

Ownership: a present unit is owned when its page docs-authority/sizing/<UNIT>.md carries the document number
AQS-SIZE-<UNIT> (the pages this sweep issued), when its unit task 02 is still open in docs-authority/TASK_PLAN.md,
or when its page carries a graph-dump strike (the 3321f37 leak). Study. Not a PE stamp."""
import json, math, os, hashlib, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GP = os.path.join(ROOT, 'flow_graph', 'plant_flow_graph.json')
D = json.load(open(GP))
N = {n['unit_id']: n for n in D['nodes']}
LIVE = [e for e in D['edges'] if e.get('presence') == 'present']
FILL = 0.8          # working volume / nominal volume of the hold-up vessel (AQS-DUTY-064 pattern)
HD = 1.5            # height / diameter of the upright hold-up cylinder
RHO = 1000.0        # kg/m3, water-like liquor assumed for the hold-up check
PLACE = {}
for _f in ('flow_graph/placement_seed.json', 'flow_graph/placement_study.json'):
    _p = os.path.join(ROOT, _f)
    if os.path.exists(_p):
        for _x in json.load(open(_p)).get('units', []):
            if _x.get('size_mm'): PLACE[_x['unit_id']] = (_x['size_mm'], _f)
_p = os.path.join(ROOT, 'flow_graph/placement_blocks.json')      # block layout: only where the seed and the study place nothing
if os.path.exists(_p):
    for _x in json.load(open(_p)).get('units', []):
        if _x.get('size_mm') and _x['unit_id'] not in PLACE: PLACE[_x['unit_id']] = (_x['size_mm'], 'flow_graph/placement_blocks.json')
DUMP_MARKERS = ('"stream_id"', "'stream_id'", 'notes_rev_', '"schema_version"', "'schema_version'")


def fmt(x):
    """Scalars only - a dict leaking here means a name collision, not formatting."""
    if isinstance(x, bool):
        return 'yes' if x else 'no'
    if isinstance(x, (int, float)):
        return f'{x:.6g}'
    if isinstance(x, str):
        return x
    raise AssertionError(f'fmt() got non-scalar {type(x).__name__} - generator bug, refusing to embed in a doc')


def cell(v):
    """A table cell for one design parameter: scalars as they are, lists and dicts summarised."""
    if v is None:
        return '—'
    if isinstance(v, (bool, int, float, str)):
        return fmt(v).replace('|', '/')
    if isinstance(v, list):
        ids = [x.get('id') or x.get('item') or x.get('name') for x in v if isinstance(x, dict)]
        if ids and all(ids):
            return f'{len(v)} items: ' + ', '.join(str(i) for i in ids)
        if all(isinstance(x, (int, float, str)) for x in v):
            return ', '.join(fmt(x) for x in v).replace('|', '/')
        return f'{len(v)} items'
    if isinstance(v, dict):
        return 'parameters ' + ', '.join(str(k) for k in v)
    return '—'


def owned():
    cur = None; open_units = set()
    tp = os.path.join(ROOT, 'docs-authority/TASK_PLAN.md')
    if os.path.exists(tp):
        for line in open(tp):
            m = re.match(r'### (\w+)\.', line)
            if m: cur = m.group(1)
            m = re.match(r'\s*- \[ \] \w+-([A-Z0-9_]+)-02', line)
            if m and cur and not cur.startswith('X-'):
                open_units.add(m.group(1))
    own = set()
    for uid, u in N.items():
        if u.get('presence') != 'present':
            continue
        path = os.path.join(ROOT, f'docs-authority/sizing/{uid}.md')
        txt = open(path, encoding='utf-8', errors='replace').read() if os.path.exists(path) else ''
        if uid in open_units or f'Document number: AQS-SIZE-{uid}\n' in txt or any(mk in txt for mk in DUMP_MARKERS):
            own.add(uid)
    return sorted(own)


def mass(e):
    r = e.get('rate') or {}
    return float(r['value']) if r.get('unit') == 'kg/d' and isinstance(r.get('value'), (int, float)) else None


def material(uid, p):
    sm = p.get('sec3_material')
    if isinstance(sm, dict) and sm.get('mat'):
        return sm['mat'].rstrip('.'), 'the graph (`params.sec3_material`)'
    path = os.path.join(ROOT, f'docs-authority/duties/{uid}.md')
    if os.path.exists(path):
        for line in open(path, encoding='utf-8'):
            if line.startswith('3. Material.'):
                return line[len('3. Material.'):].strip().rstrip('.'), f'the duty sheet `docs-authority/duties/{uid}.md`'
    return None, None


def page(uid):
    u = N[uid]; p = u.get('params', {})
    cls = u.get('class') or 'unclassed'; sector = u.get('sector_id') or '—'
    ins = [mass(e) for e in LIVE if e['to_unit_id'] == uid and mass(e) is not None]
    outs = [mass(e) for e in LIVE if e['from_unit_id'] == uid and mass(e) is not None]
    tin, tout = sum(ins), sum(outs)
    sf = next(((e.get('rate') or {}).get('value') for e in LIVE if e['to_unit_id'] == uid and e['stream_id'] == f'SF-{uid}'), None)
    ckw = (u.get('continuous_kw') or {}).get('value') if isinstance(u.get('continuous_kw'), dict) else u.get('continuous_kw')
    # envelope: params.envelope first, then params.size_mm
    env = p.get('envelope') or {}
    if env.get('size_mm'):
        L, W, H = env['size_mm']; env_src = f"`params.envelope` (state {env.get('state') or 'not stated'})"; env_basis = env.get('basis')
    elif p.get('size_mm'):
        L, W, H = p['size_mm']; env_src = '`params.size_mm`'; env_basis = p.get('size_note')
    elif uid in PLACE:
        (L, W, H), _f = PLACE[uid]; env_src = f'the placement file `{_f}`'; env_basis = None
    else:
        L = W = H = None; env_src = None; env_basis = None
    # hold-up check: one hold period of the larger of the inflow and the outflow
    ds = p.get('design_storage') or {}
    if ds.get('d_kg_d'):
        flow, hold, hold_src = float(ds['d_kg_d']), float(ds.get('hold_d') or 1.0), '`params.design_storage`'
    else:
        flow, hold, hold_src = max(tin, tout), 1.0, 'one day, the default of the sweep'
    V = flow*hold/RHO
    if V > 0:
        Dn = (4*V/FILL/(HD*math.pi))**(1/3); Hn = HD*Dn
        Dmm, Hmm = math.ceil(Dn*1000/10)*10, math.ceil(Hn*1000/10)*10
    else:
        Dmm = Hmm = None
    des = p.get('design') or p.get('sizing') or {}
    src = '`params.design`' if p.get('design') else '`params.sizing`' if p.get('sizing') else None
    mat, mat_src = material(uid, p)

    md = [f'# Sizing calculation for {uid}', '', f'Document number: AQS-SIZE-{uid}', 'Revision: B', 'Date: 2026-10-29',
          'Generated by `docs-authority/_unit_sizing_sweep.py` from the plant graph and the duty sheet of the unit. Do not edit by hand; change the generator or its inputs and run `python3 -m flow_graph.param.regen`.',
          'Study. Not a PE stamp.', '',
          '| Rev | Description | Date |', '| --- | --- | --- |',
          '| A | First issue from the unit sizing sweep. | 2026-10-20 |',
          '| B | Purpose and scope added; the design parameters set out in a table; the envelope read from `params.size_mm` or the placement files where `params.envelope` is empty; the hold-up vessel sized from the larger of the inflow and the outflow and given in millimetres; the material taken from the duty sheet in place of a polyethylene default; the fit of the vessel in the envelope checked | 2026-10-29 |', '',
          '## 1. Purpose and scope', '',
          f'This page records the size of unit {uid}, of class `{cls}` in sector {sector}, from the plant graph: its duty, its envelope, the hold-up vessel that its flow would need, and its material. '
          'It checks the envelope; it is not a detailed design.', '',
          '## 2. Duty', '']
    flows = []
    if ins or outs:
        flows.append(f'The unit takes {tin:.6g} kg/d by {len(ins)} stream{"s" if len(ins) != 1 else ""} and gives {tout:.6g} kg/d by {len(outs)} stream{"s" if len(outs) != 1 else ""}.')
    else:
        flows.append('No stream with a mass rate enters or leaves the unit on the graph.')
    if isinstance(ckw, (int, float)):
        flows.append(f'Its continuous electrical load is {ckw:.6g} kW' + (f', fed by stream SF-{uid}.' if isinstance(sf, (int, float)) else '.'))
    md.append(' '.join(flows)); md.append('')
    if des:
        md += [f'Table 2.1 lists the design parameters that the graph holds for the unit in {src}.', '', 'Table 2.1. Design parameters', '',
               '| Parameter | Value |', '| --- | --- |'] + [f'| {k} | {cell(v)} |' for k, v in des.items()] + ['']
    else:
        md += ['The graph holds no design parameters for the unit.', '']
    md += ['## 3. Geometry', '']
    if L is not None:
        md.append(f'The envelope is {fmt(L)} mm x {fmt(W)} mm x {fmt(H)} mm, from {env_src}.' + (f' Its basis is: {env_basis.rstrip(".")}.' if env_basis else ''))
    else:
        md.append('The graph gives no envelope for the unit.')
    md.append('')
    if Dmm:
        txt = (f'The hold-up check takes {flow:.6g} kg/d for a hold of {hold:g} d ({hold_src}) at a density of {RHO:g} kg/m³, a working volume of {V*1000:.4g} L. '
               f'At a fill of {FILL:g} in an upright cylinder with a height of {HD:g} diameters, the vessel is {Dmm} mm in diameter and {Hmm} mm high.')
        if L is not None:
            fits = Dmm <= min(L, W) and Hmm <= H
            if fits:
                txt += ' It fits within the envelope.'
            elif ds.get('d_kg_d'):
                txt += ' It does not fit within the envelope, so the envelope must grow or the hold must shorten.'
            else:
                txt += ' A full day of flow would not fit within the envelope, so the unit must hold less than a day; its duty sheet sets the working volume.'
        md.append(txt)
    else:
        md.append('With no mass flow, the unit has no hold-up volume to check.')
    md += ['', '## 4. Material', '']
    md.append(f'The material, from {mat_src}, is: {mat}.' if mat else 'No material is assigned to the unit yet.')
    md.append('')
    return '\n'.join(md)


def main():
    units = owned()
    for uid in units:
        body = page(uid)
        hit = [m for m in DUMP_MARKERS if m in body]
        assert not hit, f'{uid}.md leaked graph content: {hit} - fix the generator, not the doc'
        open(os.path.join(ROOT, f'docs-authority/sizing/{uid}.md'), 'w').write(body)
    open(os.path.join(ROOT, 'docs-authority/sizing/_generated.json'), 'w').write(json.dumps({'units': len(units), 'graph_sha256': hashlib.sha256(open(GP, 'rb').read()).hexdigest()[:12]}, indent=1))
    print('authored', len(units), 'units (scrub clean)')


if __name__ == '__main__':
    main()
