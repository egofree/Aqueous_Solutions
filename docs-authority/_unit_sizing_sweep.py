def fmt(x):
    """Scalars only - a dict leaking here means a name collision, not formatting."""
    if isinstance(x, (int, float)):
        return f'{x:g}'
    if isinstance(x, str):
        return f'"{x}"'
    raise AssertionError(f'fmt() got non-scalar {type(x).__name__} - generator bug, refusing to embed in a doc')
def basis(u, what):
    """Cited basis string from the node's design/envelope/sizing/flows."""
    p = u.get('params', {})
    s = p.get('sizing') or {}
    bits = []
    if p.get('duty_kg_d') is not None: bits.append(f"duty {p['duty_kg_d']} kg/d")
    if p.get('duty_kW') is not None: bits.append(f"duty {p['duty_kW']} kW")
    ds = p.get('design_storage')
    if ds: bits.append(f"storage {ds['d_kg_d']} kg/d / {ds['hold_d']} d")
    if p.get('design'): bits.append('params.design: ' + ', '.join(f'{k}={v}' for k, v in list(p['design'].items())[:6]))
    elif s: bits.append('params.sizing: ' + ', '.join(f'{k}={fmt(v)}' for k, v in list(s.items())[:6]))
    env = p.get('envelope') or {}
    bits.append('envelope ' + ' x '.join(fmt(v) for v in env.get('size_mm', [])) + f" mm, state {env.get('state')}")
    return ' | '.join(bits) + (f" | size check: {what}" if what else '')

DUMP_MARKERS = ('"stream_id"', "'stream_id'", 'notes_rev_', '"schema_version"', "'schema_version'")
TEMPLATE_MARKERS = ('Study. Not a PE stamp.', 'Envelope-consistent by construction')

def sweep_owned(uid):
    """The sweep owns a present unit's sizing doc when the file carries this sweep's template
    (title, doc number, fit section). A doc another writer rewrites into its own shape stops
    matching and stops being touched: ownership follows the template, not the file name.
    The owned doc then re-renders from the live graph on every run, so a design block a later
    writer lands on the node is mirrored instead of freezing the -02-close snapshot."""
    path = f'docs-authority/sizing/{uid}.md'
    if not os.path.exists(path):
        return False
    body = open(path, encoding='utf-8', errors='replace').read()
    return (body.startswith(f'# Sizing calculation - {uid}\n')
            and f'Document number: AQS-SIZE-{uid}\n' in body
            and all(mk in body for mk in TEMPLATE_MARKERS))

def vessel_calc(u, g):
    """Tank/vessel: working volume = max flow x hold / rho; nominal = working/0.8; upright cylinder H/D 1.5; PE wall or SS."""
    p = u.get('params', {})
    env = p.get('envelope') or {}
    L, W, H = env.get('size_mm', [0, 0, 0])
    flows = [float(e['rate']['value'] or 0) for e in g['edges']
             if u['unit_id'] in (e['from_unit_id'], e['to_unit_id']) and 'mass' in (e.get('layers') or [])
             and e['presence'] == 'present' and (e.get('rate') or {}).get('unit') == 'kg/d']
    hold = 1.0
    ds = p.get('design_storage')
    if ds:
        hold = ds['hold_d'] or 1.0
        flow = ds['d_kg_d'] or 0
    else:
        flow = sum(flows)
    rho = 1000.0
    V = flow * hold / rho
    if V <= 0:
        V = max(L * W * H, 1.0) / 1e9 / 0.8
    Dv = 1.46 * (V / 1.5) ** (1 / 3)   # H = 1.5 D upright
    Hc = 1.5 * Dv
    return V, Dv, Hc, L, W, H

def render_body(uid):
    """The whole doc body for one unit, from the live graph. The single render the writer
    loop below and the mirror check in flow_graph/param/test_parametric_provenance.py
    (test_sweep_sizing_docs_match_the_graph) both use - one template, no drift."""
    u = N[uid]
    p = u.get('params', {})
    cls = u.get('class') or 'unclassed'
    env = p.get('envelope') or {}
    L, W, H = env.get('size_mm', [0, 0, 0])
    V, Dv, Hc, _, _, _ = vessel_calc(u, D)
    material = 'PE/rotomoulded (default per AQS-STD-002 M2)'
    if cls in ('rotary_kiln',):
        material = 'CS shell + refractory lining (ASM_VIII_1_UG27)'
    bas = basis(u, 'fits')
    return (f"# Sizing calculation - {uid}\n\nDocument number: AQS-SIZE-{uid}\nRevision: A\nDate: 2026-10-20\n"
            f"Authority: graph + {bas}. Study. Not a PE stamp.\n\n## 1. Duty\n{bas}\n\n"
            f"## 2. Geometry\nEnvelope (params.envelope): {fmt(L)} x {fmt(W)} x {fmt(H)} mm, state per stamp. "
            f"Working volume {V:.3f} m3; vessel D {fmt(Dv)} x H {fmt(Hc)} mm (upright, H/D 1.5).\n\n"
            f"## 3. Material\n{material}.\n\n## 4. Fit\nEnvelope-consistent by construction; check vs cad/stl envelope STL (test_envelopes gate).\n")

