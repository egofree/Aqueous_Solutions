def fmt(x):
    if isinstance(x, (int, float)):
        return f'{x:g}'
    return f'"{x}"' if isinstance(x, str) else str(x)
def basis(u, what):
    """Cited basis string from the node's design/envelope/sizing/flows."""
    p = u.get('params', {})
    s = p.get('sizing') or {}
    bits = []
    if p.get('duty_kg_d') is not None: bits.append(f"duty {p['duty_kg_d']} kg/d")
    if p.get('duty_kW') is not None: bits.append(f"duty {p['duty_kW']} kW")
    ds = p.get('design_storage')
    if ds: bits.append(f"storage {ds['d_kg_d']} kg/d / {ds['hold_d']} d")
    if p.get('design'): bits.append('params.design: ' + ', '.join(f'{k}={v}' for k, v in list(p['design'].items())[:6]))
    elif s: bits.append('params.sizing: ' + ', '.join(f'{k}={fmt(v)}' for k, v in list(s.items())[:6]))
    env = p.get('envelope') or {}
    bits.append('envelope ' + ' x '.join(fmt(v) for v in env.get('size_mm', [])) + f" mm, state {env.get('state')}")
    return ' | '.join(bits) + (f" | size check: {what}" if what else '')

