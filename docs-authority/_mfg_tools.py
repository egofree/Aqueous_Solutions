"""AQS-MFG-010 MFG_SHOP tool list sized from the graph throughputs (X-ELS-02).
Writes docs-authority/MFG_TOOLS.md; prints average and peak kW as JSON."""
import json
g=json.load(open('flow_graph/plant_flow_graph.json'));N={n['unit_id']:n for n in g['nodes']}
def thr(u): return float(N[u]['params']['duty'].split('In ')[1].split(' ')[0])
# (tool, serves, nameplate kW, kWh/kg, kg/d, idle kW, h/d)  study values, A-M register
T=[('Induction melt furnace, 25 kg Cu charge','MET_MELT',15.0,1.0,thr('MET_MELT'),0.0,0),
   ('Close-coupled gas atomizer with Ar recirculation','GAS_ATOMIZER',12.0,3.0,thr('GAS_ATOMIZER'),0.0,0),
   ('Two-high cold rolling mill','COLD_MILL',3.0,0.1,thr('COLD_MILL'),3.0,2),
   ('Bull-block wire drawer','WIRE_DRAW',1.5,0.2,thr('WIRE_DRAW'),1.5,2),
   ('CNC vertical mill','shop',7.5,0,0,7.5*0.3,8),
   ('Engine lathe','shop',5.5,0,0,5.5*0.3,8),
   ('Band saw','shop',1.5,0,0,1.5*0.1,8),
   ('Rotary-screw air compressor','shop',4.0,0,0,4.0*0.5,8),
   ('TIG/MIG welder','shop',6.0,0,0,6.0*0.2,8),
   ('Bench grinder, drill press, hand tools','shop',2.0,0,0,2.0*0.2,8)]
rows=[];E=0;peak=0
for t,s,kw,spec,m,idle,h in T:
    e=spec*m+idle*h;E+=e;peak+=kw
    rows.append(f"| {t} | {s} | {kw:.1f} | {spec} kWh/kg × {m:.2f} kg/d + {idle:.2f} kW × {h} h | {e:.1f} |")
avg=E/24; coinc=round(15+12+7.5+4.0,1)
out=f"""# MFG_SHOP tool list

Document number: AQS-MFG-010
Revision: A
Date: 2026-10-15
Authority: graph throughputs (MET_MELT, GAS_ATOMIZER, COLD_MILL, WIRE_DRAW); AQS-PLAN-007 X-ELS-02. Generated by `docs-authority/_mfg_tools.py`. Study values in AQS-REG-002.

One 8 h shift. Melt and atomizer run in batches; their energy is per kg. Shop tools at the stated utilisation.

| Tool | Serves | Nameplate kW | Energy basis | kWh/d |
| --- | --- | --- | --- | --- |
"""+"\n".join(rows)+f"""

Total {E:.1f} kWh/d = {avg:.2f} kW average (graph continuous_kw). Connected {peak:.1f} kW. Coincident peak {coinc} kW (melt + atomizer + CNC + compressor); the MCC-1 feeder is sized on this peak.
"""
open('docs-authority/MFG_TOOLS.md','w').write(out)
print(json.dumps(dict(avg=round(avg,2),peak=coinc,connected=peak)))
