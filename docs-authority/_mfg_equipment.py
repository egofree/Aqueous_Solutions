"""Write the two manufacturing equipment lists from the plant graph.

AQS-EQP-MFG-MET-001 (docs-authority/METAL_FORMING_EQUIPMENT.md): the metal-forming units of sector MFG (melt, forming,
air handling, scrubber and heat recovery classes) with their tools, streams, balances and separation checks.
AQS-EQP-MFG-001 (docs-authority/MFG_SHOP_EQUIPMENT.md): the other units of sector MFG (the shop, the blow molder and
the electrode coating booth) with the shop tool list, streams and balance.
Tool nameplates and daily energy come from docs-authority/_mfg_tools.py --json (AQS-MFG-010); every other value is
read from flow_graph/plant_flow_graph.json. Run: python3 docs-authority/_mfg_equipment.py
"""
import json, os, subprocess, sys
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, R); os.chdir(R)
SECTOR = 'MFG'
METAL_CLASSES = ('melt', 'forming', 'ahu', 'scrubber', 'hx')   # metal-forming page; the rest of the sector is the shop page
DATE = '2026-10-29'

g = json.load(open('flow_graph/plant_flow_graph.json')); N = {n['unit_id']: n for n in g['nodes']}
E = [e for e in g['edges'] if e.get('presence') != 'retired']
tools = json.loads(subprocess.run([sys.executable, 'docs-authority/_mfg_tools.py', '--json'], capture_output=True, text=True, check=True).stdout)
present = [u for u, n in N.items() if n.get('sector_id') == SECTOR and n.get('presence') == 'present']
METAL = [u for u in present if N[u].get('class') in METAL_CLASSES]
SHOP = [u for u in present if u not in METAL]

def kw(u):
    v = (N[u].get('continuous_kw') or {}).get('value'); return v if isinstance(v, (int, float)) else None
def rate(e):
    r = e.get('rate') or {}; return r.get('value'), r.get('unit')
def f(x, nd=2):
    return '—' if x is None else f'{x:.{nd}f}'
def _and(xs):
    xs = list(xs); return ', '.join(xs[:-1]) + ' and ' + xs[-1] if len(xs) > 1 else ''.join(xs)
def role(u):
    n = N[u]; s = n.get('notes') or ''
    return (s if isinstance(s, str) else '; '.join(map(str, s))).replace('|', '/').strip() or '—'
def touching(units):
    return [e for e in E if e['from_unit_id'] in units or e['to_unit_id'] in units]
def mass(u):
    i = sum(rate(e)[0] or 0 for e in E if e['to_unit_id'] == u and rate(e)[1] == 'kg/d')
    o = sum(rate(e)[0] or 0 for e in E if e['from_unit_id'] == u and rate(e)[1] == 'kg/d')
    return i, o
def stream_table(units, cap):
    L = [cap, '', '| Stream | From | To | Rate | Unit | Layers |', '| --- | --- | --- | --- | --- | --- |']
    for e in sorted(touching(units), key=lambda e: e['stream_id']):
        v, un = rate(e)
        L.append(f"| {e['stream_id']} | {e['from_unit_id']} | {e['to_unit_id']} | {'—' if v is None else f'{v:.4g}'} | {un or '—'} | {', '.join(e.get('layers') or [])} |")
    return L
def balance_table(units, cap):
    L = [cap, '', '| Unit | Mass in, kg/d | Mass out, kg/d | Out less in, kg/d |', '| --- | --- | --- | --- |']
    for u in units:
        i, o = mass(u)
        if i or o: L.append(f'| {u} | {i:.3f} | {o:.3f} | {o - i:.3f} |')
    return L
def idle(units):
    return sorted(e['stream_id'] for e in touching(units) if rate(e)[1] != 'kW' and not rate(e)[0])
def header(title, num, rev, rows, authority):
    return [f'# {title}', '', f'Document number: {num}  ', f'Revision: {rev}  ', f'Date: {DATE}  ', f'Authority: {authority}  ',
            'Generated by `docs-authority/_mfg_equipment.py` from the plant flow graph; do not edit this page by hand. This is a study, not a construction issue.  ',
            'Licence: CERN-OHL-S-2.0.', '', '| Rev | Description | Date |', '| --- | --- | --- |'] + rows + ['']

TM = {t['unit']: t for t in tools['metal']}
TOOL_BY_UNIT = {t['serves']: t for t in tools['tools'] if t['serves'] != 'shop'}

# ---------- metal forming ----------
src_melt = sorted({e['from_unit_id'] for e in E if e['to_unit_id'] == 'MET_MELT' and e['from_unit_id'] in N and rate(e)[1] == 'kg/d' and rate(e)[0]})
bad_melt = [u for u in src_melt if N[u].get('sector_id') in ('POLYMERS', 'OIL')]
ahu = [u for u in METAL if N[u].get('class') == 'ahu']; hx = [u for u in METAL if N[u].get('class') == 'hx']
ahu_out = sorted({e['to_unit_id'] for e in E if e['from_unit_id'] in ahu})
ahu_in = sorted({e['from_unit_id'] for e in E if e['to_unit_id'] in ahu})
hx_out = sorted({(e['to_unit_id'], tuple(e.get('layers') or [])) for e in E if e['from_unit_id'] in hx})
nokw = [u for u in METAL if kw(u) is None]
fan_cover = [u for u in METAL if N[u].get('class') == 'scrubber' and ((N[u].get('params') or {}).get('design') or {}).get('fan_W')]
id_m = idle(METAL)

md = header('Metal-forming equipment list', 'AQS-EQP-MFG-MET-001', 'E', [
    '| A | First issue: wire drawing, cold mill, gas atomiser, and the air handling and heat recovery tags. | 2026-09-28 |',
    '| B to D | Not recorded on the page; see the history of the file. | 2026-10-01 |',
    '| E | Generated from the plant graph. Revision D listed tags no longer on the graph (product bins, powder crib, nitrogen blanket, swarf collection, scrubber regenerator, shop air and the electrode blank station), quoted a nitrogen atomising gas where the tool list uses argon, gave load bands and left the tool sizes as TBD. The units, tools, streams and checks are now read from the graph and the tool list AQS-MFG-010. | 2026-10-29 |'],
    'the metal-forming units of sector MFG in `flow_graph/plant_flow_graph.json`; the tool list AQS-MFG-010; the vent and scrubber list AQS-EQP-VENT-001; the stream register AQS-STR-001.')
md += ['## 1. Purpose and scope', '',
       'This list gives the units that turn electrowon and remelted metal into wire, sheet and powder, the tools that do the work, the streams that join them to the rest of the plant, and checks of those streams against the separation rules. '
       'It covers the units of sector MFG in the melt, forming, air-handling, scrubber and heat-recovery classes. The shop, the blow molder and the electrode coating booth are in the shop equipment list AQS-EQP-MFG-001. Bulk melting is done by the foundry, not here.', '',
       '## 2. Terms', '',
       '- Average load: the continuous electrical load of a unit on the graph (`continuous_kw`), equal to its daily energy over 24 h.',
       '- Nameplate: the rated input of a tool, from the tool list AQS-MFG-010.',
       '- Stream: a graph edge, named by its stream identifier.', '',
       '## 3. Units', '',
       f'Table 3.1 lists the {len(METAL)} units. The role is the note on the graph node; the tool, nameplate and daily energy are from AQS-MFG-010.', '',
       'Table 3.1. Metal-forming units', '',
       '| Unit | Class | Role | Tool | Nameplate, kW | Energy, kWh/d | Average load, kW |', '| --- | --- | --- | --- | --- | --- | --- |']
for u in METAL:
    t = TOOL_BY_UNIT.get(u)
    md.append(f"| {u} | {N[u].get('class')} | {role(u)} | {t['tool'] if t else '—'} | {f(t['nameplate_kw'], 1) if t else '—'} | {f(t['kwh_d'], 1) if t else '—'} | {f(kw(u), 4)} |")
md += ['']
if nokw:
    md.append(f'{_and(nokw)} carry no electrical load on the graph. '
              + (f'The fan that moves the metal-aisle air is in the load of {_and(fan_cover)}.' if fan_cover and ahu else '') )
    md.append('')
md += ['## 4. Streams', '', 'Table 4.1 lists every present stream into or out of these units.', ''] + stream_table(METAL, 'Table 4.1. Streams of the metal-forming units') + ['']
if id_m:
    md += [f'The streams {_and(id_m)} carry no flow on the present graph.', '']
md += ['## 5. Mass balance', '', 'Table 5.1 sums the mass streams of each unit. The air handler and the scrubber circulate the aisle air, so their streams are large against the metal streams.', '']
md += balance_table(METAL, 'Table 5.1. Mass in and out of each unit') + ['']
md += ['## 6. Separation checks', '', 'The separation rules of the hazard separation register AQS-HSE-001 are checked against the graph as follows.', '',
       f"- The melt furnace MET_MELT takes mass only from {_and(src_melt)}. "
       + ('No polymer or oil unit feeds it.' if not bad_melt else f'{_and(bad_melt)} is a polymer or oil unit, which breaks the rule; this is an open item.'),
       f"- The air handler {_and(ahu)} sends air only to {_and(ahu_out)} and takes it back only from {_and(ahu_in)}. "
       + ('It shares no return with the habitation or the farm.' if not set(ahu_out + ahu_in) & {'HABITATION', 'HAB_AHU', 'GROW_BED'} else 'It shares a return with the habitation or the farm, which breaks the rule; this is an open item.'),
       f"- The heat recovery exchanger {_and(hx)} sends " + _and([f"{'thermal' if 'thermal' in l else '/'.join(l)} duty to {t}" for t, l in hx_out]) + '. '
       + ('No flue or melt gas goes to the Q4 header.' if all(l == ('thermal',) for _, l in hx_out) else 'A stream other than heat leaves it, which must be checked.'), '']
md += ['## 7. Open items', '',
       '- The tool list sizes each tool from its energy per kilogram and gives its nameplate. The die schedule of the wire drawer, the gauge and width range of the cold mill, and the batch rate of the atomiser are not yet designed. They are recorded as an owner question in `REWRITE_TODO.md`.',
       '- The efficiencies, the flow stress and the atomising gas ratio in AQS-MFG-010 are assumptions until trial runs are made (A-M-177).']
if id_m:
    md.append('- The streams without flow in Section 4 are routes kept on the graph for later use; each needs a rate or a decision to retire it.')
md += ['', '## 8. Drawings', '',
       'The process flow diagram of these units is the sector view `flow_graph/views/pfd-mfg.svg`, which the regenerator draws from the graph with every mass stream that has an end in the sector. '
       'The units also appear in the plant view `flow_graph/views/pfd.svg`.', '']
open('docs-authority/METAL_FORMING_EQUIPMENT.md', 'w').write('\n'.join(md))

# ---------- shop ----------
shop_tools = [t for t in tools['tools'] if t['serves'] == 'shop']
shop_unit = [u for u in SHOP if N[u].get('class') == 'shop']
id_s = idle(SHOP)
md = header('Manufacturing shop equipment list', 'AQS-EQP-MFG-001', 'E', [
    '| A | Named machines at the massing level. | 2026-09-27 |',
    '| B | Metal forming pointed to its own list and streams. | 2026-09-28 |',
    '| C | Blow molder added to the minimum viable system (project decision 2026-10-01); electrode coating pointer. | 2026-10-01 |',
    '| D | Blow molder average and peak load set; industrial machine loads excluded as continuous load. | 2026-10-01 |',
    '| E | Generated from the plant graph. Revision D listed tags no longer on the graph (the stock crib and the work floor), named a polymer machine line that the polymers line now covers, and quoted load bands. The units, tools, streams and balance are now read from the graph and the tool list AQS-MFG-010. | 2026-10-29 |'],
    'the units of sector MFG in `flow_graph/plant_flow_graph.json` other than the metal-forming units; the tool list AQS-MFG-010; the stream register AQS-STR-001.')
md += ['## 1. Purpose and scope', '',
       'This list gives the manufacturing shop and the small production units beside it, the shop machine tools, the streams that join them to the rest of the plant, and their mass balance. '
       'The metal-forming units are in AQS-EQP-MFG-MET-001. The polymer units that make pellet, resin, film and stock are in the polymers line, `docs-authority/sizing/POLYMERS_LINE.md`.', '',
       '## 2. Terms', '',
       '- Average load: the continuous electrical load of a unit on the graph (`continuous_kw`), equal to its daily energy over 24 h.',
       '- Connected load: the sum of the nameplates of the tools.',
       '- Coincident peak: the load when the tools that run together are all on, from AQS-MFG-010.', '',
       '## 3. Units', '', f'Table 3.1 lists the {len(SHOP)} units. The role is the note on the graph node.', '',
       'Table 3.1. Shop units', '', '| Unit | Class | Role | Equipment | Average load, kW |', '| --- | --- | --- | --- | --- |']
for u in SHOP:
    p = N[u].get('params') or {}; eq = p.get('equipment_id') or ((p.get('design') or {}).get('machine')) or '—'
    if p.get('equipment_id') and (p.get('design') or {}).get('machine'): eq = f"{p['equipment_id']}, {p['design']['machine']}"
    md.append(f"| {u} | {N[u].get('class')} | {role(u)} | {eq} | {f(kw(u), 4)} |")
md += ['', '## 4. Shop machine tools', '',
       f"Table 4.1 lists the machine tools of the shop from AQS-MFG-010. Their average load is {f(tools['shop_avg'], 2)} kW, which is the load of {_and(shop_unit)} on the graph"
       + (' (they agree).' if shop_unit and kw(shop_unit[0]) is not None and abs(kw(shop_unit[0]) - tools['shop_avg']) < 0.005 else f" ({f(kw(shop_unit[0]) if shop_unit else None, 2)} kW on the graph; the two differ and must be reconciled)."), '',
       'Table 4.1. Shop machine tools', '', '| Tool | Nameplate, kW | Energy, kWh/d |', '| --- | --- | --- |']
md += [f"| {t['tool']} | {f(t['nameplate_kw'], 1)} | {f(t['kwh_d'], 1)} |" for t in shop_tools]
md += ['', f"The connected load of the shop tools is {f(tools['shop_connected'], 1)} kW. With the metal tools of AQS-EQP-MFG-MET-001, the whole tool list has a connected load of {f(tools['connected'], 1)} kW and a coincident peak of {f(tools['peak'], 1)} kW, which size the feeder to MCC-1.", '']
md += ['## 5. Streams', '', 'Table 5.1 lists every present stream into or out of these units.', ''] + stream_table(SHOP, 'Table 5.1. Streams of the shop units') + ['']
if id_s:
    md += [f'The streams {_and(id_s)} have no rate on the present graph.', '']
md += ['## 6. Mass balance', '', 'Table 6.1 sums the mass streams of each unit.', ''] + balance_table(SHOP, 'Table 6.1. Mass in and out of each unit') + ['']
bad = [(u, *mass(u)) for u in SHOP if any(mass(u)) and abs(mass(u)[1] - mass(u)[0]) > max(0.01, 0.001 * max(mass(u)))]
md += [('Each unit closes its mass balance within 0.1 %.' if not bad else 'The balance of ' + _and([f'{u} ({o - i:+.3f} kg/d)' for u, i, o in bad]) + ' does not close; the difference must be traced on the graph.'), '']
md += ['## 7. Open items', '']
md += ([f'- The streams without a rate in Section 5 need a rate or a decision to retire them.'] if id_s else [])
md += ['- The shop tools keep their study nameplates and utilisation until the tools are chosen (A-M-177).', '',
       '## 8. Drawings', '',
       'The process flow diagram of these units is the sector view `flow_graph/views/pfd-mfg.svg`, which the regenerator draws from the graph with every mass stream that has an end in the sector. '
       'The units also appear in the plant view `flow_graph/views/pfd.svg`.', '']
open('docs-authority/MFG_SHOP_EQUIPMENT.md', 'w').write('\n'.join(md))
print('docs-authority/METAL_FORMING_EQUIPMENT.md and docs-authority/MFG_SHOP_EQUIPMENT.md written')
