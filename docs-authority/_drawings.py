"""X-DWG-01/02/03 drawing standard applied: title block on every SVG drawing and the drawing register (AQS-DWG-002).
Title block fields per ISO_7200 (owner, number, title, revision, date, type, creator, approval, sheet); revision index is the first 8 hex of
the SHA-256 of the drawing content without the title block, so it changes exactly when the drawing changes (ASME_Y14_35 intent). The graph
views (PFD/MFD/EFD) also carry the SHA-256 of the graph they were generated from (X-DWG-03). Run: python3 docs-authority/_drawings.py"""
import glob, hashlib, json, os, re, subprocess
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TB = re.compile(r'\n?<g id="aqs-title-block".*?</g>\n?', re.S)
DATE = '2026-10-15'
FOREIGN_ROWS = ('| AQS-PID-',)   # register rows appended by other generators (pid_sheets)
FOREIGN_NOTES = ('The AQS-PID-001 series',)   # their provenance note, kept with them
def files():
    out = []
    for f in sorted(glob.glob(os.path.join(R, 'flow_graph/views/*.svg'))):
        b = os.path.basename(f)[:-4]; out.append((f, f'AQS-DWG-PFD-{b.upper()}', {'pfd': 'Process flow diagram', 'mfd': 'Mass flow diagram', 'efd-elec': 'Electrical flow diagram',
                    'efd-ess': 'Energy storage flow diagram', 'efd-thermal': 'Thermal flow diagram'}.get(b, b), 'flow diagram (ISO_10628_2)', True))
    for f in sorted(glob.glob(os.path.join(R, 'docs-authority/iso/*.svg'))):
        b = os.path.basename(f)[:-4]; out.append((f, f'AQS-ISO-002-{b}', f'Piping isometric {b}', 'piping isometric', False))
    for f in sorted(glob.glob(os.path.join(R, 'models/motors/*/export/*.svg'))):
        mf = f.split('/')[-3]; out.append((f, f'AQS-INV-005-{mf}', f'Motor family {mf} assembly', 'assembly drawing', False))
    # AQS-PLAN-006 W7 fabrication drawing sets (GA / nozzle orientation / part sheets per accepted
    # model). The title carries the graph revision - the model source (models/mfg/<unit>/params.json)
    # is the authority, so from_graph stays False (the content-hash revision governs per ASME_Y14_35).
    for f in sorted(glob.glob(os.path.join(R, 'models/mfg/*/drawings/*.svg'))):
        p = f.split(os.sep); mf = p[-3]; b = os.path.basename(f)[:-4].upper()
        out.append((f, f'AQS-MFG-{mf}-{b}', f'{mf} fabrication drawing {b} (AQS-PLAN-006 M3; graph revision AC)',
                    'fabrication drawing (GA / nozzle orientation / part sheet)', False))
    return out
def box(svg):
    m = re.search(r'viewBox="([-0-9.]+)[ ,]+([-0-9.]+)[ ,]+([-0-9.]+)[ ,]+([-0-9.]+)"', svg)
    if m: return tuple(float(x) for x in m.groups())
    w = re.search(r'<svg[^>]*width="([0-9.]+)', svg); h = re.search(r'<svg[^>]*height="([0-9.]+)', svg)
    return 0.0, 0.0, float(w.group(1)) if w else 800.0, float(h.group(1)) if h else 600.0
def stamp(path, number, title, kind, graph_sha):
    svg = TB.sub('', open(path).read()); rev = hashlib.sha256(svg.encode()).hexdigest()[:8]
    x0, y0, W, H = box(svg); s = max(0.6, min(W, H)/900); w, h = 360*s, 96*s; x, y = x0 + W - w - 4*s, y0 + H - h - 4*s; f = 9*s
    rows = [f'Aqueous Solutions (owner)   {number}', title[:60], f'Type: {kind}   Rev {rev}   Issued {DATE}',
            'Created: flow graph pipeline   Approved: not approved (study)', (f'Graph SHA-256 {graph_sha[:16]}   ' if graph_sha else '') + 'Sheet 1 of 1   AQS-DWG-001']
    t = ''.join(f'<text x="{x + 6*s:.1f}" y="{y + (16 + 17*i)*s:.1f}" font-family="sans-serif" font-size="{f:.1f}">{r.replace("&", "&amp;").replace("<", "&lt;")}</text>' for i, r in enumerate(rows))
    g = f'\n<g id="aqs-title-block"><rect x="{x:.1f}" y="{y:.1f}" width="{w:.1f}" height="{h:.1f}" fill="white" stroke="black" stroke-width="{s:.2f}"/>{t}</g>\n'
    i = svg.rfind('</svg>'); open(path, 'w').write(svg[:i] + g + svg[i:]); return rev
def main():
    gsha = hashlib.sha256(open(os.path.join(R, 'flow_graph/plant_flow_graph.json'), 'rb').read()).hexdigest()
    reg = []
    for f, num, title, kind, from_graph in files():
        rev = stamp(f, num, title, kind, gsha if from_graph else None); reg.append((num, title, kind, rev, os.path.relpath(f, R)))
    for f in sorted(glob.glob(os.path.join(R, 'models/mfg/*/export/*.step'))):
        u = f.split('/')[-3]; reg.append((f'AQS-MFG-{u}', f'{u} fabrication model (STEP, model-based definition)', '3D model', 'git', os.path.relpath(f, R)))
    for f in sorted(glob.glob(os.path.join(R, 'media/pfd/*.png'))):
        reg.append((f'AQS-PFD-IMG-{os.path.basename(f)[:-8].upper()}', os.path.basename(f), 'sector PFD image (no title block, raster)', 'graph', os.path.relpath(f, R)))
    md = ['# Drawing register', '', 'Document number: AQS-DWG-002', 'Revision: A', f'Date: {DATE}',
          'Authority: AQS-PLAN-007 X-DWG-02 under the drawing standard AQS-DWG-001. Generated by `docs-authority/_drawings.py`. Study.', '',
          f'{len(reg)} drawings. Revision for SVG drawings is the content hash in the title block (AQS-DWG-001 section 4); "git" is the file history; "graph" is the graph manifest (media/_generated.json).', '',
          '| Number | Title | Type | Revision | File |', '|---|---|---|---|---|']
    md += [f'| {a} | {b} | {c} | {d} | {e} |' for a, b, c, d, e in reg]
    # Rows of series owned by other generators (P&ID sheets, docs-authority/_pid_sheets.py) are kept
    # as they are, so the register is the same whichever of the two generators ran last.
    rp = os.path.join(R, 'docs-authority/DRAWING_REGISTER.md')
    old = open(rp).read().splitlines() if os.path.exists(rp) else []
    kept = [l for l in old if l.startswith(FOREIGN_ROWS)]
    notes = [l for l in old if l.startswith(FOREIGN_NOTES)]
    md = [re.sub(r'^\d+ drawings\.', f'{len(reg) + len(kept)} drawings.', l) for l in md]
    i = md.index('| Number | Title | Type | Revision | File |')
    md = md[:i - 1] + notes + md[i - 1:]          # same place _pid_sheets.py puts it: under the count line
    open(rp, 'w').write('\n'.join(md + kept) + '\n'); print(len(reg) + len(kept), 'drawings;', len(kept), 'rows kept from other series')
if __name__ == '__main__': main()
