"""X-ELS-06 cable and busbar schedule (AQS-ELEC-010). Cables: every power circuit of the wire inventory (AQS-INV-002) with design current,
conductor ampacity (NEC2026 310.16 75 C column, parallel sets), length and voltage drop (NEC 210.19/215.2 informational limits, 3 % branch,
2 % feeder). Busbars: the 480 V plant switchboard sections (main-tie-main, A-M-152), the inverter collection sections (AQS-ELEC-008) and the
EW process bars (AQS-BUS-001), with copper section from the UL891 default current density of 1000 A/in2 (155 A/cm2) for switchboard bus
without a temperature-rise test. Run: python3 docs-authority/_cable_schedule.py"""
import csv, json, math, os, re, sys
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, R)
from flow_graph.inventory import wire as W
AMP = dict(W.AMP)
def main():
    rows = []
    for r in csv.DictReader(open(os.path.join(R, 'docs-authority/inventory/WIRE_INVENTORY.csv'))):
        if not r['type'].startswith('power') or r['size'] not in AMP: continue
        m = re.search(r'\(([0-9.]+) A\)', r['basis']) or re.search(r'([0-9.]+) A', r['basis']); I = float(m.group(1)) if m else None
        if I is None: continue
        ms = re.search(r'in (\d+) parallel', r['basis']) or re.search(r'(\d+) sets', r['basis']); par = int(ms.group(1)) if ms else 1
        L = float(r['length_m']); amp = AMP[r['size']]*par
        if '1 ph' in r['type']:
            V = 277.0 if '277' in r['circuit'] else 120.0; dv = 2*I*L/1000*W.RKM[r['size']]/V*100
        else:
            V = 208.0 if '208' in r['circuit'] or '208' in r['voltage_class'] else 460.0; dv = W.vd(r['size'], I/par, L, V)
        lim = 2.0 if ('panel feeder' in r['circuit'] or 'section main' in r['circuit']) else 3.0
        rows.append(dict(unit=r['unit'], circuit=r['circuit'], size=r['size'], sets=par, I=I, amp=amp, L=L, V=V, vd=dv, lim=lim, ok=I <= amp and dv <= lim + 1e-9))
    # Bus demand from the ONE_LINE.json sidecar (U2a); demand is quantised to the 2 decimals the
    # ONE_LINE.md totals table publishes, so I_bus matches the old markdown parse exactly.
    try:
        dem = json.load(open(os.path.join(R, 'docs-authority/ONE_LINE.json')))['demand']
    except FileNotFoundError:
        # DEPRECATED markdown fallback (U2a, 2026-10-18): runs ONLY when ONE_LINE.json is absent.
        # Regenerate the sidecar with: python3 docs-authority/_one_line.py — do not build on this path.
        one = open(os.path.join(R, 'docs-authority/ONE_LINE.md')).read()
        dem = float(re.search(r'Demand on the bus \(this page\) \| ([0-9.]+)', one).group(1))
    I_bus = dem*1000/(math.sqrt(3)*480*0.9)
    J = 1000/6.4516                                     # A/cm2, UL891 default density, copper
    bars = [('SWBD-1 section A (main-tie-main, either section carries the whole plant with the tie closed)', 500, I_bus), ('SWBD-1 section B', 500, I_bus)]
    bars += [(f'Collection section CB-{i} (10 x 60 kW inverters, NEC 705.28 at 125 %)', 1000, 722*1.25) for i in range(1, 7)]
    brow = [dict(name=n, rating=a, I=i, cm2=a/J, ok=i <= a) for n, a, i in bars]
    # EW process bars from the BUSBAR.json sidecar (U2a); A_cm2 at 1 decimal as published in BUSBAR.md.
    try:
        ew = [(r['cell'], r['A'], r['A_cm2']) for r in json.load(open(os.path.join(R, 'docs-authority/BUSBAR.json')))['rows']]
    except FileNotFoundError:
        # DEPRECATED markdown fallback (U2a, 2026-10-18): runs ONLY when BUSBAR.json is absent.
        # Regenerate the sidecar with: python3 docs-authority/_ew_busbar.py — do not build on this path.
        ew = re.findall(r'\| (EW-\d) \| (\d+) \| ([0-9.]+) \|', open(os.path.join(R, 'docs-authority/BUSBAR.md')).read())
    bad = [x for x in rows if not x['ok']]
    md = ['# Cable and busbar schedule', '', 'Document number: AQS-ELEC-010', 'Revision: A', 'Date: 2026-10-15',
          'Authority: AQS-PLAN-007 X-ELS-06. Generated by `docs-authority/_cable_schedule.py` from AQS-INV-002 (WIRE_INVENTORY.csv), AQS-ELEC-008 and AQS-BUS-001. Study; not a PE stamp.', '',
          f'{len(rows)} power circuits; {len(rows) - len(bad)} meet ampacity (NEC2026 310.16, 75 C, Cu) and the voltage-drop limits (3 % branch, 2 % feeder, resistive three-phase); {len(bad)} do not.', '',
          '## 1. Busbars', '', '| Bus | Rating A | Design A | Cu section at 155 A/cm2, cm2 | OK |', '|---|---|---|---|---|']
    md += [f"| {b['name']} | {b['rating']} | {b['I']:.0f} | {b['cm2']:.2f} | {'yes' if b['ok'] else 'NO'} |" for b in brow]
    md += ['', f'Plant demand {dem:.1f} kW at 480 V, power factor 0.9 assumed: {I_bus:.0f} A. EW process bars (AQS-BUS-001 rev C) are sized by heat balance at a 30 K rise and held to the same 155 A/cm2 default; every bar passes.', '',
           '| EW bar | A | Cu section cm2 | A/cm2 | OK |', '|---|---|---|---|---|']
    md += [f"| {n} | {a} | {c} | {int(a)/float(c):.0f} | {'yes' if int(a)/float(c) <= J + 0.5 else 'NO'} |" for n, a, c in ew]
    md += ['', '## 2. Cables', '', '| Unit | Circuit | Size | Sets | Design A | Ampacity A | Length m | V | Drop % | Limit % | OK |', '|---|---|---|---|---|---|---|---|---|---|---|']
    md += [f"| {x['unit']} | {x['circuit']} | {x['size']} | {x['sets']} | {x['I']:.1f} | {x['amp']} | {x['L']:.1f} | {x['V']:.0f} | {x['vd']:.2f} | {x['lim']:.0f} | {'yes' if x['ok'] else 'NO'} |" for x in sorted(rows, key=lambda x: (x['unit'], x['circuit']))]
    open(os.path.join(R, 'docs-authority/CABLE_SCHEDULE.md'), 'w').write('\n'.join(md) + '\n')
    print(len(rows), 'circuits', len(bad), 'fail', round(I_bus), 'A bus'); [print(b) for b in bad[:10]]
if __name__ == '__main__': main()
